#!/usr/bin/env node
// Install the Blender-built police helicopter as the runtime asset.
//
//   node artifacts/vehicles/sf-police-helicopter-v1/install_runtime.mjs
//
// Run after build_police_helicopter.py. Copies out/sf-police-helicopter-v1.glb
// to public/assets/vehicles/police-helicopter-v1/, writes its provenance beside
// it, and regenerates src/vehicles/police-helicopter-manifest.js with the
// SHA-256 the runtime verifies before it parses the GLB. Never hand-edit the
// digest: rebuild and rerun this.
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..', '..');
const NAME = 'sf-police-helicopter-v1';
const SOURCE = join(HERE, 'out', `${NAME}.glb`);
const REPORT = join(HERE, 'out', 'build-report.json');
const DEST_DIR = join(REPO, 'public', 'assets', 'vehicles', 'police-helicopter-v1');
const DEST = join(DEST_DIR, `${NAME}.glb`);
const MANIFEST = join(REPO, 'src', 'vehicles', 'police-helicopter-manifest.js');

const bytes = readFileSync(SOURCE);
const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
if (view.getUint32(0, true) !== 0x46546c67 || view.getUint32(4, true) !== 2) throw new Error(`${SOURCE} is not a glTF 2 binary`);
const json = JSON.parse(new TextDecoder().decode(bytes.subarray(20, 20 + view.getUint32(12, true))));
if ([...(json.buffers || []), ...(json.images || [])].some((r) => r.uri)) throw new Error('every resource must be embedded');
const names = new Set((json.nodes || []).map((n) => n.name));
for (const required of ['MainRotor', 'TailRotor', 'Searchlight', 'Light_Beacon_Top', 'Light_Beacon_Belly', 'Light_Nav_L', 'Light_Nav_R', 'Light_Strobe_Tail']) {
  if (!names.has(required)) throw new Error(`node ${required} missing from ${SOURCE}`);
}
const sha256 = createHash('sha256').update(bytes).digest('hex');
const report = JSON.parse(readFileSync(REPORT, 'utf8'));

mkdirSync(DEST_DIR, { recursive: true });
copyFileSync(SOURCE, DEST);
const url = `/assets/vehicles/police-helicopter-v1/${NAME}.glb`;
writeFileSync(join(DEST_DIR, 'provenance.json'), `${JSON.stringify({
  asset: NAME,
  url,
  sha256,
  bytes: bytes.byteLength,
  method: report.method,
  builder: relative(REPO, join(HERE, 'build_police_helicopter.py')),
  installer: relative(REPO, join(HERE, 'install_runtime.mjs')),
  blender: report.blender,
  triangles: report.triangles,
  meshObjects: report.mesh_objects,
  dimensionsM: report.dimensions_m?.size,
  mainRotorDiameterM: report.main_rotor_diameter_m,
  namedNodes: report.named_nodes,
  license: 'original work authored for EarthOnline',
}, null, 2)}\n`);
writeFileSync(MANIFEST, `// GENERATED by artifacts/vehicles/sf-police-helicopter-v1/install_runtime.mjs - do not edit by hand.
// SHA-256 allowlist for the police helicopter body (AGENTS.md: a production GLB is
// verified before it is parsed). Rebuild in Blender and rerun the installer to change it.
export const POLICE_HELICOPTER_ASSET = Object.freeze({
  url: ${JSON.stringify(url)},
  sha256: ${JSON.stringify(sha256)},
  bytes: ${bytes.byteLength},
  triangles: ${Number(report.triangles) || 0},
  mainRotorRadiusM: ${(Number(report.main_rotor_diameter_m) || 10.36) / 2},
});
`);
console.log(JSON.stringify({ dest: relative(REPO, DEST), sha256, bytes: bytes.byteLength, manifest: relative(REPO, MANIFEST) }));
