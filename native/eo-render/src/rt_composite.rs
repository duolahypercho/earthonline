//! The ray-traced passes' thin G-buffer and their deferred composite (stage
//! R2, shared by `--rt-gi` and `--rt-reflect` from stage R3).
//!
//! With either option the city's opaque pass writes, beside its colour, what
//! the rig's indirect terms contributed and what they were multiplied by
//! (rt_gi_use.wgsl; the hook in look_light.wgsl records it, the colour is
//! the frame without the options): the indirect diffuse (`GSlot::A`, `B`),
//! the vertex normal and coverage (`N`), the environment reflection (`C`,
//! `D`). The traces read the normal and the specular lobe; this pass adds
//! the difference between the traced and the rig's terms in the same frame
//! (rt_composite.wgsl), then the rest of the city pass (the far layer,
//! trees, props, agents, the far shore, the sky, the glass) draws over it
//! (lib.rs).
//!
//! The G-buffer holds only what the options use (`gbuffer_layout`); without
//! either, the shader text, the layouts and every pass are as before.

use crate::lighting;

/// A G-buffer value (rt_gi_use.wgsl): `A` the indirect diffuse added and the
/// environment's class; `B` what multiplies an irradiance, the screen-space
/// visibility; `N` the vertex normal, coverage; `C` the environment
/// reflection added, the roughness; `D` what multiplies a reflected radiance,
/// the environment's class.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GSlot {
    A,
    B,
    N,
    C,
    D,
}

impl GSlot {
    fn name(self) -> &'static str {
        match self {
            GSlot::A => "a",
            GSlot::B => "b",
            GSlot::N => "n",
            GSlot::C => "c",
            GSlot::D => "d",
        }
    }
}

/// The G-buffer's targets in attachment order (after the colour): the
/// diffuse light's A, B; the normal N with either; the reflection's C, D.
pub fn gbuffer_layout(gi: bool, refl: bool) -> Vec<(GSlot, wgpu::TextureFormat)> {
    let f16 = wgpu::TextureFormat::Rgba16Float;
    let mut v = vec![];
    if gi {
        v.push((GSlot::A, f16));
        v.push((GSlot::B, f16));
    }
    if gi || refl {
        v.push((GSlot::N, wgpu::TextureFormat::Rgb10a2Unorm));
    }
    if refl {
        v.push((GSlot::C, f16));
        v.push((GSlot::D, f16));
    }
    v
}

/// The comment in look_light.wgsl the hook replaces.
pub const HOOK_MARKER: &str = "    // RT_GI_HOOK";

/// The hook look_light.wgsl gets with an option (before its return): the
/// G-buffer's values (rt_gi_use.wgsl) as they reach the colour: after the
/// glass's and the car paint's coats (their base attenuation, as their
/// blocks above apply it) and the fog; a thin pane's colour has no diffuse
/// and its reflection is not under its coat. The colour is not touched.
const HOOK: &str = r#"    // (`--rt-gi`, `--rt-reflect`; rt_composite.rs) the thin G-buffer
    // (rt_gi_use.wgsl): the indirect diffuse and the environment reflection
    // as they reach the colour, what multiplies them on their way there, the
    // environment's class, the screen-space visibility, the roughness, the
    // vertex normal. Never in the probe pass.
    if (frame.copy_step.z < 0.5) {
        let rg_fv = 0.04 + 0.96 * pow(1.0 - max(dot(ng, v), 1e-4), 5.0);
        var rg_keep = 1.0 - fog;
        if (glass && m.emissive.w > 0.0) {
            rg_keep = rg_keep * (1.0 - m.emissive.w * rg_fv);
        }
        if (coat_on) {
            rg_keep = rg_keep * (1.0 - sky_coat * rg_fv);
        }
        var rg_keep_s = rg_keep;
        if (glass && (m.flags & F_THIN_GLASS) != 0u) {
            rg_keep = 0.0;
            rg_keep_s = 1.0 - fog;
        }
        rtg_a = vec4<f32>((indirect_d + bounce) * rg_keep, env_i);
        rtg_b = vec4<f32>(diffuse / LK_PI * (vec3<f32>(1.0) - fss) * s.ao * rg_keep, ao4.a);
        rtg_n = vec4<f32>(normalize(ng) * 0.5 + 0.5, 1.0);
        rtg_c = vec4<f32>(indirect_s * rg_keep_s, rough);
        rtg_d = vec4<f32>(fss * spec_occ * rg_keep_s, env_i);
    }"#;

/// look_light.wgsl with the hook spliced in (an option on) or as it is.
pub fn splice_look_light(src: &str, on: bool) -> String {
    if !on {
        return src.to_string();
    }
    assert!(src.contains(HOOK_MARKER), "look_light.wgsl lost its RT_GI_HOOK marker");
    // diagnostic (frame cost): the G-buffer's outputs composed, the hook not spliced.
    if std::env::var_os("EO_RT_GI_NO_HOOK").is_some_and(|v| v == "1") {
        return src.to_string();
    }
    src.replace(HOOK_MARKER, HOOK)
}

/// The city shader's G-buffer values and `fs_rtg` writing those the options
/// use (appended with an option).
pub fn use_wgsl(gi: bool, refl: bool) -> String {
    let layout = gbuffer_layout(gi, refl);
    let mut s = String::from(include_str!("rt_gi_use.wgsl"));
    s += "\n// generated by rt_composite.rs `use_wgsl`: the city's opaque pipeline with the\n// option (lib.rs `opaque_rt_pipeline`), `fs` and the G-buffer (zero where\n// `look_light` is not reached: a tunnel bore's own light; the composite leaves those).\nstruct RtgOut {\n    @location(0) color: vec4<f32>,\n";
    for (k, (slot, _)) in layout.iter().enumerate() {
        s += &format!("    @location({}) {}: vec4<f32>,\n", k + 1, slot.name());
    }
    s += "};\n\n@fragment\nfn fs_rtg(in: VOut) -> RtgOut {\n    rtg_a = vec4<f32>(0.0);\n    rtg_b = vec4<f32>(0.0);\n    rtg_n = vec4<f32>(0.0);\n    rtg_c = vec4<f32>(0.0);\n    rtg_d = vec4<f32>(0.0);\n    var out: RtgOut;\n    out.color = shade(in);\n";
    for (slot, _) in &layout {
        s += &format!("    out.{0} = rtg_{0};\n", slot.name());
    }
    s += "    return out;\n}\n";
    s
}

/// The composite's uniform (rt_composite.wgsl `RtCompositeView`).
#[repr(C)]
#[derive(Clone, Copy, Debug, bytemuck::Pod, bytemuck::Zeroable)]
pub struct RtCompositeView {
    pub gi: [f32; 4],
    pub refl: [f32; 4],
    pub size: [f32; 4],
    pub misc: [f32; 4],
}

/// A traced result the composite adds: its half-resolution view and view
/// depth, its weight, fade (m) and debug view; `keep` the diffuse light's
/// kept screen-space occlusion (unused by the reflection).
pub struct RtResult<'a> {
    pub result: &'a wgpu::TextureView,
    pub z: &'a wgpu::TextureView,
    pub weight: f32,
    pub fade: (f32, f32),
    pub keep: f32,
    pub debug: u32,
}

struct State {
    gbuf: Option<((u32, u32), Vec<wgpu::TextureView>)>,
    /// The bind group and what it was made over (the depth, the results' textures).
    bg: Option<((wgpu::Texture, Option<wgpu::Texture>, Option<wgpu::Texture>), wgpu::BindGroup)>,
}

/// The G-buffer and the composite (made with an option on a device with ray queries).
pub struct RtComposite {
    pub gi: bool,
    pub refl: bool,
    layout: Vec<(GSlot, wgpu::TextureFormat)>,
    device: wgpu::Device,
    queue: wgpu::Queue,
    look_buf: wgpu::Buffer,
    view_buf: wgpu::Buffer,
    bgl: wgpu::BindGroupLayout,
    add: wgpu::RenderPipeline,
    replace: wgpu::RenderPipeline,
    /// 1 x 1 stand-ins for what an option does not make (rgba16float, r32float).
    stand_in: (wgpu::TextureView, wgpu::TextureView),
    state: std::sync::Mutex<State>,
}

/// The composite's shader source.
pub fn shader_source() -> String {
    format!("{}\n{}", crate::look::look_common_source(), include_str!("rt_composite.wgsl"))
}

impl RtComposite {
    pub fn new(device: &wgpu::Device, queue: &wgpu::Queue, look_buf: &wgpu::Buffer, gi: bool, refl: bool) -> Self {
        let view_buf = device.create_buffer(&wgpu::BufferDescriptor { label: Some("rt-composite-view"), size: std::mem::size_of::<RtCompositeView>() as u64, usage: wgpu::BufferUsages::UNIFORM | wgpu::BufferUsages::COPY_DST, mapped_at_creation: false });
        let f = |binding, ty| wgpu::BindGroupLayoutEntry { binding, visibility: wgpu::ShaderStages::FRAGMENT, ty, count: None };
        let ubuf = wgpu::BindingType::Buffer { ty: wgpu::BufferBindingType::Uniform, has_dynamic_offset: false, min_binding_size: None };
        let tex = wgpu::BindingType::Texture { sample_type: wgpu::TextureSampleType::Float { filterable: false }, view_dimension: wgpu::TextureViewDimension::D2, multisampled: false };
        let depth_tex = wgpu::BindingType::Texture { sample_type: wgpu::TextureSampleType::Depth, view_dimension: wgpu::TextureViewDimension::D2, multisampled: false };
        let bgl = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("rt-composite-bgl"),
            entries: &[f(0, ubuf), f(1, ubuf), f(2, tex), f(3, tex), f(4, tex), f(5, depth_tex), f(6, tex), f(7, tex), f(8, tex), f(9, tex), f(10, tex), f(11, tex)],
        });
        let module = device.create_shader_module(wgpu::ShaderModuleDescriptor { label: Some("rt_composite.wgsl"), source: wgpu::ShaderSource::Wgsl(shader_source().into()) });
        let layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor { label: Some("rt-composite"), bind_group_layouts: &[Some(&bgl)], immediate_size: 0 });
        let pipe = |label: &str, blend: Option<wgpu::BlendState>| {
            device.create_render_pipeline(&wgpu::RenderPipelineDescriptor {
                label: Some(label),
                layout: Some(&layout),
                vertex: wgpu::VertexState { module: &module, entry_point: Some("rc_vs"), compilation_options: Default::default(), buffers: &[] },
                primitive: wgpu::PrimitiveState::default(),
                depth_stencil: None,
                multisample: wgpu::MultisampleState::default(),
                fragment: Some(wgpu::FragmentState { module: &module, entry_point: Some("rc_fs"), compilation_options: Default::default(), targets: &[Some(wgpu::ColorTargetState { format: crate::look::HDR_FORMAT, blend, write_mask: wgpu::ColorWrites::ALL })] }),
                multiview_mask: None,
                cache: None,
            })
        };
        let add = pipe(
            "rt-composite-add",
            Some(wgpu::BlendState {
                color: wgpu::BlendComponent { src_factor: wgpu::BlendFactor::One, dst_factor: wgpu::BlendFactor::One, operation: wgpu::BlendOperation::Add },
                alpha: wgpu::BlendComponent { src_factor: wgpu::BlendFactor::Zero, dst_factor: wgpu::BlendFactor::One, operation: wgpu::BlendOperation::Add },
            }),
        );
        let replace = pipe("rt-composite-debug", None);
        let one = |label: &str, format| {
            device
                .create_texture(&wgpu::TextureDescriptor { label: Some(label), size: wgpu::Extent3d { width: 1, height: 1, depth_or_array_layers: 1 }, mip_level_count: 1, sample_count: 1, dimension: wgpu::TextureDimension::D2, format, usage: wgpu::TextureUsages::TEXTURE_BINDING, view_formats: &[] })
                .create_view(&Default::default())
        };
        let stand_in = (one("rt-stand-in", wgpu::TextureFormat::Rgba16Float), one("rt-stand-in-z", wgpu::TextureFormat::R32Float));
        Self {
            gi,
            refl,
            layout: gbuffer_layout(gi, refl),
            device: device.clone(),
            queue: queue.clone(),
            look_buf: look_buf.clone(),
            view_buf,
            bgl,
            add,
            replace,
            stand_in,
            state: std::sync::Mutex::new(State { gbuf: None, bg: None }),
        }
    }

    /// The G-buffer's formats in attachment order (the city's `opaque_rt_pipeline`).
    pub fn formats(&self) -> Vec<wgpu::TextureFormat> {
        self.layout.iter().map(|(_, f)| *f).collect()
    }

    /// The G-buffer's views for an output of `size` (made or remade here), in
    /// attachment order.
    pub fn gbuffer_views(&self, size: (u32, u32)) -> Vec<wgpu::TextureView> {
        let mut st = self.state.lock().unwrap();
        if st.gbuf.as_ref().map(|g| g.0) != Some(size) {
            let views = self
                .layout
                .iter()
                .map(|(slot, format)| {
                    self.device
                        .create_texture(&wgpu::TextureDescriptor {
                            label: Some(&format!("rt-gbuffer-{}", slot.name())),
                            size: wgpu::Extent3d { width: size.0, height: size.1, depth_or_array_layers: 1 },
                            mip_level_count: 1,
                            sample_count: 1,
                            dimension: wgpu::TextureDimension::D2,
                            format: *format,
                            usage: wgpu::TextureUsages::RENDER_ATTACHMENT | wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::COPY_SRC,
                            view_formats: &[],
                        })
                        .create_view(&Default::default())
                })
                .collect();
            st.gbuf = Some((size, views));
            st.bg = None;
        }
        st.gbuf.as_ref().unwrap().1.clone()
    }

    /// A G-buffer value's view (once made).
    pub fn view(&self, slot: GSlot) -> Option<wgpu::TextureView> {
        let st = self.state.lock().unwrap();
        let k = self.layout.iter().position(|(s, _)| *s == slot)?;
        st.gbuf.as_ref().map(|g| g.1[k].clone())
    }

    /// Bytes of the G-buffer (once made).
    pub fn bytes(&self) -> u64 {
        let st = self.state.lock().unwrap();
        let per: u64 = self.layout.iter().map(|(_, f)| if *f == wgpu::TextureFormat::Rgba16Float { 8 } else { 4 }).sum();
        st.gbuf.as_ref().map(|g| g.0 .0 as u64 * g.0 .1 as u64 * per).unwrap_or(0)
    }

    /// The composite into `hdr` of what was traced this frame (nothing when
    /// neither result is given). Its timestamps are `lighting::Q_RT_COMPOSITE`.
    pub fn encode(&self, enc: &mut wgpu::CommandEncoder, depth: &wgpu::TextureView, hdr: &wgpu::TextureView, gi: Option<RtResult>, refl: Option<RtResult>, ts: lighting::Ts<'_>) {
        if gi.is_none() && refl.is_none() {
            lighting::empty_span(enc, ts, lighting::Q_RT_COMPOSITE, "rt-composite (idle)");
            return;
        }
        let dt = depth.texture();
        let mut st = self.state.lock().unwrap();
        let Some((size, gb)) = st.gbuf.clone() else {
            lighting::empty_span(enc, ts, lighting::Q_RT_COMPOSITE, "rt-composite (no G-buffer)");
            return;
        };
        let key = (dt.clone(), gi.as_ref().map(|r| r.result.texture().clone()), refl.as_ref().map(|r| r.result.texture().clone()));
        if st.bg.as_ref().is_none_or(|(k, _)| *k != key) {
            crate::hitch::mark(crate::hitch::Mark::BindGroupCreated, 1);
            let at = |slot: GSlot| self.layout.iter().position(|(s, _)| *s == slot).map(|k| &gb[k]).unwrap_or(&self.stand_in.0);
            let tv = |v| wgpu::BindingResource::TextureView(v);
            let (gi_r, gi_z) = gi.as_ref().map(|r| (r.result, r.z)).unwrap_or((&self.stand_in.0, &self.stand_in.1));
            let (rf_r, rf_z) = refl.as_ref().map(|r| (r.result, r.z)).unwrap_or((&self.stand_in.0, &self.stand_in.1));
            let bg = self.device.create_bind_group(&wgpu::BindGroupDescriptor {
                label: Some("rt-composite-bg"),
                layout: &self.bgl,
                entries: &[
                    wgpu::BindGroupEntry { binding: 0, resource: self.look_buf.as_entire_binding() },
                    wgpu::BindGroupEntry { binding: 1, resource: self.view_buf.as_entire_binding() },
                    wgpu::BindGroupEntry { binding: 2, resource: tv(at(GSlot::A)) },
                    wgpu::BindGroupEntry { binding: 3, resource: tv(at(GSlot::B)) },
                    wgpu::BindGroupEntry { binding: 4, resource: tv(at(GSlot::N)) },
                    wgpu::BindGroupEntry { binding: 5, resource: tv(depth) },
                    wgpu::BindGroupEntry { binding: 6, resource: tv(gi_r) },
                    wgpu::BindGroupEntry { binding: 7, resource: tv(gi_z) },
                    wgpu::BindGroupEntry { binding: 8, resource: tv(at(GSlot::C)) },
                    wgpu::BindGroupEntry { binding: 9, resource: tv(at(GSlot::D)) },
                    wgpu::BindGroupEntry { binding: 10, resource: tv(rf_r) },
                    wgpu::BindGroupEntry { binding: 11, resource: tv(rf_z) },
                ],
            });
            st.bg = Some((key, bg));
        }
        let half = ((size.0 / 2).max(1) as f32, (size.1 / 2).max(1) as f32);
        let debug = (gi.as_ref().map(|r| r.debug).unwrap_or(0), refl.as_ref().map(|r| r.debug).unwrap_or(0));
        let v = RtCompositeView {
            gi: gi.as_ref().map(|r| [r.keep, r.weight, r.fade.0, r.fade.1]).unwrap_or([0.0; 4]),
            refl: refl.as_ref().map(|r| [0.0, r.weight, r.fade.0, r.fade.1]).unwrap_or([0.0; 4]),
            size: [half.0, half.1, size.0 as f32, size.1 as f32],
            misc: [gi.is_some() as u32 as f32, refl.is_some() as u32 as f32, debug.0 as f32, debug.1 as f32],
        };
        self.queue.write_buffer(&self.view_buf, 0, bytemuck::bytes_of(&v));
        let tw = ts.map(|(q, b)| wgpu::RenderPassTimestampWrites { query_set: q, beginning_of_pass_write_index: Some(b + lighting::Q_RT_COMPOSITE), end_of_pass_write_index: Some(b + lighting::Q_RT_COMPOSITE + 1) });
        let mut pass = enc.begin_render_pass(&wgpu::RenderPassDescriptor {
            label: Some("rt-composite"),
            color_attachments: &[Some(wgpu::RenderPassColorAttachment { view: hdr, depth_slice: None, resolve_target: None, ops: wgpu::Operations { load: wgpu::LoadOp::Load, store: wgpu::StoreOp::Store } })],
            depth_stencil_attachment: None,
            timestamp_writes: tw,
            occlusion_query_set: None,
            multiview_mask: None,
        });
        pass.set_pipeline(if debug.0 > 0 || debug.1 > 0 { &self.replace } else { &self.add });
        pass.set_bind_group(0, &st.bg.as_ref().unwrap().1, &[]);
        pass.draw(0..3, 0..1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_hook_is_spliced_only_with_an_option() {
        let src = include_str!("look_light.wgsl");
        assert_eq!(splice_look_light(src, false), src, "off: look_light.wgsl as it is");
        let on = splice_look_light(src, true);
        assert!(!on.contains(HOOK_MARKER) && on.contains("rtg_a =") && on.contains("rtg_c ="), "on: the hook in the marker's place");
        assert_eq!(src.matches(HOOK_MARKER).count(), 1, "one marker");
        // the hook sits after the last change to the colour, before the return.
        let at = src.find(HOOK_MARKER).unwrap();
        assert!(src[at + HOOK_MARKER.len()..].trim_start().starts_with("return vec4<f32>(lit, alpha);"));
    }

    #[test]
    fn the_gbuffer_holds_what_the_options_use() {
        assert!(gbuffer_layout(false, false).is_empty());
        let slots = |gi, refl| gbuffer_layout(gi, refl).into_iter().map(|(s, _)| s).collect::<Vec<_>>();
        assert_eq!(slots(true, false), [GSlot::A, GSlot::B, GSlot::N]);
        assert_eq!(slots(false, true), [GSlot::N, GSlot::C, GSlot::D]);
        assert_eq!(slots(true, true), [GSlot::A, GSlot::B, GSlot::N, GSlot::C, GSlot::D]);
        // colour + five targets of at most 8 bytes: within the 8 attachments and 64 bytes a pixel of Apple's tile memory.
        let bytes: u32 = 8 + gbuffer_layout(true, true).iter().map(|(_, f)| f.target_pixel_byte_cost().unwrap()).sum::<u32>();
        assert!(bytes <= 64, "{bytes}");
        let u = use_wgsl(false, true);
        assert!(u.contains("@location(1) n:") && u.contains("@location(3) d:") && !u.contains(" a: vec4"));
    }

    #[test]
    fn the_view_matches_its_wgsl_struct() {
        let src = shader_source();
        let m = wgpu::naga::front::wgsl::parse_str(&src).unwrap_or_else(|e| panic!("{}", e.emit_to_string(&src)));
        wgpu::naga::valid::Validator::new(wgpu::naga::valid::ValidationFlags::all(), wgpu::naga::valid::Capabilities::all()).validate(&m).unwrap_or_else(|e| panic!("{}", e.emit_to_string(&src)));
        let (_, ty) = m.types.iter().find(|(_, t)| t.name.as_deref() == Some("RtCompositeView")).expect("RtCompositeView");
        let wgpu::naga::TypeInner::Struct { span, .. } = ty.inner else { panic!() };
        assert_eq!(span as usize, std::mem::size_of::<RtCompositeView>());
    }

    /// Every lit pipeline's shader as composed with the options off is, after
    /// translation to Metal, the shader of the frame before the options
    /// existed: the composition differs from the old one only by the hook's
    /// marker comment, which the front end drops (`--no-rt-gi --no-rt-reflect`
    /// is today's frame byte for byte at the shader level; the layouts and the
    /// device features are unchanged without them, see `GpuContext::ray_query`).
    #[cfg(target_os = "macos")]
    #[test]
    fn the_shaders_without_the_options_translate_as_before() {
        use wgpu::naga;
        let msl = |label: &str, src: &str| -> String {
            let m = naga::front::wgsl::parse_str(src).unwrap_or_else(|e| panic!("{label}: {}", e.emit_to_string(src)));
            let info = naga::valid::Validator::new(naga::valid::ValidationFlags::all(), naga::valid::Capabilities::all()).validate(&m).unwrap_or_else(|e| panic!("{label}: {e:?}"));
            let opts = naga::back::msl::Options { lang_version: (2, 4), ..Default::default() };
            naga::back::msl::write_string(&m, &info, &opts, &naga::back::msl::PipelineOptions::default()).unwrap_or_else(|e| panic!("{label}: {e:?}")).0
        };
        for (name, f) in [("none", crate::look::ShaderFeatures::NONE), ("all", crate::look::ShaderFeatures::ALL)] {
            crate::look::with_shader_features(f, || {
                let variants = [
                    ("city", crate::look::city_shader_source()),
                    ("far layer", crate::look::city_shader_source_far()),
                    ("props", crate::look::city_shader_source_variant_probes(crate::ambient::ShaderLevels::Plane, crate::look::ShadowLevels::Near, false)),
                ];
                for (label, src) in variants {
                    assert!(src.contains(HOOK_MARKER) && !src.contains("rtg_a") && !src.contains("fs_rtg"), "{name} {label}: no trace of the options");
                    let old = src.replacen(&format!("{HOOK_MARKER}\n"), "", 1);
                    assert_ne!(old, src);
                    assert_eq!(msl(label, &src), msl(label, &old), "{name} {label}: the Metal shader is the old one");
                }
            });
        }
        // with an option, the hook, the G-buffer's values and their entry point are in.
        for f in [crate::look::ShaderFeatures::NONE, crate::look::ShaderFeatures::ALL] {
            for (gi, refl) in [(true, false), (false, true), (true, true)] {
                crate::look::with_shader_features(crate::look::ShaderFeatures { rt_gi: gi, rt_reflect: refl, ..f }, || {
                    for (label, src) in [("city", crate::look::city_shader_source()), ("far layer", crate::look::city_shader_source_far())] {
                        assert!(src.contains("rtg_a = vec4") && src.contains("fn fs_rtg"), "{label}");
                        msl(label, &src);
                    }
                });
            }
        }
    }
}
