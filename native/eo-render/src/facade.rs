//! building surfaces as the JS game draws them, beyond the kit maps.
//!
//! * **Weathering** of the Blender-built buildings (kit/materials.js
//!   `weatheringGraph`, applied by blender/runtime.js to every non-glass kit
//!   material of an exterior: soot at the base, run-off under every storey
//!   line, grime, overpaint ghosts, mottle, base soiling) with the per-building
//!   scalars the shared program reads (`weatheringLiteralScalars` of the
//!   runtime's weathering object: base height, origin, storey bands, the
//!   module's own overrides).
//! * **Archetype ageing** of the kit buildings (kit/ageing-nodes.js
//!   `applyArchetypeAgeing`, `archetype-ageing-v3-worn-not-speckled`): the same
//!   graph driven per building by the packed appearance (eo-kit appearance.rs,
//!   building-appearance.js), plus paint fade, rust, splash-back, salt bloom and
//!   the `facade-detail-v1` relief and cavity. The contact terms (reveals,
//!   sill drips, chipped arrises) need the per-face facts the JS packs in the
//!   uv (kit/contact-uv.js); the kit mesh here has no uv, so they are not drawn.
//!
//! Every number is the JS's: `data/facade-oracle.json` is written by
//! the earlier browser version's exporter from the game's own modules, and the
//! WGSL constants below are generated from it.

use serde_json::Value;
use std::collections::BTreeMap;
use std::sync::OnceLock;

/// The oracle the JS export wrote (tables, kit appearance sample, authored weathering).
pub fn oracle() -> &'static Value {
    static O: OnceLock<Value> = OnceLock::new();
    O.get_or_init(|| serde_json::from_str(include_str!("../data/facade-oracle.json")).expect("facade-oracle.json"))
}

fn tables() -> &'static Value {
    &oracle()["tables"]
}

/// Ageing classes (FINISH_AGEING_CLASS / finishAgeingClass), as material flag values.
pub const AGE_NONE: u32 = 0;
pub const AGE_RENDER: u32 = 1;
pub const AGE_PAINTED: u32 = 2;
pub const AGE_MASONRY: u32 = 3;
pub const AGE_METAL: u32 = 4;
pub const AGE_ROOF: u32 = 5;

/// Material flag bits (draw.wgsl mirrors them).
pub const FLAG_AGE_SHIFT: u32 = 8; // 3 bits: the ageing class
pub const FLAG_DETAIL_SHIFT: u32 = 11; // 5 bits: facade detail finish index + 1
pub const FLAG_KIT_WEATHER: u32 = 1 << 16; // a non-glass kit finish (authored weathering applies)
pub const FLAG_ATLAS: u32 = 1 << 17; // a finish drawn from the scanned facade atlas (two taps)

/// `finishAgeingClass(name)`.
pub fn age_class(name: &str) -> u32 {
    let cls = tables()["finishAgeingClass"][name].as_str().map(|s| s.to_string()).or_else(|| {
        if ["brick", "stone", "concrete", "ashlar"].iter().any(|k| name.contains(k)) {
            Some("masonry".into())
        } else if name.contains("stucco") || name.contains("plaster") {
            Some("render".into())
        } else {
            None
        }
    });
    match cls.as_deref() {
        Some("render") => AGE_RENDER,
        Some("painted") => AGE_PAINTED,
        Some("masonry") => AGE_MASONRY,
        Some("metal") => AGE_METAL,
        Some("roof") => AGE_ROOF,
        _ => AGE_NONE,
    }
}

/// The finishes `FACADE_DETAIL_FINISHES` names, in a fixed order (the WGSL table index).
pub fn detail_finishes() -> Vec<(String, Value)> {
    let mut v: Vec<(String, Value)> =
        tables()["detailFinishes"].as_object().map(|o| o.iter().map(|(k, v)| (k.clone(), v.clone())).collect()).unwrap_or_default();
    v.sort_by(|a, b| a.0.cmp(&b.0));
    v
}

/// Material flags for a kit finish (`name` the base kit material name).
pub fn material_flags(name: &str, glass: bool, atlas: bool) -> u32 {
    if glass {
        return 0;
    }
    let mut f = FLAG_KIT_WEATHER | (age_class(name) << FLAG_AGE_SHIFT);
    if let Some(i) = detail_finishes().iter().position(|(k, _)| k == name) {
        f |= ((i as u32) + 1) << FLAG_DETAIL_SHIFT;
    }
    if atlas {
        f |= FLAG_ATLAS;
    }
    f
}

/// The archetype ageing graph's WGSL constants (AGEING_WEATHERING rows,
/// AGEING_FIXED, AGEING_SURFACE, the literal base-soil scalars, the detail
/// atlas layout and per-finish spec), generated from the JS tables.
pub fn facade_constants_wgsl() -> String {
    let t = tables();
    let f = |v: f64| format!("{v:.6}");
    let mut s = String::from("\n// generated by facade.rs facade_constants_wgsl (data/facade-oracle.json, the JS tables)\n");
    let w = &t["ageingWeathering"];
    for (k, name) in [
        ("sootStrength", "AW_SOOT_STRENGTH"),
        ("sootHeight", "AW_SOOT_HEIGHT"),
        ("streakStrength", "AW_STREAK_STRENGTH"),
        ("streakDrop", "AW_STREAK_DROP"),
        ("bandStrength", "AW_BAND_STRENGTH"),
        ("bandDrop", "AW_BAND_DROP"),
        ("grimeStrength", "AW_GRIME_STRENGTH"),
        ("roughnessGain", "AW_ROUGHNESS_GAIN"),
        ("ghostStrength", "AW_GHOST_STRENGTH"),
        ("mottlePainted", "AW_MOTTLE_PAINTED"),
        ("mottleMasonry", "AW_MOTTLE_MASONRY"),
        ("mottleSheen", "AW_MOTTLE_SHEEN"),
        ("paintFade", "AW_PAINT_FADE"),
        ("rust", "AW_RUST"),
    ] {
        let row = &w[k];
        // driver: 0 wear, 1 paint, 2 max(wear, paint)
        let drv = match row["driver"].as_str() {
            Some("W") => 0,
            Some("P") => 1,
            _ => 2,
        };
        s.push_str(&format!("const {name}: vec3<f32> = vec3<f32>({}, {}, {drv}.0);\n", f(row["base"].as_f64().unwrap()), f(row["perUnit"].as_f64().unwrap())));
    }
    let fx = &t["ageingFixed"];
    for (k, name) in [("grimeMetres", "AF_GRIME_M"), ("patchMetres", "AF_PATCH_M"), ("patchTop", "AF_PATCH_TOP"), ("columnMetres", "AF_COLUMN_M")] {
        s.push_str(&format!("const {name}: f32 = {};\n", f(fx[k].as_f64().unwrap())));
    }
    let su = &t["ageingSurface"];
    for (k, name) in [
        ("splashTop", "AS_SPLASH_TOP"),
        ("splashTopWear", "AS_SPLASH_TOP_WEAR"),
        ("splashDark", "AS_SPLASH_DARK"),
        ("splashDarkWear", "AS_SPLASH_DARK_WEAR"),
        ("saltReach", "AS_SALT_REACH"),
        ("saltStrength", "AS_SALT_STRENGTH"),
    ] {
        s.push_str(&format!("const {name}: f32 = {};\n", f(su[k].as_f64().unwrap())));
    }
    let lit = &t["ageingLiteral"];
    for (k, name) in [
        ("baseSoilStrength", "AL_BASE_SOIL_STRENGTH"),
        ("baseSoilTop", "AL_BASE_SOIL_TOP"),
        ("baseSoilBottom", "AL_BASE_SOIL_BOTTOM"),
        ("baseSoilDampStrength", "AL_DAMP_STRENGTH"),
        ("baseSoilDampTop", "AL_DAMP_TOP"),
    ] {
        s.push_str(&format!("const {name}: f32 = {};\n", f(lit[k].as_f64().unwrap())));
    }
    // The ageing structure has damp only when the literal damp line is set
    // (WEATHERING_DEFAULTS.base.dampLineM > 0).
    let damp = t["weatheringDefaults"]["base"]["dampLineM"].as_f64().unwrap_or(0.0) > 0.0;
    s.push_str(&format!("const AL_DAMP_ON: bool = {damp};\n"));
    s.push_str(&format!("const AGE_BANDS: u32 = {}u;\n", t["ageingSettings"]["bands"].as_u64().unwrap_or(6).min(12)));
    s.push_str(&format!("const AGE_GHOSTS: bool = {};\n", t["ageingSettings"]["ghosts"].as_bool().unwrap_or(true)));
    s.push_str(&format!("const AGE_DETAIL: bool = {};\n", t["ageingSettings"]["detail"].as_bool().unwrap_or(true)));
    let pr = crate::probe::constants();
    s.push_str(&format!(
        "const FA_PROBE_LOG2: f32 = {};\nconst FA_PROBE_MAXLOD: f32 = {}.0;\nconst FA_CANYON_M: f32 = {};\nconst FA_GLAZING_FLOOR: f32 = {};\n",
        f((pr.face_size as f64).log2()),
        crate::probe::MIPS - 1,
        f(pr.canyon_m as f64),
        f(pr.glazing_floor as f64)
    ));
    let a = &t["detailAtlas"];
    s.push_str(&format!(
        "const FD_COLUMNS: f32 = {}.0;\nconst FD_ROWS: f32 = {}.0;\nconst FD_CELL_PX: f32 = {}.0;\nconst FD_PAD_PX: f32 = {}.0;\n",
        a["columns"].as_u64().unwrap(),
        a["rows"].as_u64().unwrap(),
        a["cellPx"].as_u64().unwrap(),
        a["padPx"].as_u64().unwrap()
    ));
    let fins = detail_finishes();
    let n = fins.len().max(1);
    let row = |v: &Value| {
        format!(
            "vec4<f32>({}, {}, {}, {})",
            f(v["cell"].as_f64().unwrap_or(0.0)),
            f(v["tileMetres"].as_f64().unwrap_or(1.0)),
            f(v["normal"].as_f64().unwrap_or(1.0)),
            f(v["cavity"].as_f64().unwrap_or(0.0))
        )
    };
    let row2 = |v: &Value| format!("vec2<f32>({}, {})", f(v["ao"].as_f64().unwrap_or(0.0)), if v["replaceNormal"].as_bool().unwrap_or(false) { "1.0" } else { "0.0" });
    s.push_str(&format!("const FD_SPEC: array<vec4<f32>, {n}> = array<vec4<f32>, {n}>({});\n", fins.iter().map(|(_, v)| row(v)).collect::<Vec<_>>().join(", ")));
    s.push_str(&format!("const FD_SPEC2: array<vec2<f32>, {n}> = array<vec2<f32>, {n}>({});\n", fins.iter().map(|(_, v)| row2(v)).collect::<Vec<_>>().join(", ")));
    s
}

/// JS `Math.round`.
fn js_round(v: f64) -> f64 {
    (v + 0.5).floor()
}

/// The weathering object blender/runtime.js builds for a Blender building:
/// `{ baseY: round(baseY * 2) / 2, origin: [round(cx), round(cz)], bands:
/// levels[1..] at round((y + baseY) * 4) / 4 (12 at most), ...data.weathering }`
/// (`data.weathering === false` opts out: None). `centre` is the footprint
/// frame's centre in the authoring frame (z north).
pub fn authored_weathering(levels: &[f64], over: &Value, base_y: f64, centre: [f64; 2]) -> Option<Value> {
    if over.as_bool() == Some(false) {
        return None;
    }
    let mut o = serde_json::Map::new();
    o.insert("baseY".into(), Value::from(js_round(base_y * 2.0) / 2.0));
    o.insert("origin".into(), Value::from(vec![js_round(centre[0]), js_round(centre[1])]));
    let bands: Vec<f64> = levels.iter().skip(1).map(|y| js_round((y + base_y) * 4.0) / 4.0).take(12).collect();
    o.insert("bands".into(), Value::from(bands));
    if let Some(m) = over.as_object() {
        for (k, v) in m {
            o.insert(k.clone(), v.clone());
        }
    }
    Some(Value::Object(o))
}

/// `weatheringLiteralScalars(params)` (kit/materials.js `weatheringScalars` of
/// `resolveWeathering`) for the nested parameter forms the Blender modules
/// use (soot, streak, grime, patches, base, blocks strength, bands, baseY,
/// origin, axis, roughnessGain, bandStrength, bandDrop), plus the structure
/// flags of `sharedWeatheringPlan` (axis wall, patches, mottle, base, damp).
pub fn weathering_scalars(p: &Value) -> (BTreeMap<String, f64>, u32) {
    let d = &tables()["weatheringDefaults"];
    let num = |v: &Value| v.as_f64();
    let get = |group: &str, key: &str| -> f64 { num(&p[group][key]).or(num(&d[group][key])).unwrap_or(0.0) };
    let top = |key: &str| -> f64 { num(&p[key]).or(num(&d[key])).unwrap_or(0.0) };
    let base_y = num(&p["baseY"]).unwrap_or(0.0);
    let origin = [num(&p["origin"][0]).unwrap_or(0.0), num(&p["origin"][1]).unwrap_or(0.0)];
    let patches_strength = get("patches", "strength");
    let patches_metres = get("patches", "metres");
    let big = (if patches_metres > 0.0 { patches_metres } else { 1.3 }).max(0.2);
    let small = big * 0.61;
    let soil_strength = get("base", "strength");
    let soil_height = get("base", "height");
    let damp_share = get("base", "dampShare");
    let damp_line = get("base", "dampLineM");
    let blocks_strength = get("blocks", "strength");
    let grime_m = get("grime", "metres");
    let mut s = BTreeMap::new();
    let mut put = |k: &str, v: f64| {
        s.insert(k.to_string(), v);
    };
    put("baseY", base_y);
    put("originX", origin[0]);
    put("originZ", origin[1]);
    put("patchSeed", get("patches", "seed"));
    put("baseSoilStrength", soil_strength);
    put("baseSoilTop", base_y + (if soil_height != 0.0 { soil_height } else { 0.5 }).max(0.05));
    put("baseSoilBottom", base_y);
    put("baseSoilDampStrength", soil_strength * (if damp_share != 0.0 { damp_share } else { 0.5 }).clamp(0.0, 1.0));
    put("baseSoilDampTop", base_y + damp_line.max(0.01));
    put("columnMetres", get("streak", "columnMetres"));
    put("sootStrength", get("soot", "strength"));
    put("sootTop", base_y + get("soot", "height"));
    put("roughnessGain", top("roughnessGain"));
    put("grimeStrength", get("grime", "strength"));
    put("grimeAX", grime_m);
    put("grimeAY", grime_m * 1.31);
    put("grimeBX", grime_m * 1.73);
    put("grimeBY", grime_m * 2.11);
    put("streakDrop", get("streak", "drop"));
    put("streakStrength", get("streak", "strength"));
    put("bandStrength", top("bandStrength"));
    put("bandDrop", top("bandDrop"));
    put("ceiling", 1.0 + patches_strength.max(0.0) + blocks_strength.max(0.0));
    put("patchLight", patches_strength);
    put("patchDark", patches_strength * 0.85);
    put("patchBig", big);
    put("patchBigY", big * 0.78);
    put("patchSmall", small);
    put("patchSmallY", small * 0.86);
    put("patchReachTop", base_y + get("patches", "top") + 0.6);
    put("patchReachBottom", base_y + get("patches", "top") - 1.4);
    let mottle = get("patches", "mottle");
    put("mottle", mottle);
    put("mottleSheen", get("patches", "mottleSheenDelta"));
    put("mottleAX", big * 0.7);
    put("mottleAY", big * 0.7 * 0.82);
    put("mottleBX", big * 1.6);
    put("mottleBY", big * 1.6 * 0.9);
    let bands: Vec<f64> = p["bands"].as_array().map(|a| a.iter().filter_map(|v| v.as_f64()).take(12).collect()).unwrap_or_default();
    for i in 0..12 {
        put(&format!("band{i}"), bands.get(i).copied().unwrap_or(-1e5));
    }
    let mut flags = 0u32;
    if p["axis"].as_str() == Some("wall") {
        flags |= 1;
    }
    if patches_strength > 0.0 {
        flags |= 2;
    }
    if mottle > 0.0 {
        flags |= 4;
    }
    if soil_strength > 0.0 {
        flags |= 8;
        if damp_line > 0.0 {
            flags |= 16;
        }
    }
    (s, flags)
}

/// WEATHERING_SCALAR_KEYS without the bands, in the JS order (the GPU record layout).
pub const SCALAR_KEYS: [&str; 37] = [
    "baseY", "originX", "originZ", "patchSeed", "columnMetres", "sootStrength", "sootTop", "roughnessGain", "grimeStrength", "grimeAX",
    "grimeAY", "grimeBX", "grimeBY", "streakDrop", "streakStrength", "bandStrength", "bandDrop", "ceiling", "patchLight", "patchDark",
    "patchBig", "patchBigY", "patchSmall", "patchSmallY", "patchReachTop", "patchReachBottom", "mottle", "mottleSheen", "mottleAX",
    "mottleAY", "mottleBX", "mottleBY", "baseSoilStrength", "baseSoilTop", "baseSoilBottom", "baseSoilDampStrength", "baseSoilDampTop",
];

/// One authored building's GPU weathering record: the 37 scalars, the
/// structure flags at [37] (1 wall axis, 2 patches, 4 mottle, 8 base soil,
/// 16 damp, 32 on), the 12 bands at [38..50]. All zero = no weathering.
pub type WeatherRecord = [[f32; 4]; 13];

pub fn weather_record(p: Option<&Value>) -> WeatherRecord {
    let mut r = [[0f32; 4]; 13];
    let Some(p) = p else { return r };
    let (s, flags) = weathering_scalars(p);
    let mut flat = [0f32; 52];
    for (i, k) in SCALAR_KEYS.iter().enumerate() {
        flat[i] = s[*k] as f32;
    }
    flat[37] = (flags | 32) as f32;
    for i in 0..12 {
        flat[38 + i] = s[&format!("band{i}")] as f32;
    }
    for i in 0..13 {
        r[i] = [flat[i * 4], flat[i * 4 + 1], flat[i * 4 + 2], flat[i * 4 + 3]];
    }
    r
}

