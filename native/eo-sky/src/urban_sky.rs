//! (`--urban-sky`) The sky over a lit city. Its glow is the street lamps'
//! light scattered back by the air (eo-render sky.rs: on the practicals'
//! photometric scale with `--night-photometry`), and it hides all but the
//! brightest stars: a star shows where it is brighter than the limiting
//! magnitude the sky's surface brightness leaves. Pure functions; the
//! renderer's star field (look_sky.wgsl `sky_stars_urban`) is built from
//! `wgsl`.
//!
//! Sources:
//! - San Francisco's zenith: the Bay Area's artificial sky brightness is
//!   10-40 x the natural 22.0 mag/arcsec^2 (Falchi et al. 2016, "The new
//!   world atlas of artificial night sky brightness", Sci. Adv. 2:e1600377);
//!   the city's core at the top of that range, ~18.0 mag/arcsec^2 clear.
//! - The limiting magnitude of the naked eye against a sky of surface
//!   brightness B (mag/arcsec^2): NELM = 7.93 - 5 log10(10^(4.316 - B / 5)
//!   + 1) (Schaefer 1990, "Telescopic limiting magnitudes", PASP 102:212,
//!   in the form used to convert sky-quality-meter readings): 6.6 under a
//!   dark 22.0 sky, 4.0 under 18.0, 3.1 under 17.0.
//! - Star counts: the number of stars brighter than m grows about as
//!   10^(0.5 m) over the naked-eye range (Allen's Astrophysical Quantities,
//!   4th ed., 2000, sec. 15.4: ~5,000 stars to m 6, ~500 to m 4, ~170 to
//!   m 3, ~50 to m 2), so a field of `FIELD_STARS` candidates ranked
//!   uniformly by u in (0, 1] has magnitudes m = 6 + 2 log10(u).

/// The city's zenith sky brightness on a clear night (mag/arcsec^2).
pub const ZENITH_MAG_ARCSEC2: f64 = 18.0;
/// The magnitude of the faintest candidate in the field (u = 1).
pub const FIELD_FAINTEST_MAG: f64 = 6.0;
/// How fast star counts grow with magnitude (log10 per magnitude).
pub const COUNT_SLOPE: f64 = 0.5;
/// The brightest a candidate is held to (Sirius, -1.46).
pub const BRIGHTEST_MAG: f64 = -1.46;
/// The field's drawn brightness (look_sky.wgsl `sky_stars`: 0.15 to 1, x
/// 1.3 at the core) is a star's flux relative to a magnitude-`FULL_MAG`
/// star's, 10^(-0.4 (m - FULL_MAG)), held in [`FAINTEST_DRAWN`, 1]: the
/// stars a city sky leaves keep the flux ratios between them, drawn at the
/// field's own scale (a pixel-sized star's radiance is not what the eye's
/// threshold sees; the limit decides which show).
pub const FULL_MAG: f64 = 1.0;
pub const FAINTEST_DRAWN: f64 = 0.15;
/// Stars fade in over this many magnitudes above the limit.
pub const FADE_MAG: f64 = 0.5;

/// The naked eye's limiting magnitude under a sky of surface brightness
/// `b` mag/arcsec^2 (Schaefer 1990).
pub fn limiting_magnitude(b: f64) -> f64 {
    7.93 - 5.0 * (10f64.powf(4.316 - b / 5.0) + 1.0).log10()
}

/// A field candidate's magnitude from its rank `u` in (0, 1].
pub fn magnitude_of_rank(u: f64) -> f64 {
    (FIELD_FAINTEST_MAG + (u.max(1e-9)).log10() / COUNT_SLOPE).max(BRIGHTEST_MAG)
}

/// The sky's surface brightness (mag/arcsec^2) where the city's glow is
/// `ratio` x its clear zenith.
pub fn sky_brightness(ratio: f64) -> f64 {
    ZENITH_MAG_ARCSEC2 - 2.5 * ratio.max(1e-6).log10()
}

/// A star's drawn brightness at magnitude `m` under a limit `nelm`: its
/// flux relative to `FULL_MAG`'s in [`FAINTEST_DRAWN`, 1], faded in over
/// `FADE_MAG` above the limit (0 at or past it).
pub fn star_brightness(m: f64, nelm: f64) -> f64 {
    let t = ((nelm - m) / FADE_MAG).clamp(0.0, 1.0);
    let vis = t * t * (3.0 - 2.0 * t);
    10f64.powf(-0.4 * (m - FULL_MAG)).clamp(FAINTEST_DRAWN, 1.0) * vis
}

/// The constants the star field is built with (look_sky.wgsl).
pub fn wgsl() -> String {
    format!(
        "\n// generated by eo-sky urban_sky::wgsl\nconst US_ZENITH_MAG: f32 = {ZENITH_MAG_ARCSEC2:?};\nconst US_FAINTEST_MAG: f32 = {FIELD_FAINTEST_MAG:?};\nconst US_COUNT_SLOPE: f32 = {COUNT_SLOPE:?};\nconst US_BRIGHTEST_MAG: f32 = {BRIGHTEST_MAG:?};\nconst US_FULL_MAG: f32 = {FULL_MAG:?};\nconst US_FAINTEST_DRAWN: f32 = {FAINTEST_DRAWN:?};\nconst US_FADE_MAG: f32 = {FADE_MAG:?};\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_limiting_magnitude_falls_with_the_sky() {
        assert!((limiting_magnitude(22.0) - 6.6).abs() < 0.1, "{}", limiting_magnitude(22.0));
        assert!((limiting_magnitude(18.0) - 3.97).abs() < 0.05, "{}", limiting_magnitude(18.0));
        assert!((limiting_magnitude(17.0) - 3.1).abs() < 0.1, "{}", limiting_magnitude(17.0));
        assert!(limiting_magnitude(16.0) < limiting_magnitude(17.0));
    }

    #[test]
    fn the_field_has_the_skys_counts() {
        // the share of candidates brighter than m: 10^(0.5 (m - 6)); ~170 / 5,000 to m 3.
        for (m, share) in [(6.0, 1.0), (4.0, 0.1), (3.0, 0.0316), (2.0, 0.01)] {
            let u = 10f64.powf(COUNT_SLOPE * (m - FIELD_FAINTEST_MAG));
            assert!((u - share).abs() < 1e-3, "{m}: {u}");
            assert!((magnitude_of_rank(u) - m).abs() < 1e-9);
        }
        assert_eq!(magnitude_of_rank(1e-12), BRIGHTEST_MAG);
        // under the city's zenith only a few percent of the field shows; toward the
        // horizon, where the glow is ~3.6 x, fewer.
        let shown = |ratio: f64| 10f64.powf(COUNT_SLOPE * (limiting_magnitude(sky_brightness(ratio)) - FIELD_FAINTEST_MAG));
        assert!(shown(1.0) > 0.08 && shown(1.0) < 0.12, "{}", shown(1.0));
        assert!(shown(3.6) < 0.5 * shown(1.0), "{}", shown(3.6));
    }

    #[test]
    fn a_star_shows_by_its_flux_and_only_over_the_limit() {
        assert_eq!(star_brightness(4.0, 4.0), 0.0);
        assert_eq!(star_brightness(5.0, 4.0), 0.0);
        assert_eq!(star_brightness(0.0, 4.0), 1.0);
        assert!((star_brightness(2.0, 4.0) - 10f64.powf(-0.4)).abs() < 1e-12, "a magnitude under the full one: 0.40");
        assert_eq!(star_brightness(3.4, 4.0), FAINTEST_DRAWN);
        assert!(star_brightness(3.8, 4.0) < FAINTEST_DRAWN && star_brightness(3.8, 4.0) > 0.0, "fading in");
    }

    #[test]
    fn the_shader_constants_are_the_models() {
        let s = wgsl();
        assert!(s.contains("const US_ZENITH_MAG: f32 = 18.0;"), "{s}");
        assert!(s.contains("const US_COUNT_SLOPE: f32 = 0.5;"), "{s}");
    }
}
