#[derive(Clone, Debug)]
struct Node {
    name: String,
    parent: Option<usize>,
    t: Vec3,
    r: Quat,
    s: Vec3,
}

fn read_nodes(g: &Glb) -> Vec<Node> {
    let ns = g.nodes();
    let mut parent = vec![None; ns.len()];
    for (i, n) in ns.iter().enumerate() {
        for c in n.get("children").and_then(|c| c.as_array()).into_iter().flatten() {
            if let Some(c) = c.as_u64().map(|c| c as usize).filter(|&c| c < ns.len()) {
                parent[c] = Some(i);
            }
        }
    }
    let v3 = |n: &serde_json::Value, k: &str, d: [f32; 3]| -> Vec3 {
        n.get(k).and_then(|a| a.as_array()).filter(|a| a.len() == 3).map(|a| Vec3::new(a[0].as_f64().unwrap_or(0.0) as f32, a[1].as_f64().unwrap_or(0.0) as f32, a[2].as_f64().unwrap_or(0.0) as f32)).unwrap_or(Vec3::from(d))
    };
    ns.iter()
        .enumerate()
        .map(|(i, n)| {
            let r = n
                .get("rotation")
                .and_then(|a| a.as_array())
                .filter(|a| a.len() == 4)
                .map(|a| Quat::from_xyzw(a[0].as_f64().unwrap_or(0.0) as f32, a[1].as_f64().unwrap_or(0.0) as f32, a[2].as_f64().unwrap_or(0.0) as f32, a[3].as_f64().unwrap_or(1.0) as f32).normalize())
                .unwrap_or(Quat::IDENTITY);
            Node { name: n.get("name").and_then(|x| x.as_str()).unwrap_or("").to_string(), parent: parent[i], t: v3(n, "translation", [0.0; 3]), r, s: v3(n, "scale", [1.0; 3]) }
        })
        .collect()
}

fn world_of(nodes: &[Node]) -> Vec<Mat4> {
    let mut w: Vec<Option<Mat4>> = vec![None; nodes.len()];
    fn get(i: usize, nodes: &[Node], w: &mut Vec<Option<Mat4>>, depth: usize) -> Mat4 {
        if let Some(m) = w[i] {
            return m;
        }
        let n = &nodes[i];
        let local = Mat4::from_scale_rotation_translation(n.s, n.r, n.t);
        let m = match n.parent {
            Some(p) if depth < 256 => get(p, nodes, w, depth + 1) * local,
            _ => local,
        };
        w[i] = Some(m);
        m
    }
    (0..nodes.len()).map(|i| get(i, nodes, &mut w, 0)).collect()
}

/// One avatar's skeleton in the cooked frame (facing +Z, feet on y = 0), for the bake.
#[derive(Clone, Debug)]
pub struct BipSkeleton {
    /// Per `JOINTS` entry: bind position and rotation of the node it reads
    /// (a missing joint reads its listed parent's), and whether it is present.
    pub pos: Vec<Vec3>,
    pub rot: Vec<Quat>,
    pub present: Vec<bool>,
    /// FK parent (index into `JOINTS`) of each entry; the thighs hang from the pelvis.
    pub parent: Vec<Option<usize>>,
    /// the file's own node hierarchy at bind (local TRS), the
    /// node each `JOINTS` entry reads, and the yaw into the cooked frame (the
    /// Rocketbox clips play on these nodes).
    pub nodes: Vec<RestNode>,
    pub node_of: Vec<Option<usize>>,
    pub face: Quat,
}

/// two skeletons that bake to the same table within 1 mm and
/// 0.1 degree a joint (the same joints present, under the same parent nodes;
/// other nodes, a ponytail, do not matter).
pub fn same_bind(a: &BipSkeleton, b: &BipSkeleton) -> bool {
    fn parent(s: &BipSkeleton, k: usize) -> Option<&str> {
        s.node_of[k].and_then(|i| s.nodes[i].parent).map(|p| s.nodes[p].name.as_str())
    }
    (0..JOINTS.len()).all(|k| a.present[k] == b.present[k] && (a.pos[k] - b.pos[k]).length() < 1e-3 && a.rot[k].angle_between(b.rot[k]) < 0.1f32.to_radians() && parent(a, k) == parent(b, k))
}

/// a GLB's node hierarchy at rest (local TRS).
pub(crate) fn rest_nodes(g: &Glb) -> Vec<RestNode> {
    read_nodes(g).into_iter().map(|n| RestNode { name: n.name, parent: n.parent, t: n.t, r: n.r, s: n.s }).collect()
}

fn joint_parent(k: usize) -> Option<usize> {
    let (bip, _) = JOINTS[k];
    let find = |n: &str| JOINTS.iter().position(|(b, _)| *b == n);
    let side = if bip.contains(" L ") { "L" } else { "R" };
    let p = match bip {
        "Bip01 Pelvis" => return None,
        "Bip01 Spine" => "Bip01 Pelvis",
        "Bip01 Spine1" => "Bip01 Spine",
        "Bip01 Spine2" => "Bip01 Spine1",
        "Bip01 Neck" => "Bip01 Spine2",
        "Bip01 Head" => "Bip01 Neck",
        "Bip01 MJaw" | "Bip01 LEye" | "Bip01 REye" => "Bip01 Head",
        _ => {
            let tail = &bip[8..];
            let parent = match tail {
                "Clavicle" => "Bip01 Spine2".to_string(),
                "UpperArm" => format!("Bip01 {side} Clavicle"),
                "Forearm" => format!("Bip01 {side} UpperArm"),
                "Hand" => format!("Bip01 {side} Forearm"),
                "Thigh" => "Bip01 Pelvis".to_string(),
                "Calf" => format!("Bip01 {side} Thigh"),
                "Foot" => format!("Bip01 {side} Calf"),
                "Toe0" => format!("Bip01 {side} Foot"),
                f if f.starts_with("Finger") && f.len() == 7 => format!("Bip01 {side} Hand"),
                f if f.starts_with("Finger") => format!("Bip01 {side} {}", &f[..f.len() - 1]),
                _ => return None,
            };
            return find(&parent);
        }
    };
    find(p)
}

impl BipSkeleton {
    /// A key equal for skeletons that bake to the same table.
    pub fn key(&self) -> Vec<i32> {
        let mut k = vec![];
        for i in 0..JOINTS.len() {
            k.extend(self.pos[i].to_array().map(|x| (x * 2000.0).round() as i32));
            let q = if self.rot[i].w < 0.0 { -self.rot[i] } else { self.rot[i] };
            k.extend(q.to_array().map(|x| (x * 5000.0).round() as i32));
            k.push(self.present[i] as i32);
        }
        k
    }
}

/// what one stretch of a table is sampled from, in table order.
pub enum BakeSrc<'a> {
    /// A Rocketbox clip on the avatar's own nodes: a `motion::ROLES` loop, `frames` stored (closed).
    Clip { clip: &'a RbClip, role: &'a Role, frames: u32 },
    /// A 100STYLE gait cycle, retargeted (`WALK_FRAMES + 1` stored, closed).
    Style { cycle: &'a StyleCycle },
}

/// a baked table and, per stretch, its lift and (walks) the
/// stride its planted foot covers in a cycle with the median slide left.
pub struct Baked {
    pub rows: Vec<[f32; 4]>,
    pub lifts: Vec<f32>,
    pub strides: Vec<Option<(f32, f32)>>,
}

type Pose = (Vec<Vec3>, Vec<Quat>);

/// the pose of the `JOINTS` from the avatar's own node
/// rotations (the root at rest, the pelvis at `pelvis_t`), in the cooked frame.
fn pose_of_nodes(sk: &BipSkeleton, order: &[usize], r: &[Quat], pelvis: usize, pelvis_t: Vec3) -> Pose {
    let nodes = &sk.nodes;
    let mut world = vec![Mat4::IDENTITY; nodes.len()];
    for &i in order {
        let nd = &nodes[i];
        let t = if i == pelvis { pelvis_t } else { nd.t };
        let m = Mat4::from_scale_rotation_translation(nd.s, r[i], t);
        world[i] = match nd.parent {
            Some(p) => world[p] * m,
            None => m,
        };
    }
    let n = JOINTS.len();
    let mut p = vec![Vec3::ZERO; n];
    let mut q = vec![Quat::IDENTITY; n];
    for k in topo(n, |i| sk.parent[i]) {
        match sk.node_of[k] {
            Some(i) => {
                let (_s, rr, t) = world[i].to_scale_rotation_translation();
                p[k] = sk.face * t;
                q[k] = (sk.face * rr).normalize();
            }
            None => {
                let par = sk.parent[k].unwrap_or(0);
                p[k] = p[par];
                q[k] = q[par] * (sk.rot[par].inverse() * sk.rot[k]);
            }
        }
    }
    (p, q)
}

/// a Rocketbox clip's `role` loop on this avatar's own nodes,
/// `frames` stored (the last a copy of the first).
fn clip_frames(sk: &BipSkeleton, c: &RbClip, role: &Role, frames: u32) -> Result<Vec<Pose>> {
    let index: HashMap<&str, usize> = sk.nodes.iter().enumerate().map(|(i, n)| (n.name.as_str(), i)).collect();
    let order = crate::motion::topo_nodes(&sk.nodes);
    let pelvis = sk.node_of[0].ok_or_else(|| anyhow!("no pelvis node"))?;
    let mut root = pelvis;
    while let Some(p) = sk.nodes[root].parent {
        root = p;
    }
    let ratio = if c.root_y > 0.1 && root != pelvis { sk.nodes[root].t.y / c.root_y } else { 1.0 };
    if c.clip.duration < c.start + crate::motion::role_needs_s(role, &c.id) - 1e-3 {
        bail!("{} lasts {:.1} s, the {} window needs {:.1} s", c.id, c.clip.duration, role.name, c.start + crate::motion::role_needs_s(role, &c.id));
    }
    let looped = frames.saturating_sub(1).max(1);
    let mut out = Vec::with_capacity(frames as usize);
    for k in 0..looped {
        let u = k as f32 / looped as f32 * role.seconds;
        let (r, pt) = crate::motion::rb_loop_local(c, &sk.nodes, &index, role, u, pelvis, ratio);
        out.push(pose_of_nodes(sk, &order, &r, pelvis, pt));
    }
    out.push(out[0].clone());
    Ok(out)
}

/// the fingers' rotations relative to their parent joint in
/// the first frame of a clip loop (the relaxed hand the walks take).
pub fn relaxed_hands(sk: &BipSkeleton, c: &RbClip, role: &Role) -> Result<Vec<Quat>> {
    let (_, r) = clip_frames(sk, c, role, 2)?.swap_remove(0);
    Ok((0..JOINTS.len()).map(|k| sk.parent[k].map(|p| (r[p].inverse() * r[k]).normalize()).unwrap_or(Quat::IDENTITY)).collect())
}

fn is_finger(k: usize) -> bool {
    JOINTS[k].0.contains("Finger")
}

/// a 100STYLE gait cycle retargeted onto this skeleton
/// (world rotation changes from the source T-pose on the lined-up limbs).
fn style_frames(sk: &BipSkeleton, c: &StyleCycle, relaxed: Option<&[Quat]>) -> Result<Vec<Pose>> {
    let n = JOINTS.len();
    let sidx: HashMap<&str, usize> = c.nodes.iter().enumerate().map(|(i, nd)| (nd.name.as_str(), i)).collect();
    let sorder = crate::motion::topo_nodes(&c.nodes);
    let rest_r: Vec<Quat> = c.nodes.iter().map(|nd| nd.r).collect();
    let hips = *sidx.get("Hips").ok_or_else(|| anyhow!("{}: no Hips", c.name))?;
    let (rest_p, rest_w) = {
        let mut wp = vec![Vec3::ZERO; c.nodes.len()];
        let mut wr = vec![Quat::IDENTITY; c.nodes.len()];
        for &i in &sorder {
            let nd = &c.nodes[i];
            match nd.parent {
                Some(p) => {
                    wp[i] = wp[p] + wr[p] * (nd.t * c.nodes[p].s);
                    wr[i] = wr[p] * rest_r[i];
                }
                None => {
                    wp[i] = Vec3::new(0.0, nd.t.y, 0.0);
                    wr[i] = rest_r[i];
                }
            }
        }
        (wp, wr)
    };
    // Per joint: the source joint it follows (0 none), whether it keeps the posture, its line-up.
    let mut map: Vec<Option<usize>> = vec![None; n];
    let mut posture = vec![false; n];
    let mut align = vec![Quat::IDENTITY; n];
    let order = topo(n, |i| sk.parent[i]);
    let jidx = |b: &str| JOINTS.iter().position(|(x, _)| *x == b);
    for (bip, src, child) in crate::motion::STYLE_MAP {
        let k = jidx(bip).ok_or_else(|| anyhow!("no joint {bip}"))?;
        let s = *sidx.get(src).ok_or_else(|| anyhow!("{}: no source joint {src}", c.name))?;
        map[k] = Some(s);
        if child.is_empty() {
            posture[k] = true;
            continue;
        }
        let sc = *sidx.get(child).ok_or_else(|| anyhow!("{}: no source joint {child}", c.name))?;
        // The Bip01 bone's direction: to its own child joint (the hand: to the middle finger).
        let bip_child = match bip {
            b if b.ends_with("Clavicle") => b.replace("Clavicle", "UpperArm"),
            b if b.ends_with("UpperArm") => b.replace("UpperArm", "Forearm"),
            b if b.ends_with("Forearm") => b.replace("Forearm", "Hand"),
            b if b.ends_with("Hand") => b.replace("Hand", "Finger2"),
            b if b.ends_with("Thigh") => b.replace("Thigh", "Calf"),
            b if b.ends_with("Calf") => b.replace("Calf", "Foot"),
            b if b.ends_with("Foot") => b.replace("Foot", "Toe0"),
            b => b.to_string(),
        };
        let kc = jidx(&bip_child);
        let db = kc.filter(|&kc| sk.present[kc] && sk.present[k]).map(|kc| (sk.pos[kc] - sk.pos[k]).normalize_or_zero()).unwrap_or(Vec3::ZERO);
        let ds = (rest_p[sc] - rest_p[s]).normalize_or_zero();
        align[k] = if db.length_squared() > 0.5 && ds.length_squared() > 0.5 { Quat::from_rotation_arc(db, ds) } else { Quat::IDENTITY };
    }
    for (bip, src) in crate::motion::STYLE_TOES {
        let k = jidx(bip).ok_or_else(|| anyhow!("no joint {bip}"))?;
        map[k] = Some(*sidx.get(src).ok_or_else(|| anyhow!("{}: no source joint {src}", c.name))?);
        align[k] = sk.parent[k].map(|p| align[p]).unwrap_or(Quat::IDENTITY);
    }
    let hip_scale = sk.pos[0].y / rest_p[hips].y.max(0.1);
    let mut out = Vec::with_capacity(c.frames.len());
    for (lr, off) in &c.frames {
        let (_, wr) = fk_src(&c.nodes, &sorder, lr);
        let hip_delta = Vec3::new(off.x, off.y - rest_p[hips].y, off.z) * hip_scale;
        let mut p = vec![Vec3::ZERO; n];
        let mut r = vec![Quat::IDENTITY; n];
        for &k in &order {
            r[k] = match (map[k], sk.parent[k]) {
                (Some(s), _) if sk.present[k] => {
                    let delta = wr[s] * rest_w[s].inverse();
                    if posture[k] { delta * sk.rot[k] } else { delta * align[k] * sk.rot[k] }
                }
                (_, Some(q)) => {
                    let rel = match relaxed {
                        Some(rel) if is_finger(k) && sk.present[k] => rel[k],
                        _ => sk.rot[q].inverse() * sk.rot[k],
                    };
                    r[q] * rel
                }
                _ => sk.rot[k],
            };
            p[k] = match sk.parent[k] {
                None => sk.pos[k] + hip_delta,
                Some(q) => p[q] + r[q] * (sk.rot[q].inverse() * (sk.pos[k] - sk.pos[q])),
            };
        }
        out.push((p, r));
    }
    scale_stride(sk, &mut out, c.stride_scale);
    Ok(out)
}

/// lengthen a walk's stride by `k`: each ankle's fore-and-aft
/// travel about its mean scaled, the legs re-solved to reach (two bones, the
/// knee kept in its own bend plane, the feet and toes keep their world
/// rotation), the whole body lowered on a frame where a leg would not reach.
fn scale_stride(sk: &BipSkeleton, frames: &mut [Pose], k: f32) {
    if (k - 1.0).abs() < 1e-3 || frames.len() < 3 {
        return;
    }
    let id = |b: &str| JOINTS.iter().position(|(x, _)| *x == b).unwrap();
    let legs: Vec<[usize; 4]> = ["L", "R"].iter().map(|s| [id(&format!("Bip01 {s} Thigh")), id(&format!("Bip01 {s} Calf")), id(&format!("Bip01 {s} Foot")), id(&format!("Bip01 {s} Toe0"))]).collect();
    let n = frames.len() - 1;
    let lens: Vec<(f32, f32)> = legs.iter().map(|l| ((sk.pos[l[1]] - sk.pos[l[0]]).length(), (sk.pos[l[2]] - sk.pos[l[1]]).length())).collect();
    let zmean: Vec<f32> = legs.iter().map(|l| frames[..n].iter().map(|(p, _)| p[l[2]].z).sum::<f32>() / n as f32).collect();
    for (p, r) in frames.iter_mut() {
        let targets: Vec<Vec3> = legs.iter().zip(&zmean).map(|(l, zm)| { let a = p[l[2]]; Vec3::new(a.x, a.y, zm + k * (a.z - zm)) }).collect();
        // Lower the body where a stretched leg would not reach its target.
        let mut drop = 0f32;
        for ((l, t), (l1, l2)) in legs.iter().zip(&targets).zip(&lens) {
            let reach = 0.995 * (l1 + l2);
            let hip = p[l[0]];
            let h2 = (t.x - hip.x).powi(2) + (t.z - hip.z).powi(2);
            if h2 < reach * reach {
                drop = drop.max(hip.y - t.y - (reach * reach - h2).sqrt());
            }
        }
        if drop > 0.0 {
            for q in p.iter_mut() {
                q.y -= drop;
            }
        }
        for ((l, t), (l1, l2)) in legs.iter().zip(&targets).zip(&lens) {
            let (hip, knee, ankle, toe) = (p[l[0]], p[l[1]], p[l[2]], p[l[3]]);
            let d = *t - hip;
            let dist = d.length().clamp((l1 - l2).abs() + 1e-3, 0.999 * (l1 + l2));
            let dn = d.normalize_or(Vec3::NEG_Y);
            let bend = (knee - hip) - dn * (knee - hip).dot(dn);
            let pole = if bend.length_squared() > 1e-8 { bend.normalize() } else { Vec3::Z };
            let ca = ((l1 * l1 + dist * dist - l2 * l2) / (2.0 * l1 * dist)).clamp(-1.0, 1.0);
            let knee2 = hip + dn * (l1 * ca) + pole * (l1 * (1.0 - ca * ca).max(0.0).sqrt());
            let ankle2 = hip + dn * dist;
            let dthigh = Quat::from_rotation_arc((knee - hip).normalize_or(Vec3::NEG_Y), (knee2 - hip).normalize_or(Vec3::NEG_Y));
            let calf_dir = dthigh * (ankle - knee).normalize_or(Vec3::NEG_Y);
            let dcalf = Quat::from_rotation_arc(calf_dir, (ankle2 - knee2).normalize_or(Vec3::NEG_Y));
            r[l[0]] = (dthigh * r[l[0]]).normalize();
            r[l[1]] = (dcalf * dthigh * r[l[1]]).normalize();
            p[l[1]] = knee2;
            p[l[2]] = ankle2;
            p[l[3]] = ankle2 + (toe - ankle);
        }
    }
}

/// World rotations of a source pose (local rotations; the root's position does not matter here).
fn fk_src(nodes: &[RestNode], order: &[usize], lr: &[Quat]) -> (Vec<Vec3>, Vec<Quat>) {
    let mut wp = vec![Vec3::ZERO; nodes.len()];
    let mut wr = vec![Quat::IDENTITY; nodes.len()];
    for &i in order {
        let nd = &nodes[i];
        match nd.parent {
            Some(p) => {
                wp[i] = wp[p] + wr[p] * (nd.t * nodes[p].s);
                wr[i] = wr[p] * lr[i];
            }
            None => wr[i] = lr[i],
        }
    }
    (wp, wr)
}

const FEET: [&str; 4] = ["Bip01 L Foot", "Bip01 R Foot", "Bip01 L Toe0", "Bip01 R Toe0"];

/// The lift that stands the lowest ankle or toe at its bind height.
fn lift_of(sk: &BipSkeleton, frames: &[Pose]) -> f32 {
    let feet: Vec<usize> = FEET.iter().filter_map(|f| JOINTS.iter().position(|(b, _)| b == f)).collect();
    let mut lowest = f32::MAX;
    for (p, _) in frames {
        for &f in &feet {
            lowest = lowest.min(p[f].y - sk.pos[f].y);
        }
    }
    if lowest.is_finite() { -lowest } else { 0.0 }
}

/// the metres a closed walk loop's planted foot travels
/// backwards in one cycle (the median over the frames a foot's ankle or toe
/// stands within 2.5 cm of the ground), and the median share it is off by.
pub fn stride_of(sk: &BipSkeleton, frames: &[Pose], lift: f32) -> Option<(f32, f32)> {
    let n = frames.len().checked_sub(1)?;
    if n < 8 {
        return None;
    }
    let id = |b: &str| JOINTS.iter().position(|(x, _)| *x == b);
    let mut samples = vec![];
    for (ankle, toe) in [(id("Bip01 L Foot")?, id("Bip01 L Toe0")?), (id("Bip01 R Foot")?, id("Bip01 R Toe0")?)] {
        let contact = |k: usize| -> Option<usize> {
            let (p, _) = &frames[k];
            let ha = p[ankle].y + lift - sk.pos[ankle].y;
            let ht = p[toe].y + lift - sk.pos[toe].y;
            let (j, h) = if ha <= ht { (ankle, ha) } else { (toe, ht) };
            (h < 0.025).then_some(j)
        };
        for k in 0..n {
            let (Some(a), Some(b)) = (contact(k), contact(k + 1)) else { continue };
            if a != b {
                continue;
            }
            samples.push(-(frames[k + 1].0[a].z - frames[k].0[a].z) * n as f32);
        }
    }
    if samples.len() < 6 {
        return None;
    }
    samples.sort_by(f32::total_cmp);
    let s = samples[samples.len() / 2];
    let mut off: Vec<f32> = samples.iter().map(|x| (x - s).abs() / s.abs().max(0.1)).collect();
    off.sort_by(f32::total_cmp);
    Some((s, off[off.len() / 2]))
}

/// a table of every stretch in `srcs`, in order.
pub fn bake_list(sk: &BipSkeleton, srcs: &[BakeSrc], relaxed: Option<&[Quat]>) -> Result<Baked> {
    let n = JOINTS.len();
    let mut out = Baked { rows: vec![], lifts: vec![], strides: vec![] };
    for src in srcs {
        let frames = match src {
            BakeSrc::Clip { clip, role, frames } => clip_frames(sk, clip, role, *frames)?,
            BakeSrc::Style { cycle } => style_frames(sk, cycle, relaxed)?,
        };
        let lift = lift_of(sk, &frames);
        out.lifts.push(lift);
        out.strides.push(if matches!(src, BakeSrc::Style { .. }) { stride_of(sk, &frames, lift) } else { None });
        for (p, r) in &frames {
            for k in 0..n {
                let m = Mat4::from_translation(p[k] + Vec3::Y * lift) * Mat4::from_quat(r[k] * sk.rot[k].inverse()) * Mat4::from_translation(-sk.pos[k]);
                let rows = m.transpose().to_cols_array_2d();
                out.rows.push(rows[0]);
                out.rows.push(rows[1]);
                out.rows.push(rows[2]);
            }
        }
    }
    Ok(out)
}

fn topo(n: usize, parent: impl Fn(usize) -> Option<usize>) -> Vec<usize> {
    let mut order = vec![];
    let mut placed = vec![false; n];
    let mut guard = 0;
    while order.len() < n && guard < n + 2 {
        guard += 1;
        for i in 0..n {
            if !placed[i] && parent(i).is_none_or(|p| p >= n || placed[p]) {
                placed[i] = true;
                order.push(i);
            }
        }
    }
    order
}

