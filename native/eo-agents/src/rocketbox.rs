//! the Microsoft Rocketbox avatars (MIT, Copyright (c) 2020 Microsoft)
//! as the street civilians, cooked from CodePawl's packed GLB repackaging.
//!
//! Source: the folder `EO_PEOPLE_ROOT` names (no default), a copy
//! of the dataset's `objects/` (full mesh, WebP colour + normal maps) and
//! `lods/` (50 / 20 / 6 % of the triangles) for the people, pinned to one
//! dataset revision. Every file is checked against `native/assets/people-manifest.json`
//! (byte length + SHA-256, the upstream commit, the licence) before it is
//! parsed; anything missing or different is refused and no people are
//! drawn (one log line says why). The files are data: nothing in them runs.
//!
//! Tiers: the full mesh is the hero tier, lod1 near, lod2 mid, lod3 far (a
//! lod3 that fails the checks below falls back to lod2). Blendshapes are
//! dropped (only the base attributes are read). Each avatar's materials
//! (body, head, hair/eyelash cutout, and any extras) are packed into one
//! 1024 px atlas, block-compressed (BC3 colour + cutout, BC5 normal, BC1 ORM)
//! with their mip chain at cook time; roughness is set per material class
//! (skin, hair, cloth), metalness 0, hair and eyelashes alpha-tested.
//!
//! MOTION (`motion.rs` says where it comes from and why): the Rocketbox
//! clips drive each avatar's own nodes with no retarget; the 100STYLE walks
//! are retargeted onto the Bip01 bones (each limb's bind direction lined up
//! with the source bone's, the torso and head keeping the avatar's own
//! posture, the hips' travel scaled by the hip height), so each avatar keeps
//! its own bind, weights and proportions. Each stretch of the table is
//! lifted so its lowest foot stands on the ground (`bake_list`). Rocketbox
//! ships two adult skeletons (female, male) whose avatars differ by mesh
//! only, so the bake is per proportion group: identical skeletons share one
//! table.

