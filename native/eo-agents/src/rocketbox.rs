#[derive(Clone, Debug, Deserialize)]
pub struct ManifestSource {
    pub revision: String,
    pub upstream_commit: String,
    pub licence: String,
}

#[derive(Clone, Debug, Deserialize)]
pub struct Manifest {
    pub source: ManifestSource,
    pub files: Vec<ManifestFile>,
    pub avatars: Vec<ManifestAvatar>,
}

impl Manifest {
    pub fn load() -> Result<Self> {
        let m: Manifest = serde_json::from_str(MANIFEST_JSON).context("native/assets/people-manifest.json")?;
        if m.source.licence != "MIT" || m.source.upstream_commit != "0943055db6ec570bcef9f2c8b41c9e5467c808f9" {
            bail!("people manifest: unexpected licence or upstream commit");
        }
        Ok(m)
    }

    pub fn digest() -> String {
        eo_assets::glb::sha256_hex(MANIFEST_JSON.as_bytes())
    }

    pub fn file(&self, path: &str) -> Option<&ManifestFile> {
        self.files.iter().find(|f| f.path == path)
    }

    /// Avatars kept out of the random pool, by role (for later roles).
    pub fn reserved(&self) -> std::collections::BTreeMap<String, Vec<String>> {
        let mut out: std::collections::BTreeMap<String, Vec<String>> = Default::default();
        for a in &self.avatars {
            if !a.pool {
                out.entry(a.role.clone()).or_default().push(a.id.clone());
            }
        }
        out
    }
}

/// The people root `EO_PEOPLE_ROOT` names; None when it is not set or holds no copy.
pub fn root_from_env() -> Option<PathBuf> {
    let p = std::env::var_os(ROOT_ENV).filter(|v| !v.is_empty()).map(PathBuf::from)?;
    (p.join("LICENSES.md").is_file() && p.join("objects").is_dir()).then_some(p)
}

/// A manifest file read from the root, refused unless its length and SHA-256 match.
pub fn read_verified(root: &Path, m: &Manifest, rel: &str) -> Result<Vec<u8>> {
    if rel.is_empty() || rel.split('/').any(|c| c.is_empty() || c == "." || c == ".." || !c.chars().all(|ch| ch.is_ascii_alphanumeric() || "-_.".contains(ch))) {
        bail!("refused path {rel}");
    }
    let f = m.file(rel).ok_or_else(|| anyhow!("{rel} is not in the people manifest"))?;
    let p = rel.split('/').fold(root.to_path_buf(), |acc, c| acc.join(c));
    let bytes = std::fs::read(&p).with_context(|| format!("reading {}", p.display()))?;
    if bytes.len() as u64 != f.bytes {
        bail!("{rel}: {} bytes, the manifest says {}", bytes.len(), f.bytes);
    }
    let sha = eo_assets::glb::sha256_hex(&bytes);
    if sha != f.sha256 {
        bail!("{rel}: SHA-256 {sha} differs from the manifest");
    }
    Ok(bytes)
}

