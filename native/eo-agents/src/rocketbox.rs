/// The cooked frame of a file: yaw so the toes point +Z, and the mesh dequantization.
struct Frame {
    face: Quat,
    nodes: Vec<Node>,
    world: Vec<Mat4>,
    joints: Vec<usize>,
    dequant: Mat4,
}

fn frame_of(g: &Glb, face: Option<Quat>) -> Result<Frame> {
    let nodes = read_nodes(g);
    let world = world_of(&nodes);
    let skin = g.skins().first().ok_or_else(|| anyhow!("no skin"))?;
    let joints: Vec<usize> = skin.get("joints").and_then(|j| j.as_array()).ok_or_else(|| anyhow!("skin without joints"))?.iter().map(|j| j.as_u64().unwrap_or(u64::MAX) as usize).collect();
    if joints.is_empty() || joints.len() > 255 || joints.iter().any(|&j| j >= nodes.len()) {
        bail!("skin joints out of range");
    }
    let ibm_acc = skin.get("inverseBindMatrices").and_then(|x| x.as_u64()).ok_or_else(|| anyhow!("skin without inverse binds"))? as usize;
    let ibms = g.mat4s(ibm_acc)?;
    if ibms.len() != joints.len() {
        bail!("{} inverse binds for {} joints", ibms.len(), joints.len());
    }
    // The packer folds the position dequantization into the inverse binds:
    // joint world x inverse bind is that one transform for every joint.
    let mq: Vec<Mat4> = joints.iter().zip(&ibms).map(|(&j, ib)| world[j] * Mat4::from_cols_array(ib)).collect();
    let dequant = mq[0];
    let spread = mq.iter().map(|m| m.to_cols_array().iter().zip(dequant.to_cols_array()).map(|(a, b)| (a - b).abs()).fold(0.0f32, f32::max)).fold(0.0, f32::max);
    if !(spread < 2e-3 * dequant.to_cols_array().iter().map(|x| x.abs()).fold(0.0, f32::max).max(1e-6)) {
        bail!("the skin is not at its bind pose (joint x inverse bind spread {spread})");
    }
    let face = match face {
        Some(q) => q,
        None => {
            let pos = |name: &str| nodes.iter().position(|n| n.name == name).map(|i| world[i].w_axis.truncate());
            let (Some(foot), Some(toe), Some(lt), Some(rt)) = (pos("Bip01 L Foot"), pos("Bip01 L Toe0"), pos("Bip01 L Thigh"), pos("Bip01 R Thigh")) else { bail!("no Bip01 feet and thighs") };
            let fwd = Vec3::new(toe.x - foot.x, 0.0, toe.z - foot.z);
            if fwd.length() < 1e-4 {
                bail!("cannot tell which way the avatar faces");
            }
            let q = Quat::from_rotation_arc(fwd.normalize(), Vec3::Z);
            // Left is +x when facing +z.
            if (q * (lt - rt)).x <= 0.0 {
                bail!("the avatar's left thigh is not on its left");
            }
            q
        }
    };
    Ok(Frame { face, nodes, world, joints, dequant })
}

/// Bind skeleton of a file in the cooked frame.
fn skeleton_of(f: &Frame) -> Result<BipSkeleton> {
    let n = JOINTS.len();
    let find = |name: &str| f.nodes.iter().position(|nd| nd.name == name);
    let mut pos = vec![Vec3::ZERO; n];
    let mut rot = vec![Quat::IDENTITY; n];
    let mut present = vec![false; n];
    let parent: Vec<Option<usize>> = (0..n).map(joint_parent).collect();
    let mut node_of = vec![None; n];
    for k in topo(n, |i| parent[i]) {
        match find(JOINTS[k].0) {
            Some(i) => {
                let (_s, r, t) = f.world[i].to_scale_rotation_translation();
                pos[k] = f.face * t;
                rot[k] = (f.face * r).normalize();
                present[k] = true;
                node_of[k] = Some(i);
            }
            None => {
                let p = parent[k].ok_or_else(|| anyhow!("no {}", JOINTS[k].0))?;
                pos[k] = pos[p];
                rot[k] = rot[p];
            }
        }
    }
    for need in ["Bip01 Pelvis", "Bip01 L Thigh", "Bip01 R Thigh", "Bip01 L Foot", "Bip01 R Foot", "Bip01 L UpperArm", "Bip01 R UpperArm", "Bip01 Head"] {
        if !present[JOINTS.iter().position(|(b, _)| *b == need).unwrap()] {
            bail!("skeleton lacks {need}");
        }
    }
    let nodes = f.nodes.iter().map(|nd| RestNode { name: nd.name.clone(), parent: nd.parent, t: nd.t, r: nd.r, s: nd.s }).collect();
    Ok(BipSkeleton { pos, rot, present, parent, nodes, node_of, face: f.face })
}

/// Node index -> `JOINTS` entry (the nearest listed ancestor for unlisted nodes).
fn joint_map(f: &Frame) -> Vec<Option<u8>> {
    let listed: HashMap<&str, u8> = JOINTS.iter().enumerate().map(|(k, (b, _))| (*b, k as u8)).collect();
    (0..f.nodes.len())
        .map(|i| {
            let mut at = Some(i);
            let mut guard = 0;
            while let Some(a) = at {
                if let Some(&k) = listed.get(f.nodes[a].name.as_str()) {
                    return Some(k);
                }
                at = f.nodes[a].parent;
                guard += 1;
                if guard > 256 {
                    break;
                }
            }
            None
        })
        .collect()
}

fn regions_of(g: &Glb) -> Result<HashMap<String, Region>> {
    let mut out = HashMap::new();
    let mut small = 0;
    let mats = g.materials();
    // The body first (it takes the large slot), then the rest in file order.
    let mut order: Vec<usize> = (0..mats.len()).collect();
    order.sort_by_key(|&i| {
        let m = &mats[i];
        let name = m.get("name").and_then(|x| x.as_str()).unwrap_or("");
        let cut = m.get("alphaMode").and_then(|x| x.as_str()) == Some("MASK");
        match class_of(name, cut) {
            Class::Body => 0,
            Class::Head => 1,
            Class::Hair => 2,
            _ => 3,
        }
    });
    let mut body_taken = false;
    for i in order {
        let m = &mats[i];
        let name = m.get("name").and_then(|x| x.as_str()).unwrap_or("").to_string();
        let cutout = m.get("alphaMode").and_then(|x| x.as_str()) == Some("MASK");
        let class = class_of(&name, cutout);
        let tex = |v: Option<&serde_json::Value>| v.and_then(|t| t.get("index")).and_then(|x| x.as_u64()).map(|x| x as usize);
        let pbr = m.get("pbrMetallicRoughness");
        if m.get("extensions").is_some_and(|e| e.get("KHR_texture_transform").is_some()) || pbr.and_then(|p| p.get("baseColorTexture")).and_then(|t| t.get("extensions")).is_some() {
            bail!("material {name}: texture transforms are not handled");
        }
        let slot = if class == Class::Body && !body_taken {
            body_taken = true;
            BODY_SLOT
        } else {
            let s = *SMALL_SLOTS.get(small).ok_or_else(|| anyhow!("more than {} small materials", SMALL_SLOTS.len()))?;
            small += 1;
            s
        };
        out.insert(name, Region { slot, class, cutout, base_tex: tex(pbr.and_then(|p| p.get("baseColorTexture"))), normal_tex: tex(m.get("normalTexture")) });
    }
    Ok(out)
}

/// Read one tier's skinned mesh into the cooked frame with atlas texture coordinates.
fn read_tier(g: &Glb, f: &Frame, regions: &HashMap<String, Region>, material: u32) -> Result<RbTier> {
    let jmap = joint_map(f);
    let to_joint: Vec<u8> = f.joints.iter().map(|&n| jmap[n].unwrap_or(0)).collect();
    let mats = g.materials();
    let normal_m = Mat3::from_mat4(f.dequant).inverse().transpose();
    let mut out = RbTier::default();
    let (mut mn, mut mx) = (Vec3::splat(f32::MAX), Vec3::splat(f32::MIN));
    let mesh_node = g.nodes().iter().find(|n| n.get("mesh").is_some() && n.get("skin").is_some()).ok_or_else(|| anyhow!("no skinned mesh node"))?;
    let mesh = g.meshes().get(mesh_node["mesh"].as_u64().unwrap_or(u64::MAX) as usize).ok_or_else(|| anyhow!("mesh missing"))?;
    for p in mesh.get("primitives").and_then(|p| p.as_array()).into_iter().flatten() {
        if p.get("mode").and_then(|m| m.as_u64()).unwrap_or(4) != 4 {
            bail!("non-triangle primitive");
        }
        let at = |k: &str| p.get("attributes").and_then(|a| a.get(k)).and_then(|x| x.as_u64()).map(|x| x as usize);
        let mname = p.get("material").and_then(|m| m.as_u64()).and_then(|m| mats.get(m as usize)).and_then(|m| m.get("name")).and_then(|n| n.as_str()).unwrap_or("");
        let region = regions.get(mname).ok_or_else(|| anyhow!("material {mname} has no atlas slot"))?;
        let pos = g.floats(at("POSITION").ok_or_else(|| anyhow!("no POSITION"))?)?;
        let nrm = g.floats(at("NORMAL").ok_or_else(|| anyhow!("no NORMAL"))?)?;
        let uv = g.floats(at("TEXCOORD_0").ok_or_else(|| anyhow!("no TEXCOORD_0"))?)?;
        let js = g.uints(at("JOINTS_0").ok_or_else(|| anyhow!("no JOINTS_0"))?)?;
        let ws = g.floats(at("WEIGHTS_0").ok_or_else(|| anyhow!("no WEIGHTS_0"))?)?;
        let nv = pos.len();
        if nrm.len() != nv || uv.len() != nv || js.len() != nv || ws.len() != nv {
            bail!("attribute counts differ");
        }
        let base = out.vertices.len() as u32;
        let (sx, sy, ss) = region.slot;
        for i in 0..nv {
            let pw = f.face * f.dequant.transform_point3(Vec3::new(pos[i][0], pos[i][1], pos[i][2]));
            let nw = (f.face * (normal_m * Vec3::new(nrm[i][0], nrm[i][1], nrm[i][2]))).normalize_or_zero();
            if !pw.is_finite() {
                bail!("non-finite position");
            }
            mn = mn.min(pw);
            mx = mx.max(pw);
            // Influences folded onto the driven joints, then four bytes summing to 255.
            let mut infl: [(u8, f32); 4] = [(0, 0.0); 4];
            let mut used = 0;
            for c in 0..4 {
                let w = ws[i][c];
                if w <= 0.0 {
                    continue;
                }
                let j = *to_joint.get(js[i][c] as usize).ok_or_else(|| anyhow!("joint index out of range"))?;
                if let Some(e) = infl[..used].iter_mut().find(|e| e.0 == j) {
                    e.1 += w;
                } else {
                    infl[used] = (j, w);
                    used += 1;
                }
            }
            if used == 0 {
                infl[0] = (0, 1.0);
                used = 1;
            }
            let sum: f32 = infl[..used].iter().map(|e| e.1).sum::<f32>().max(1e-6);
            let mut q = [0i32; 4];
            let mut jj = [0u8; 4];
            for c in 0..used {
                jj[c] = infl[c].0;
                q[c] = (infl[c].1 / sum * 255.0).round() as i32;
            }
            let total: i32 = q.iter().sum();
            let big = (0..used).max_by(|a, b| infl[*a].1.total_cmp(&infl[*b].1)).unwrap();
            q[big] = (q[big] + 255 - total).clamp(0, 255);
            let u = (sx as f32 + uv[i][0].clamp(0.0, 1.0) * ss as f32) / ATLAS_RES as f32;
            let v = (sy as f32 + uv[i][1].clamp(0.0, 1.0) * ss as f32) / ATLAS_RES as f32;
            out.vertices.push(AgentVertex {
                pos: pw.to_array(),
                normal: crate::vehicles::pack_normal(nw),
                uv: [(u * 65535.0).round() as u16, (v * 65535.0).round() as u16],
                joints: jj,
                weights: q.map(|x| x as u8),
                tag: tag(material, 0),
            });
        }
        let idx = g.uints(p.get("indices").and_then(|x| x.as_u64()).ok_or_else(|| anyhow!("unindexed primitive"))? as usize)?;
        for t in idx.chunks_exact(3) {
            let (a, b, c) = (t[0][0], t[1][0], t[2][0]);
            if a as usize >= nv || b as usize >= nv || c as usize >= nv {
                bail!("index out of range");
            }
            if a == b || b == c || a == c {
                continue;
            }
            out.indices.extend([a + base, b + base, c + base]);
        }
    }
    out.min = mn.to_array();
    out.max = mx.to_array();
    Ok(out)
}

/// A tier draws: triangles with area, a person-sized box.
fn tier_problem(t: &RbTier, hero: Option<&RbTier>) -> Option<String> {
    if t.indices.len() < 3 * 50 {
        return Some(format!("{} triangles", t.indices.len() / 3));
    }
    let area: f32 = t
        .indices
        .chunks_exact(3)
        .map(|c| {
            let p = |i: u32| Vec3::from(t.vertices[i as usize].pos);
            (p(c[1]) - p(c[0])).cross(p(c[2]) - p(c[0])).length() * 0.5
        })
        .sum();
    let h = t.max[1] - t.min[1];
    if !(area > 0.5) || !(0.9..2.3).contains(&h) {
        return Some(format!("area {area:.2} m2, height {h:.2} m"));
    }
    if let Some(hero) = hero {
        let hh = hero.max[1] - hero.min[1];
        if (h - hh).abs() > 0.1 * hh {
            return Some(format!("height {h:.2} m against the full mesh's {hh:.2} m"));
        }
    }
    None
}

// ------------------------------------------------------------------ atlas

fn srgb_lut() -> [f32; 256] {
    let mut l = [0f32; 256];
    for (i, v) in l.iter_mut().enumerate() {
        *v = crate::srgb_to_linear(i as f32 / 255.0);
    }
    l
}

fn to_srgb8(v: f32) -> u8 {
    let v = v.clamp(0.0, 1.0);
    let s = if v <= 0.0031308 { v * 12.92 } else { 1.055 * v.powf(1.0 / 2.4) - 0.055 };
    (s * 255.0 + 0.5) as u8
}

/// Area resample of an RGBA image (linear-light colour for `srgb`), to `d` x `d`.
fn resample(src: &[u8], w: u32, h: u32, d: u32, srgb: bool, lut: &[f32; 256]) -> Vec<[f32; 4]> {
    let (w, h, d) = (w as usize, h as usize, d as usize);
    let fetch = |x: usize, y: usize, c: usize| -> f32 {
        let b = src[(y * w + x) * 4 + c];
        if srgb && c < 3 { lut[b as usize] } else { b as f32 / 255.0 }
    };
    // Separable box of the footprint, fractional at the edges.
    let weights = |n: usize, m: usize| -> Vec<Vec<(usize, f32)>> {
        let s = n as f32 / m as f32;
        (0..m)
            .map(|o| {
                let (a, b) = (o as f32 * s, (o + 1) as f32 * s);
                let mut v = vec![];
                let mut i = a.floor() as usize;
                while (i as f32) < b && i < n {
                    let cov = (b.min(i as f32 + 1.0) - a.max(i as f32)).max(0.0);
                    if cov > 0.0 {
                        v.push((i, cov / s));
                    }
                    i += 1;
                }
                v
            })
            .collect()
    };
    let wx = weights(w, d);
    let wy = weights(h, d);
    let mut rows = vec![[0f32; 4]; d * h];
    for y in 0..h {
        for (ox, ws) in wx.iter().enumerate() {
            let mut acc = [0f32; 4];
            for &(x, k) in ws {
                for (c, a) in acc.iter_mut().enumerate() {
                    *a += fetch(x, y, c) * k;
                }
            }
            rows[y * d + ox] = acc;
        }
    }
    let mut out = vec![[0f32; 4]; d * d];
    for (oy, ws) in wy.iter().enumerate() {
        for ox in 0..d {
            let mut acc = [0f32; 4];
            for &(y, k) in ws {
                let r = rows[y * d + ox];
                for c in 0..4 {
                    acc[c] += r[c] * k;
                }
            }
            out[oy * d + ox] = acc;
        }
    }
    out
}

/// Skin-coloured texel (YCbCr box), for the body map's roughness.
fn skin_like(r: f32, g: f32, b: f32) -> bool {
    let (r, g, b) = (r * 255.0, g * 255.0, b * 255.0);
    let y = 0.299 * r + 0.587 * g + 0.114 * b;
    let cb = 128.0 - 0.168736 * r - 0.331264 * g + 0.5 * b;
    let cr = 128.0 + 0.5 * r - 0.418688 * g - 0.081312 * b;
    y > 40.0 && y < 235.0 && (80.0..=125.0).contains(&cb) && (137.0..=170.0).contains(&cr) && r > g && r > b
}

/// Linear-space float maps of the atlas before compression.
struct Planes {
    albedo: Vec<[f32; 4]>,
    normal: Vec<[f32; 3]>,
    orm: Vec<[f32; 3]>,
    cutout: Vec<bool>,
}

/// Cook a glTF material already laid out in one atlas. Share the crowd's
/// texture format so the player can use the same material and shadow passes.
pub(crate) fn material_atlas(
    maps: [(u32, u32, Vec<u8>); 3],
    masked: bool,
    orm_factors: [f32; 3],
) -> Atlas {
    let [albedo, normal, orm] = maps;
    let lut = srgb_lut();
    let resize = |(w, h, rgba): (u32, u32, Vec<u8>), srgb| {
        resample(&rgba, w, h, ATLAS_RES, srgb, &lut)
    };
    let mut albedo = resize(albedo, true);
    if !masked {
        for texel in &mut albedo {
            texel[3] = 1.0;
        }
    }
    let normal = resize(normal, false).into_iter().map(|[r, g, b, _]| {
        (Vec3::new(r, g, b) * 2.0 - Vec3::ONE).normalize_or(Vec3::Z).to_array()
    }).collect();
    let orm = resize(orm, false).into_iter().map(|[r, g, b, _]| {
        [1.0 + (r - 1.0) * orm_factors[0], g * orm_factors[1], b * orm_factors[2]]
    }).collect();
    let cutout = vec![masked; albedo.len()];
    compress_planes(Planes { albedo, normal, orm, cutout })
}

fn build_planes(g: &Glb, regions: &HashMap<String, Region>) -> Result<Planes> {
    let n = (ATLAS_RES * ATLAS_RES) as usize;
    let lut = srgb_lut();
    let mut p = Planes { albedo: vec![[0.5, 0.5, 0.5, 1.0]; n], normal: vec![[0.0, 0.0, 1.0]; n], orm: vec![[1.0, 0.85, 0.0]; n], cutout: vec![false; n] };
    let mut cache: HashMap<usize, (u32, u32, Vec<u8>)> = HashMap::new();
    let mut image = |t: usize| -> Result<(u32, u32, Vec<u8>)> {
        if let Some(v) = cache.get(&t) {
            return Ok(v.clone());
        }
        let v = g.texture_rgba(t)?;
        cache.insert(t, v.clone());
        Ok(v)
    };
    for (name, r) in regions {
        let (sx, sy, ss) = r.slot;
        let base = match r.base_tex {
            Some(t) => {
                let (w, h, px) = image(t).with_context(|| format!("{name} colour"))?;
                resample(&px, w, h, ss, true, &lut)
            }
            None => vec![[0.5, 0.5, 0.5, 1.0]; (ss * ss) as usize],
        };
        let normal = match r.normal_tex {
            Some(t) => {
                let (w, h, px) = image(t).with_context(|| format!("{name} normal"))?;
                Some(resample(&px, w, h, ss, false, &lut))
            }
            None => None,
        };
        for y in 0..ss {
            for x in 0..ss {
                let s = (y * ss + x) as usize;
                let d = ((sy + y) * ATLAS_RES + sx + x) as usize;
                let c = base[s];
                p.albedo[d] = [c[0], c[1], c[2], if r.cutout { c[3] } else { 1.0 }];
                p.cutout[d] = r.cutout;
                if let Some(nm) = &normal {
                    let v = Vec3::new(nm[s][0] * 2.0 - 1.0, nm[s][1] * 2.0 - 1.0, nm[s][2] * 2.0 - 1.0).normalize_or(Vec3::Z);
                    p.normal[d] = v.to_array();
                }
                // Roughness by class (no specular map ships): skin 0.5, hair 0.45,
                // cloth 0.85, glasses 0.15, gear 0.6; metalness 0 throughout.
                let srgb = [to_srgb8(c[0]) as f32 / 255.0, to_srgb8(c[1]) as f32 / 255.0, to_srgb8(c[2]) as f32 / 255.0];
                let rough = match r.class {
                    Class::Head => 0.5,
                    Class::Hair => 0.45,
                    Class::Glass => 0.15,
                    Class::Gear => 0.6,
                    Class::Cloth => 0.85,
                    Class::Body => {
                        if skin_like(srgb[0], srgb[1], srgb[2]) {
                            0.55
                        } else {
                            0.85
                        }
                    }
                };
                p.orm[d] = [1.0, rough, 0.0];
            }
        }
    }
    Ok(p)
}

/// The BC mip chains of one atlas (alpha coverage of the cutout kept per level).
fn compress_planes(p: Planes) -> Atlas {
    let mut albedo = p.albedo;
    let mut normal = p.normal;
    let mut orm = p.orm;
    let mut cut = p.cutout;
    let mut res = ATLAS_RES as usize;
    let coverage = |a: &[[f32; 4]], c: &[bool]| -> f32 {
        let (mut n, mut k) = (0usize, 0usize);
        for (v, &m) in a.iter().zip(c) {
            if m {
                n += 1;
                k += (v[3] >= 0.5) as usize;
            }
        }
        if n == 0 { -1.0 } else { k as f32 / n as f32 }
    };
    let target = coverage(&albedo, &cut);
    let mut maps: [Vec<u8>; 3] = [vec![], vec![], vec![]];
    for level in 0..ATLAS_LEVELS {
        if level > 0 {
            let n = res / 2;
            let mut a2 = vec![[0f32; 4]; n * n];
            let mut n2 = vec![[0f32; 3]; n * n];
            let mut o2 = vec![[0f32; 3]; n * n];
            let mut c2 = vec![false; n * n];
            for y in 0..n {
                for x in 0..n {
                    let ids = [(2 * y) * res + 2 * x, (2 * y) * res + 2 * x + 1, (2 * y + 1) * res + 2 * x, (2 * y + 1) * res + 2 * x + 1];
                    let d = y * n + x;
                    for i in ids {
                        for c in 0..4 {
                            a2[d][c] += albedo[i][c] * 0.25;
                        }
                        for c in 0..3 {
                            n2[d][c] += normal[i][c] * 0.25;
                            o2[d][c] += orm[i][c] * 0.25;
                        }
                        c2[d] |= cut[i];
                    }
                    n2[d] = Vec3::from(n2[d]).normalize_or(Vec3::Z).to_array();
                }
            }
            albedo = a2;
            normal = n2;
            orm = o2;
            cut = c2;
            res = n;
            if target > 0.0 {
                // Scale the cutout alpha so the share of texels kept matches level 0.
                let (mut lo, mut hi) = (0.25f32, 8.0f32);
                for _ in 0..20 {
                    let mid = 0.5 * (lo + hi);
                    let (mut n, mut k) = (0usize, 0usize);
                    for (v, &m) in albedo.iter().zip(&cut) {
                        if m {
                            n += 1;
                            k += (v[3] * mid >= 0.5) as usize;
                        }
                    }
                    if (k as f32 / n.max(1) as f32) < target {
                        lo = mid;
                    } else {
                        hi = mid;
                    }
                }
                let f = 0.5 * (lo + hi);
                for (v, &m) in albedo.iter_mut().zip(&cut) {
                    if m {
                        v[3] = (v[3] * f).min(1.0);
                    }
                }
            }
        }
        let px = res * res;
        let mut a8 = vec![0u8; px * 4];
        let mut n8 = vec![0u8; px * 4];
        let mut o8 = vec![0u8; px * 4];
        for i in 0..px {
            let a = albedo[i];
            a8[i * 4] = to_srgb8(a[0]);
            a8[i * 4 + 1] = to_srgb8(a[1]);
            a8[i * 4 + 2] = to_srgb8(a[2]);
            a8[i * 4 + 3] = (a[3].clamp(0.0, 1.0) * 255.0 + 0.5) as u8;
            let nn = normal[i];
            n8[i * 4] = ((nn[0] * 0.5 + 0.5).clamp(0.0, 1.0) * 255.0 + 0.5) as u8;
            n8[i * 4 + 1] = ((nn[1] * 0.5 + 0.5).clamp(0.0, 1.0) * 255.0 + 0.5) as u8;
            n8[i * 4 + 2] = ((nn[2] * 0.5 + 0.5).clamp(0.0, 1.0) * 255.0 + 0.5) as u8;
            n8[i * 4 + 3] = 255;
            for c in 0..3 {
                o8[i * 4 + c] = (orm[i][c].clamp(0.0, 1.0) * 255.0 + 0.5) as u8;
            }
            o8[i * 4 + 3] = 255;
        }
        let fit = |fmt: texpresso::Format, src: &[u8], algo: texpresso::Algorithm, out: &mut Vec<u8>| {
            let mut buf = vec![0u8; fmt.compressed_size(res, res)];
            fmt.compress(src, res, res, texpresso::Params { algorithm: algo, ..Default::default() }, &mut buf);
            out.extend_from_slice(&buf);
        };
        let algo = if level <= 1 { texpresso::Algorithm::ClusterFit } else { texpresso::Algorithm::RangeFit };
        fit(texpresso::Format::Bc3, &a8, algo, &mut maps[0]);
        fit(texpresso::Format::Bc5, &n8, texpresso::Algorithm::RangeFit, &mut maps[1]);
        fit(texpresso::Format::Bc1, &o8, texpresso::Algorithm::RangeFit, &mut maps[2]);
    }
    Atlas { res: ATLAS_RES, maps: [vec![], vec![], vec![]], bc: maps, bc_levels: ATLAS_LEVELS }
}

/// The block format of atlas map `k` (0 basecolor + cutout, 1 normal xy, 2 ORM).
pub fn bc_format(k: usize) -> texpresso::Format {
    [texpresso::Format::Bc3, texpresso::Format::Bc5, texpresso::Format::Bc1][k.min(2)]
}

/// Bytes of one level of map `k` at `res` px.
pub fn bc_level_bytes(k: usize, res: u32) -> usize {
    bc_format(k).compressed_size(res as usize, res as usize)
}

/// One level of map `k` decoded to RGBA8 (for a device without BC textures).
pub fn bc_level_rgba(k: usize, data: &[u8], res: u32) -> Vec<u8> {
    let mut out = vec![0u8; (res * res * 4) as usize];
    bc_format(k).decompress(data, res as usize, res as usize, &mut out);
    if k == 1 {
        // BC5 leaves blue and alpha unset: rebuild z for the RGBA8 normal map.
        for px in out.chunks_exact_mut(4) {
            let (x, y) = (px[0] as f32 / 127.5 - 1.0, px[1] as f32 / 127.5 - 1.0);
            px[2] = (((1.0 - x * x - y * y).max(0.0).sqrt() * 0.5 + 0.5) * 255.0 + 0.5) as u8;
            px[3] = 255;
        }
    }
    out
}

