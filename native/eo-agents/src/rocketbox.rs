/// Atlas slots (x, y, size) in pixels of `ATLAS_RES`: the body, then 256 px slots.
const BODY_SLOT: (u32, u32, u32) = (0, 0, 768);
const SMALL_SLOTS: [(u32, u32, u32); 7] = [(768, 0, 256), (768, 256, 256), (768, 512, 256), (768, 768, 256), (0, 768, 256), (256, 768, 256), (512, 768, 256)];

#[derive(Clone, Copy, Debug, PartialEq)]
enum Class {
    Body,
    Head,
    Hair,
    Glass,
    Gear,
    Cloth,
}

fn class_of(material: &str, cutout: bool) -> Class {
    let m = material.to_ascii_lowercase();
    let tail = m.rsplit('_').next().unwrap_or(&m);
    if cutout || tail.contains("opacity") || tail.contains("hair") {
        Class::Hair
    } else if tail.contains("body") || m == tail {
        Class::Body
    } else if tail.contains("head") {
        Class::Head
    } else if tail.contains("glass") {
        Class::Glass
    } else if ["keffiyeh", "hat", "scarf", "cap"].iter().any(|k| tail.contains(k)) {
        Class::Cloth
    } else {
        Class::Gear
    }
}

