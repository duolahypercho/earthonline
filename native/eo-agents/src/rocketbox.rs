pub const TIER_FILES: [&str; 4] = ["web", "lod1", "lod2", "lod3"];

/// Cook one avatar from its four verified files.
pub fn cook_avatar(root: &Path, m: &Manifest, a: &ManifestAvatar) -> Result<RbAvatar> {
    let t0 = std::time::Instant::now();
    let mut notes = vec![];
    let file = |k: &str| a.files.get(k).cloned().ok_or_else(|| anyhow!("{}: no {k} file", a.id));
    let full_bytes = read_verified(root, m, &file("web")?)?;
    let full = Glb::parse(&full_bytes)?;
    let f = frame_of(&full, None)?;
    let skeleton = skeleton_of(&f)?;
    let regions = regions_of(&full)?;
    let hero = read_tier(&full, &f, &regions, 0)?;
    if let Some(p) = tier_problem(&hero, None) {
        bail!("{}: full mesh: {p}", a.id);
    }
    let mut tiers = [hero, RbTier::default(), RbTier::default(), RbTier::default()];
    for k in 1..4 {
        let r = (|| -> Result<RbTier> {
            let bytes = read_verified(root, m, &file(TIER_FILES[k])?)?;
            let g = Glb::parse(&bytes)?;
            let fk = frame_of(&g, Some(f.face))?;
            let sk = skeleton_of(&fk)?;
            let worst = (0..JOINTS.len()).map(|j| (sk.pos[j] - skeleton.pos[j]).length()).fold(0.0, f32::max);
            if worst > 0.002 {
                bail!("its skeleton differs from the full mesh's by {worst:.4} m");
            }
            let t = read_tier(&g, &fk, &regions, 0)?;
            if let Some(p) = tier_problem(&t, Some(&tiers[0])) {
                bail!("{p}");
            }
            Ok(t)
        })();
        match r {
            Ok(t) => tiers[k] = t,
            Err(e) => {
                notes.push(format!("{}: {} refused ({e:#}); the {} tier draws {}", a.id, TIER_FILES[k], crate::library::PERSON_TIERS[k], TIER_FILES[k - 1]));
                tiers[k] = tiers[k - 1].clone();
            }
        }
    }
    let atlas = compress_planes(build_planes(&full, &regions)?);
    let height = tiers[0].max[1] - tiers[0].min[1].min(0.0);
    if tiers[0].min[1].abs() > 0.03 {
        notes.push(format!("{}: lowest point of the bind mesh at {:.3} m", a.id, tiers[0].min[1]));
    }
    Ok(RbAvatar { id: a.id.clone(), tiers, atlas, skeleton, height, notes, cook_ms: t0.elapsed().as_secs_f64() * 1e3 })
}

/// an avatar's bind skeleton alone (its full mesh file verified
/// and read, nothing cooked), for the motion checks.
pub fn skeleton_only(root: &Path, m: &Manifest, a: &ManifestAvatar) -> Result<BipSkeleton> {
    let file = a.files.get("web").ok_or_else(|| anyhow!("{}: no web file", a.id))?;
    let bytes = read_verified(root, m, file)?;
    let g = Glb::parse(&bytes)?;
    skeleton_of(&frame_of(&g, None)?)
}

/// The avatars of the random pool, at most `max`, in manifest order.
pub fn pool(m: &Manifest, max: usize) -> Vec<&ManifestAvatar> {
    m.avatars.iter().filter(|a| a.pool).take(max).collect()
}

