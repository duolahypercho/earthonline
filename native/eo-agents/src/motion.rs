/// The first animation of a GLB, channels by node name (LINEAR keys; the
/// sampler data checked: equal counts, finite, increasing times).
pub fn glb_clip(g: &Glb, name: &str) -> Result<Clip> {
    let clip = read_glb_clip(g, 0, name)?;
    if clip.duration <= 0.0 {
        bail!("{name}: an empty clip");
    }
    Ok(clip)
}

pub(crate) fn read_glb_clip(g: &Glb, index: usize, name: &str) -> Result<Clip> {
    let a = g.json.get("animations").and_then(|a| a.as_array()).and_then(|a| a.get(index)).ok_or_else(|| anyhow!("{name}: no animation"))?;
    let samplers = a.get("samplers").and_then(|s| s.as_array()).ok_or_else(|| anyhow!("{name}: no samplers"))?;
    let nodes = g.nodes();
    let mut clip = Clip { name: name.to_string(), ..Default::default() };
    let chans = a.get("channels").and_then(|c| c.as_array()).ok_or_else(|| anyhow!("{name}: no channels"))?;
    if chans.len() > 1024 {
        bail!("{name}: {} channels", chans.len());
    }
    let mut start = f32::MAX;
    for ch in chans {
        let t = ch.get("target").ok_or_else(|| anyhow!("{name}: channel without target"))?;
        let path = match t.get("path").and_then(|p| p.as_str()).unwrap_or("") {
            "translation" => 0u8,
            "rotation" => 1,
            "scale" => 2,
            _ => continue,
        };
        let node = t.get("node").and_then(|n| n.as_u64()).map(|n| n as usize).filter(|&n| n < nodes.len()).ok_or_else(|| anyhow!("{name}: channel node out of range"))?;
        let s = ch.get("sampler").and_then(|s| s.as_u64()).and_then(|s| samplers.get(s as usize)).ok_or_else(|| anyhow!("{name}: channel sampler out of range"))?;
        let step = match s.get("interpolation").and_then(|i| i.as_str()).unwrap_or("LINEAR") {
            "LINEAR" => false,
            "STEP" => true,
            other => bail!("{name}: {other} interpolation is not handled"),
        };
        let input = s.get("input").and_then(|x| x.as_u64()).ok_or_else(|| anyhow!("{name}: sampler without input"))? as usize;
        let output = s.get("output").and_then(|x| x.as_u64()).ok_or_else(|| anyhow!("{name}: sampler without output"))? as usize;
        let mut times: Vec<f32> = g.floats(input)?.into_iter().map(|v| v[0]).collect();
        let mut values = g.floats(output)?;
        if times.is_empty() || times.len() != values.len() {
            bail!("{name}: {} times for {} values", times.len(), values.len());
        }
        if times.iter().any(|t| !t.is_finite()) || times.windows(2).any(|w| w[1] < w[0]) || values.iter().flatten().any(|v| !v.is_finite()) {
            bail!("{name}: non-finite or unordered keys");
        }
        if step && times.len() > 1 {
            // STEP: each value held until the next key (a key just before it), sampled linearly.
            let (mut t2, mut v2) = (vec![], vec![]);
            for k in 0..times.len() {
                if k > 0 {
                    t2.push((times[k] - 1e-4).max(times[k - 1]));
                    v2.push(values[k - 1]);
                }
                t2.push(times[k]);
                v2.push(values[k]);
            }
            times = t2;
            values = v2;
        }
        if path == 1 {
            for v in &mut values {
                let q = Quat::from_array(*v);
                *v = if q.length_squared() > 1e-8 { q.normalize().to_array() } else { [0.0, 0.0, 0.0, 1.0] };
            }
        }
        start = start.min(times[0]);
        clip.duration = clip.duration.max(*times.last().unwrap());
        let node_name = nodes[node].get("name").and_then(|n| n.as_str()).unwrap_or("").to_string();
        clip.channels.push(Channel { node: node_name, path, times, values });
    }
    if clip.channels.is_empty() {
        bail!("{name}: an empty clip");
    }
    Ok(clip)
}

/// A Rocketbox clip ready to play on any avatar: its channels by node, and the
/// root height of the avatar it was baked on (the pelvis's travel is scaled
/// by the ratio of root heights).
#[derive(Clone, Debug)]
pub struct RbClip {
    pub id: String,
    pub clip: Clip,
    pub root_y: f32,
    pub start: f32,
}

pub fn load_rb_clip(root: &Path, m: &Manifest, id: &str) -> Result<RbClip> {
    let bytes = m.read(root, &clip_file(id))?;
    let g = Glb::parse(&bytes).with_context(|| id.to_string())?;
    let clip = glb_clip(&g, id)?;
    let nodes = rest_nodes(&g);
    let root_y = nodes.iter().find(|n| n.parent.is_none() && n.name.starts_with("Bip01")).map(|n| n.t.y).ok_or_else(|| anyhow!("{id}: no Bip01 root"))?;
    let start = clip.channels.iter().map(|c| c.times[0]).fold(f32::MAX, f32::min);
    for need in ["Bip01 Pelvis", "Bip01 L Thigh", "Bip01 R UpperArm", "Bip01 Head"] {
        if !clip.channels.iter().any(|c| c.node == need && c.path == 1) {
            bail!("{id}: no rotation channel for {need}");
        }
    }
    Ok(RbClip { id: id.to_string(), clip, root_y, start })
}

/// Local rotations of `nodes` (rest where the clip has no channel) and the
/// pelvis translation, at clip time `t`.
pub fn rb_local(c: &RbClip, nodes: &[RestNode], index: &HashMap<&str, usize>, t: f32, pelvis: usize, height_ratio: f32) -> (Vec<Quat>, Vec3) {
    let mut r: Vec<Quat> = nodes.iter().map(|n| n.r).collect();
    let mut pt = nodes[pelvis].t;
    for ch in &c.clip.channels {
        let Some(&i) = index.get(ch.node.as_str()) else { continue };
        match ch.path {
            1 => r[i] = Quat::from_array(c.clip.sample(ch, t)).normalize(),
            0 if i == pelvis => {
                let v = c.clip.sample(ch, t);
                pt = Vec3::new(v[0], v[1], v[2]) * height_ratio;
            }
            _ => {}
        }
    }
    (r, pt)
}

fn nlerp_same(a: Quat, b: Quat, w: f32) -> Quat {
    let b = if a.dot(b) < 0.0 { -b } else { b };
    a.slerp(b, w).normalize()
}

/// The local pose of a standing loop at loop time `u` seconds (0 .. seconds):
/// the window `[start, start + seconds)` of the clip, its seam cross-faded
/// over `LOOP_FADE_S` with the clip just after the window.
pub fn rb_loop_local(c: &RbClip, nodes: &[RestNode], index: &HashMap<&str, usize>, role: &Role, u: f32, pelvis: usize, height_ratio: f32) -> (Vec<Quat>, Vec3) {
    let s0 = c.start + role.start_in(&c.id);
    let fade = LOOP_FADE_S.min(role.seconds * 0.25);
    let (ra, pa) = rb_local(c, nodes, index, s0 + u, pelvis, height_ratio);
    if u >= fade {
        return (ra, pa);
    }
    let (rb, pb) = rb_local(c, nodes, index, s0 + role.seconds + u, pelvis, height_ratio);
    let x = u / fade;
    let w = x * x * (3.0 - 2.0 * x);
    let r = rb.iter().zip(&ra).map(|(b, a)| nlerp_same(*b, *a, w)).collect();
    (r, pb.lerp(pa, w))
}

/// The clip time a role's window needs in clip `id`.
pub fn role_needs_s(role: &Role, id: &str) -> f32 {
    role.start_in(id) + role.seconds + LOOP_FADE_S.min(role.seconds * 0.25)
}

