#[derive(Clone, Debug, Deserialize)]
pub struct ManifestFile {
    pub path: String,
    pub bytes: u64,
    pub sha256: String,
}

#[derive(Clone, Debug, Deserialize)]
pub struct ManifestSource {
    pub dataset: String,
    pub revision: String,
    pub licence: String,
    #[serde(default)]
    pub upstream_commit: String,
    #[serde(default)]
    pub upstream_record: String,
}

#[derive(Clone, Debug, Deserialize)]
pub struct Manifest {
    pub source: ManifestSource,
    pub credit: String,
    pub files: Vec<ManifestFile>,
}

impl Manifest {
    pub fn clips() -> Result<Self> {
        let m: Manifest = serde_json::from_str(CLIPS_MANIFEST_JSON).context("native/assets/rocketbox-motions-manifest.json")?;
        if m.source.licence != "MIT" || m.source.upstream_commit != UPSTREAM_COMMIT || m.source.revision != CLIPS_REVISION {
            bail!("Rocketbox motions manifest: unexpected licence, upstream commit or revision");
        }
        Ok(m)
    }

    pub fn styles() -> Result<Self> {
        let m: Manifest = serde_json::from_str(STYLES_MANIFEST_JSON).context("native/assets/100style-manifest.json")?;
        if m.source.licence != "CC-BY-4.0" || m.source.upstream_record != "https://zenodo.org/records/8127870" || m.source.revision != STYLES_REVISION {
            bail!("100STYLE manifest: unexpected licence, record or revision");
        }
        Ok(m)
    }

    pub fn file(&self, path: &str) -> Option<&ManifestFile> {
        self.files.iter().find(|f| f.path == path)
    }

    /// A manifest file read from `root`, refused unless its length and SHA-256 match.
    pub fn read(&self, root: &Path, rel: &str) -> Result<Vec<u8>> {
        if rel.is_empty() || rel.split('/').any(|c| c.is_empty() || c == "." || c == ".." || !c.chars().all(|ch| ch.is_ascii_alphanumeric() || "-_.".contains(ch))) {
            bail!("refused path {rel}");
        }
        let f = self.file(rel).ok_or_else(|| anyhow!("{rel} is not in the manifest"))?;
        let p = rel.split('/').fold(root.to_path_buf(), |acc, c| acc.join(c));
        let bytes = std::fs::read(&p).with_context(|| format!("reading {}", p.display()))?;
        if bytes.len() as u64 != f.bytes {
            bail!("{rel}: {} bytes, the manifest says {}", bytes.len(), f.bytes);
        }
        let sha = eo_assets::glb::sha256_hex(&bytes);
        if sha != f.sha256 {
            bail!("{rel}: SHA-256 {sha} differs from the manifest");
        }
        Ok(bytes)
    }
}

/// Where the motions come from this run (None: that part is missing).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct MotionRoots {
    pub clips: Option<PathBuf>,
    pub styles: Option<PathBuf>,
}

impl MotionRoots {
    /// The motion folders this run ([`MotionRoots::folders`]) that hold a
    /// copy (`LICENSES.md` and the tier folder); none when switched off.
    pub fn from_env() -> Self {
        if !enabled() {
            return Self::default();
        }
        let (clips, styles) = Self::folders();
        let pick = |p: Option<PathBuf>, tier: &str| -> Option<PathBuf> {
            let p = p?;
            (p.join("LICENSES.md").is_file() && p.join(tier).is_dir()).then_some(p)
        };
        Self { clips: pick(clips, "objects"), styles: pick(styles, "skeleton") }
    }

    /// Where the clips and the walks are looked for: the folders
    /// `EO_PEOPLE_MOTIONS_ROOT` and `EO_PEOPLE_STYLES_ROOT` name, else
    /// `<repo>/external/people-motions` and `<repo>/external/people-styles`.
    pub fn folders() -> (Option<PathBuf>, Option<PathBuf>) {
        (eo_data::external::PEOPLE_MOTIONS.root(), eo_data::external::PEOPLE_STYLES.root())
    }

    pub fn any(&self) -> bool {
        self.clips.is_some() || self.styles.is_some()
    }
}

