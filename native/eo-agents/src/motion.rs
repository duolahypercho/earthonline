/// One closed gait cycle of a style on the source skeleton.
#[derive(Clone, Debug)]
pub struct StyleCycle {
    pub name: String,
    pub phone: bool,
    /// The source skeleton at rest.
    pub nodes: Vec<RestNode>,
    /// `WALK_FRAMES + 1` poses (the last is the first): local rotations of
    /// every source node, and the hips' offset (in place, facing +Z; y is the
    /// hips' height).
    pub frames: Vec<(Vec<Quat>, Vec3)>,
    /// The source's gait cycle: seconds, metres covered, m/s.
    pub seconds: f32,
    pub stride: f32,
    pub speed: f32,
    /// Where the cycle starts in the clip, s; cycles found; turn over the two cycles used, degrees.
    pub from_s: f32,
    pub cycles: usize,
    pub turn_deg: f32,
    /// How much the bake lengthens the stride (the fore-and-aft travel of the feet).
    pub stride_scale: f32,
}

/// Forward kinematics of a node list: world positions and rotations.
pub fn fk(nodes: &[RestNode], order: &[usize], r: &[Quat], root_t: Vec3) -> (Vec<Vec3>, Vec<Quat>) {
    let mut wp = vec![Vec3::ZERO; nodes.len()];
    let mut wr = vec![Quat::IDENTITY; nodes.len()];
    for &i in order {
        let n = &nodes[i];
        match n.parent {
            Some(p) => {
                wp[i] = wp[p] + wr[p] * (n.t * nodes[p].s);
                wr[i] = wr[p] * r[i];
            }
            None => {
                wp[i] = root_t;
                wr[i] = r[i];
            }
        }
    }
    (wp, wr)
}

/// Node indices, parents before children.
pub fn topo_nodes(nodes: &[RestNode]) -> Vec<usize> {
    let n = nodes.len();
    let mut order = vec![];
    let mut placed = vec![false; n];
    let mut guard = 0;
    while order.len() < n && guard < n + 2 {
        guard += 1;
        for i in 0..n {
            if !placed[i] && nodes[i].parent.is_none_or(|p| p >= n || placed[p]) {
                placed[i] = true;
                order.push(i);
            }
        }
    }
    order
}

/// Cut one closed gait cycle out of a style's forward walk. The take walks
/// round the capture room, so the walk is made in place against its own
/// smoothed path (the hips' mean over a cycle), each frame turned by that
/// path's heading: what is left is the sway and surge of the hips about a
/// steady, straight line, whatever the room made the performer do.
pub fn extract_cycle(name: &str, phone: bool, nodes: &[RestNode], clip: &Clip) -> Result<StyleCycle> {
    let index: HashMap<&str, usize> = nodes.iter().enumerate().map(|(i, n)| (n.name.as_str(), i)).collect();
    let get = |n: &str| index.get(n).copied().ok_or_else(|| anyhow!("{name}: no source joint {n}"));
    let hips = get("Hips")?;
    if nodes[hips].parent.is_some() {
        bail!("{name}: Hips is not the root");
    }
    let la = get("LeftAnkle")?;
    let order = topo_nodes(nodes);
    let chan: Vec<Option<&Channel>> = (0..nodes.len()).map(|i| clip.channels.iter().find(|c| c.path == 1 && c.node == nodes[i].name)).collect();
    let root_ch = clip.channels.iter().find(|c| c.path == 0 && c.node == "Hips").ok_or_else(|| anyhow!("{name}: no root motion on Hips"))?;
    let local = |t: f32| -> (Vec<Quat>, Vec3) {
        let r: Vec<Quat> = (0..nodes.len()).map(|i| chan[i].map(|c| Quat::from_array(clip.sample(c, t)).normalize()).unwrap_or(nodes[i].r)).collect();
        let v = clip.sample(root_ch, t);
        (r, Vec3::new(v[0], v[1], v[2]))
    };
    // Sample the whole take at 60 Hz.
    let hz = 60.0f32;
    let t0 = root_ch.times[0];
    let n = ((clip.duration - t0) * hz).floor() as usize;
    if n < 600 {
        bail!("{name}: {:.1} s of walk is too short", n as f32 / hz);
    }
    let mut root = Vec::with_capacity(n);
    let mut lpos = Vec::with_capacity(n);
    for k in 0..n {
        let (r, rt0) = local(t0 + k as f32 / hz);
        let (wp, _) = fk(nodes, &order, &r, rt0);
        root.push(wp[hips]);
        lpos.push(wp[la]);
    }
    let flat = |v: Vec3| Vec3::new(v.x, 0.0, v.z);
    let speed_of = |p: &[Vec3], k: usize, h: usize| -> f32 {
        let (a, b) = (k.saturating_sub(h), (k + h).min(p.len() - 1));
        flat(p[b] - p[a]).length() * hz / (b - a).max(1) as f32
    };
    let mut sorted: Vec<f32> = (0..n).map(|k| speed_of(&root, k, 15)).collect();
    sorted.sort_by(f32::total_cmp);
    // The take slows at the room's ends: the steady walking speed is its upper quartile.
    let v_ref = sorted[3 * n / 4];
    if !(v_ref > 0.3) {
        bail!("{name}: the root hardly moves ({v_ref:.2} m/s)");
    }
    let ground = {
        let mut h: Vec<f32> = lpos.iter().map(|p| p.y).collect();
        h.sort_by(f32::total_cmp);
        h[n / 50]
    };
    // Left heel strikes: the left ankle slows below a third of the walking
    // speed near its lowest after a swing.
    let thr = 0.35 * v_ref;
    let mut strikes: Vec<usize> = vec![];
    let mut swinging = false;
    for k in 2..n - 2 {
        let s = speed_of(&lpos, k, 2);
        if s > 1.2 * v_ref {
            swinging = true;
        }
        if swinging && s < thr && lpos[k].y < ground + 0.05 {
            if strikes.last().is_none_or(|&l| k - l > (0.5 * hz) as usize) {
                strikes.push(k);
            }
            swinging = false;
        }
    }
    if strikes.len() < 6 {
        bail!("{name}: {} left heel strikes found (walking {v_ref:.2} m/s)", strikes.len());
    }
    let mut periods: Vec<usize> = strikes.windows(2).map(|w| w[1] - w[0]).collect();
    periods.sort_unstable();
    let w = periods[periods.len() / 2].max(30);
    // The smoothed path: the hips' mean over one cycle, and its heading.
    let mut pre = vec![Vec3::ZERO; n + 1];
    for k in 0..n {
        pre[k + 1] = pre[k] + flat(root[k]);
    }
    let path: Vec<Vec3> = (0..n)
        .map(|k| {
            let (a, b) = (k.saturating_sub(w / 2), (k + w / 2 + 1).min(n));
            (pre[b] - pre[a]) / (b - a) as f32
        })
        .collect();
    let heading: Vec<f32> = (0..n)
        .map(|k| {
            let d = path[(k + 6).min(n - 1)] - path[k.saturating_sub(6)];
            d.x.atan2(d.z)
        })
        .collect();
    let wrap = |a: f32| -> f32 { (a + std::f32::consts::PI).rem_euclid(std::f32::consts::TAU) - std::f32::consts::PI };
    let arc = |a: usize, b: usize| -> f32 { (a..b).map(|k| (path[k + 1] - path[k]).length()).sum() };
    let turn_of = |a: usize, b: usize| -> f32 { (a..b).map(|k| wrap(heading[k + 1] - heading[k]).abs()).sum::<f32>().to_degrees() };
    // The best cycle: steady and straight, with a like cycle before it (the loop is closed with it).
    let mut best: Option<(f32, usize)> = None;
    for j in 1..strikes.len() - 1 {
        let (p, a, b) = (strikes[j - 1], strikes[j], strikes[j + 1]);
        if a < w || b + w >= n {
            continue;
        }
        let (tp, ta) = ((a - p) as f32 / hz, (b - a) as f32 / hz);
        if !(0.6..1.7).contains(&tp) || !(0.6..1.7).contains(&ta) {
            continue;
        }
        let (va, vp) = (arc(a, b) / ta, arc(p, a) / tp);
        let turn = turn_of(p, b);
        if turn > 60.0 || (va - vp).abs() > 0.2 * va || (va - v_ref).abs() > 0.4 * v_ref {
            continue;
        }
        let score = (va - v_ref).abs() / v_ref + (ta - tp).abs() / ta + turn / 20.0;
        if best.is_none_or(|(s, _)| score < s) {
            best = Some((score, j));
        }
    }
    if std::env::var_os("EO_MOTION_DEBUG").is_some() {
        for j in 1..strikes.len() - 1 {
            let (p, a, b) = (strikes[j - 1], strikes[j], strikes[j + 1]);
            let ta = (b - a) as f32 / hz;
            eprintln!("{name} cycle {j} at {:.1} s: {ta:.2} s, {:.2} m/s (prev {:.2}), turn {:.1} deg (with prev)", a as f32 / hz, arc(a, b) / ta, arc(p, a) / ((a - p) as f32 / hz), turn_of(p, b));
        }
    }
    let (_, j) = best.ok_or_else(|| anyhow!("{name}: no straight, steady cycle among {} strikes (walking {v_ref:.2} m/s)", strikes.len()))?;
    let (p, a, b) = (strikes[j - 1], strikes[j], strikes[j + 1]);
    let ta = (b - a) as f32 / hz;
    let at = |v: &[f32], k: f32| -> f32 {
        let i = (k.floor() as usize).min(n - 2);
        let f = k - i as f32;
        v[i] + wrap(v[i + 1] - v[i]) * f
    };
    let at3 = |v: &[Vec3], k: f32| -> Vec3 {
        let i = (k.floor() as usize).min(n - 2);
        v[i].lerp(v[i + 1], k - i as f32)
    };
    // A frame `k` (60 Hz samples, fractional) in place, facing +Z.
    let pose = |k: f32| -> (Vec<Quat>, Vec3) {
        let (mut r, rt0) = local(t0 + k / hz);
        let yaw = Quat::from_rotation_y(-at(&heading, k));
        r[hips] = (yaw * r[hips]).normalize();
        let off = yaw * flat(rt0 - at3(&path, k));
        (r, Vec3::new(off.x, rt0.y, off.z))
    };
    let mut frames = Vec::with_capacity(WALK_FRAMES as usize + 1);
    for f in 0..WALK_FRAMES {
        let u = f as f32 / WALK_FRAMES as f32;
        let (qa, oa) = pose(a as f32 + u * (b - a) as f32);
        let (qb, ob) = pose(p as f32 + u * (a - p) as f32);
        let r: Vec<Quat> = qa.iter().zip(&qb).map(|(x, y)| nlerp_same(*x, *y, u)).collect();
        frames.push((r, oa.lerp(ob, u)));
    }
    frames.push(frames[0].clone());
    let stride = arc(a, b);
    // The takes walk slower than the street (0.6-1.0 m/s against 0.95-1.65): the
    // bake lengthens the stride by up to a third, the cadence makes the rest.
    let stride_scale = (STREET_PACE / (stride / ta)).sqrt().clamp(1.0, MAX_STRIDE_SCALE);
    Ok(StyleCycle { name: name.to_string(), phone, nodes: nodes.to_vec(), frames, seconds: ta, stride, speed: stride / ta, from_s: t0 + a as f32 / hz, cycles: strikes.len() - 1, turn_deg: turn_of(p, b), stride_scale })
}


