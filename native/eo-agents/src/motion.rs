/// One standing loop: its slot, the clip for women and for men, the window
/// cut from it and the rate it is baked at.
#[derive(Clone, Copy, Debug)]
pub struct Role {
    pub name: &'static str,
    pub slot: usize,
    pub family: Family,
    pub female: &'static str,
    pub male: &'static str,
    /// Window start in the women's clip and in the men's, seconds.
    pub start_s: f32,
    pub start_m: f32,
    pub seconds: f32,
    pub fps: f32,
    /// What the bake changes on every frame of the window (`pose_edit`).
    pub edit: Edit,
}

/// A bake-time edit of a standing loop (`crate::pose_edit`): what a player's
/// emote needs that no Rocketbox take holds as it is.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Edit {
    None,
    /// A one-arm wave over a standing loop: the right arm (clavicle to
    /// fingertips) as it is at one instant of another take (`at_f`, `at_m`
    /// seconds into the women's and the men's), the forearm swung about the
    /// elbow across the body's front, `swing_deg` each way, `cycles` times a loop.
    Wave { female: &'static str, male: &'static str, at_f: f32, at_m: f32, cycles: u32, swing_deg: f32 },
    /// The pointing hand: the index finger straight, the other fingers and
    /// the thumb curled; the head and neck turned toward where the arm points.
    Point,
    /// A selfie over a standing loop: the right arm reaches out and up in
    /// front of the face (two-bone IK), the hand turned to hold a phone
    /// toward the face, its fingers round the phone, the head toward it.
    Selfie,
}

#[allow(clippy::too_many_arguments)]
const fn role(name: &'static str, slot: usize, family: Family, female: &'static str, male: &'static str, start_s: f32, start_m: f32, seconds: f32, fps: f32) -> Role {
    Role { name, slot, family, female, male, start_s, start_m, seconds, fps, edit: Edit::None }
}

impl Role {
    /// Where the window starts in clip `id`.
    pub fn start_in(&self, id: &str) -> f32 {
        if id == self.male && id != self.female { self.start_m } else { self.start_s }
    }

    const fn with(self, edit: Edit) -> Role {
        Role { edit, ..self }
    }

    /// Every take this loop reads (its own, and an edit's other take).
    pub fn clips(&self) -> Vec<&'static str> {
        let mut v = vec![self.female, self.male];
        if let Edit::Wave { female, male, .. } = self.edit {
            v.push(female);
            v.push(male);
        }
        v
    }

    /// The edit's other take for a women's (`female`) or men's skeleton, and the instant read from it.
    pub fn layer(&self, female: bool) -> Option<(&'static str, f32)> {
        match self.edit {
            Edit::Wave { female: f, male: m, at_f, at_m, .. } => Some(if female { (f, at_f) } else { (m, at_m) }),
            _ => None,
        }
    }
}

