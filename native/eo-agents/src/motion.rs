impl MotionMeta {
    pub fn styled(&self) -> bool {
        self.walk_frames > 0 && !self.styles.is_empty()
    }

    pub fn looped(&self, slot: usize) -> bool {
        self.loops.get(slot).is_some_and(|l| !l.is_empty())
    }

    pub fn any(&self) -> bool {
        self.styled() || (1..CLIPS).any(|s| self.looped(s))
    }

    /// The instance's `anim` for a walk style at cycle phase 0..1 (0 = left heel strike).
    pub fn walk_anim(&self, style: usize, phase: f64) -> f32 {
        if !self.styled() {
            return phase.rem_euclid(1.0) as f32;
        }
        let stride = (self.walk_frames + 1) as f64;
        let n = self.styles.len() as f64;
        let s = style.min(self.styles.len() - 1) as f64;
        let u = phase.rem_euclid(1.0).min(1.0 - 1e-5);
        // A thousandth of a frame in from each end: the f32 the shader floors stays inside the loop.
        ((s * stride + 1e-3 + u * (self.walk_frames as f64 - 2e-3)) / (n * stride)) as f32
    }

    /// The instance's `clip_phase` for loop `l` of a standing slot at loop phase 0..1.
    pub fn clip_phase(&self, slot: usize, l: usize, u: f64) -> f32 {
        let u = u.rem_euclid(1.0);
        if !self.looped(slot) {
            return u as f32;
        }
        let lp = &self.loops[slot][l.min(self.loops[slot].len() - 1)];
        let total = self.slot_frames[slot].max(1) as f64;
        ((lp.first as f64 + 1e-3 + u.min(1.0 - 1e-5) * (lp.frames as f64 - 2e-3)) / total) as f32
    }

    pub fn loop_seconds(&self, slot: usize, l: usize) -> f64 {
        self.loops.get(slot).and_then(|v| v.get(l)).map(|lp| lp.seconds as f64).unwrap_or(0.0)
    }

    /// A loop of `family` for the walker keyed `key` (slot, loop).
    pub fn pick_loop(&self, family: Family, key: &str) -> Option<(usize, usize)> {
        let all: Vec<(usize, usize)> = (1..CLIPS).flat_map(|s| self.loops[s].iter().enumerate().filter(|(_, l)| l.family == family).map(move |(i, _)| (s, i))).collect();
        if all.is_empty() {
            return None;
        }
        let r = eo_sim::rng::keyed_random(key, &format!("motion-loop-{family:?}"));
        Some(all[((r * all.len() as f64) as usize).min(all.len() - 1)])
    }

    /// Stride (m a cycle) and natural speed (m/s) of `style` for person `pool` at scale 1.
    pub fn walk_of(&self, pool: usize, style: usize) -> [f32; 2] {
        let g = self.person_group.get(pool).copied().unwrap_or(0) as usize;
        self.group_walk.get(g).and_then(|v| v.get(style)).copied().unwrap_or([1.4, 1.3])
    }

    /// The walk style of a walker keyed `key` at `pace` m/s, drawn per walker
    /// among the styles whose natural pace on this body is close to it (the
    /// cadence then stays close to the style's own): within -22 / +32 %, else
    /// the window widens until three styles fit; the phone styles while on the phone.
    pub fn pick_style(&self, pool: usize, pace: f64, scale: f32, phone: bool, key: &str) -> usize {
        let n = self.styles.len();
        if n == 0 {
            return 0;
        }
        let want_phone = phone && self.styles.iter().any(|s| s.phone);
        let ratio = |i: usize| pace / (self.walk_of(pool, i)[1] as f64 * scale as f64).max(0.1);
        let cands: Vec<usize> = (0..n).filter(|&i| self.styles[i].phone == want_phone).collect();
        let need = 3.min(cands.len()).max(1);
        let mut fits: Vec<usize> = vec![];
        for widen in [1.0f64, 1.15, 1.3, 1.5, 2.0, 100.0] {
            fits = cands.iter().copied().filter(|&i| (0.78 / widen..=1.32 * widen).contains(&ratio(i))).collect();
            if fits.len() >= need {
                break;
            }
        }
        if fits.is_empty() {
            return cands.first().copied().unwrap_or(0);
        }
        let salt = if want_phone { "motion-walk-style-phone" } else { "motion-walk-style" };
        let r = eo_sim::rng::keyed_random(key, salt);
        fits[((r * fits.len() as f64) as usize).min(fits.len() - 1)]
    }
}

/// One walker's motion state on the feed thread.
#[derive(Clone, Copy, Debug, Default)]
pub struct WalkerMotion {
    pub style: Option<usize>,
    pub phone_style: bool,
    pub phase: f64,
    /// The sim's gait phase last seen (cycles, 0..1) and the walker's pace.
    pub last_gait: f64,
    pub pace: f64,
    pub seen: bool,
    /// The loop drawn per `Family` (slot, loop), once.
    pub loops: [Option<(u8, u8)>; FAMILIES],
}

/// The key the walker's draws hang on (as the feed's other picks).
pub fn walker_key(id: u32) -> String {
    format!("ambient-{id}")
}

/// What the sim's activity (`eo_sim::consts::Activity`) asks of a standing
/// walker: at the kerb or waiting, waiting; talking, talk or listen
/// (alternating within a group, whose members' ids follow each other); on
/// the phone, a call (three in five) or texting; standing, browsing or
/// carrying, standing about.
pub fn standing_family(activity: u16, flags: u32, id: u32) -> Family {
    if flags & eo_sim::output::FLAG_KERB_WAIT as u32 != 0 {
        return Family::Wait;
    }
    match activity {
        1 => Family::Wait,
        2 if id % 2 == 0 => Family::Talk,
        2 => Family::Listen,
        3 if eo_sim::rng::keyed_random(&walker_key(id), "motion-phone-call") < 0.6 => Family::Call,
        3 => Family::Text,
        _ => Family::Idle,
    }
}

/// The standing loop for this walker now (drawn once per family), or None
/// when the slots hold no loops.
pub fn standing(m: &MotionMeta, w: &mut WalkerMotion, activity: u16, flags: u32, id: u32) -> Option<(usize, usize)> {
    let mut fam = standing_family(activity, flags, id);
    if m.steady && fam == Family::Text {
        // (`--people-motion`) the texting clip looks down at a phone no one is drawn holding.
        fam = Family::Call;
    }
    let i = fam as usize;
    if let Some((s, l)) = w.loops[i] {
        return Some((s as usize, l as usize));
    }
    // A family with no loop of its own stands about.
    let (s, l) = m.pick_loop(fam, &walker_key(id)).or_else(|| m.pick_loop(Family::Idle, &walker_key(id)))?;
    w.loops[i] = Some((s as u8, l as u8));
    Some((s, l))
}

/// The walk for one walker this frame: the style (drawn on its first steps,
/// redrawn when it takes out or puts away its phone) and the cycle phase,
/// advanced by the distance the sim walked it (its gait phase is one cycle
/// per `gait::stride(pace)` metres) over the stride this style covers on
/// this body. Returns the instance's `anim`.
#[allow(clippy::too_many_arguments)]
pub fn walk_step(m: &MotionMeta, w: &mut WalkerMotion, pool: usize, id: u32, gait_cycles: f64, speed: f64, scale: f32, phone: bool) -> f32 {
    let gait = gait_cycles.rem_euclid(1.0);
    if speed > 0.05 {
        w.pace = speed;
    }
    if w.pace > 0.05 && (w.style.is_none() || w.phone_style != phone) {
        let s = m.pick_style(pool, w.pace, scale, phone, &walker_key(id));
        w.phone_style = phone;
        w.style = Some(s);
    }
    let style = w.style.unwrap_or(0);
    if !w.seen {
        w.phase = gait;
        w.seen = true;
    } else {
        // The sim's gait advances only while it walks; less than a cycle passes between frames.
        let dc = (gait - w.last_gait).rem_euclid(1.0);
        if w.pace > 0.05 && dc < 0.9 {
            let sim_stride = crate::gait::stride(w.pace, crate::gait::REFERENCE_HEIGHT_M);
            let s = m.walk_of(pool, style)[0] as f64 * scale as f64;
            w.phase = (w.phase + dc * sim_stride / s.max(0.2)).rem_euclid(1.0);
        }
    }
    w.last_gait = gait;
    m.walk_anim(style, w.phase)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The motion folders are `<repo>/external/people-motions` and
    /// `people-styles` unless their variables name others.
    #[test]
    fn motion_folders_default_to_external() {
        let repo = eo_data::DataPaths::discover().expect("the repository").repo_root;
        let (clips, styles) = MotionRoots::folders();
        for (env, dir, got) in [(CLIPS_ROOT_ENV, "people-motions", clips), (STYLES_ROOT_ENV, "people-styles", styles)] {
            match std::env::var_os(env).filter(|v| !v.is_empty()) {
                Some(v) => assert_eq!(got, Some(PathBuf::from(v)), "{env}"),
                None => assert_eq!(got, Some(repo.join("external").join(dir)), "{env}"),
            }
        }
    }

    fn meta() -> MotionMeta {
        let mut m = MotionMeta { walk: "100style".into(), walk_frames: WALK_FRAMES, ..Default::default() };
        m.styles = (0..5).map(|i| StyleMeta { name: format!("s{i}"), phone: i == 4, ..Default::default() }).collect();
        m.loops[1] = vec![LoopMeta { role: "a".into(), family: Family::Idle, first: 0, frames: 100, seconds: 10.0, ..Default::default() }, LoopMeta { role: "b".into(), family: Family::Wait, first: 101, frames: 120, seconds: 12.0, ..Default::default() }];
        m.slot_frames = [5 * 33, 222, 0, 0];
        m.person_group = vec![0];
        m.group_walk = vec![vec![[1.4, 1.3], [1.4, 1.25], [1.4, 1.35], [0.8, 0.7], [1.3, 1.2]]];
        m
    }

    #[test]
    fn phases_stay_inside_their_loop() {
        let m = meta();
        // The shader's frame pair (floor(f), floor(f) + 1) never leaves the loop.
        for style in 0..5 {
            for k in 0..=1000 {
                let ph = k as f64 / 1000.0;
                let f = m.walk_anim(style, ph) as f64 * m.slot_frames[0] as f64;
                let f0 = f.floor() as u32;
                assert!(f0 >= style as u32 * 33 && f0 + 1 <= style as u32 * 33 + 32, "style {style} phase {ph}: frames {f0}, {}", f0 + 1);
            }
        }
        for (l, (first, n)) in [(0usize, (0u32, 100u32)), (1, (101, 120))] {
            for k in 0..=1000 {
                let f = m.clip_phase(1, l, k as f64 / 1000.0) as f64 * 222.0;
                let f0 = f.floor() as u32;
                assert!(f0 >= first && f0 + 1 <= first + n, "loop {l}: frames {f0}, {}", f0 + 1);
            }
        }
        // Today's layout: the phase as it was.
        let old = MotionMeta::default();
        assert_eq!(old.walk_anim(5, 0.25), 0.25);
        assert_eq!(old.clip_phase(1, 3, 1.75), 0.75);
    }

    /// (`--people-motion`) a texting walker takes a call instead (no phone is
    /// drawn in a hand); without it, the texting loop as before.
    #[test]
    fn steady_texters_take_a_call() {
        let mut m = meta();
        m.loops[3] = vec![
            LoopMeta { role: "call".into(), family: Family::Call, first: 0, frames: 100, seconds: 10.0, ..Default::default() },
            LoopMeta { role: "text".into(), family: Family::Text, first: 101, frames: 100, seconds: 10.0, ..Default::default() },
        ];
        // walkers whose phone draw is a text (activity 3)
        let texters: Vec<u32> = (0..200).filter(|&id| standing_family(3, 0, id) == Family::Text).collect();
        assert!(!texters.is_empty());
        for &id in &texters {
            let mut w = WalkerMotion::default();
            assert_eq!(standing(&m, &mut w, 3, 0, id), Some((3, 1)), "texting as before");
            m.steady = true;
            let mut w = WalkerMotion::default();
            assert_eq!(standing(&m, &mut w, 3, 0, id), Some((3, 0)), "a call");
            m.steady = false;
        }
    }

    #[test]
    fn styles_fit_the_pace() {
        let m = meta();
        // 1.3 m/s: styles 0-2 (1.25-1.35 m/s) are drawn, style 3 (0.7 m/s) never; the phone style on the phone.
        let mut seen = [0; 5];
        for id in 0..300 {
            seen[m.pick_style(0, 1.3, 1.0, false, &format!("ambient-{id}"))] += 1;
            assert_eq!(m.pick_style(0, 1.3, 1.0, true, &format!("ambient-{id}")), 4);
        }
        assert!(seen[0] > 50 && seen[1] > 50 && seen[2] > 50 && seen[3] == 0 && seen[4] == 0, "{seen:?}");
        // A slow walker gets the slow style among others.
        assert!((0..300).any(|id| m.pick_style(0, 0.75, 1.0, false, &format!("ambient-{id}")) == 3));
        // The walk advances by distance over the stride: 10 m at 1.3 m/s on a 1.4 m stride is 7.14 cycles.
        let mut w = WalkerMotion::default();
        let sim_stride = crate::gait::stride(1.3, crate::gait::REFERENCE_HEIGHT_M);
        let mut gait = 0.0;
        walk_step(&m, &mut w, 0, 1, gait, 1.3, 1.0, false);
        let p0 = w.phase;
        let mut walked = 0.0;
        while walked < 10.0 - 1e-9 {
            walked += 0.05;
            gait += 0.05 / sim_stride;
            walk_step(&m, &mut w, 0, 1, gait, 1.3, 1.0, false);
        }
        let cycles = (10.0f64 / 1.4).fract();
        assert!(((w.phase - p0).rem_euclid(1.0) - cycles).abs() < 1e-6, "phase moved {} cycles, want {cycles}", (w.phase - p0).rem_euclid(1.0));
    }
}
