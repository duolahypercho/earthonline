//! the people's motion: the Rocketbox people's own clips for standing
//! still, and walk styles from 100STYLE, cooked into baked joint-matrix tables.
//!
//! Sources, not in Git (`scripts/setup-assets.py` fetches them into
//! `<repo>/external/`; each variable below names another folder instead),
//! each file checked against its manifest (byte length + SHA-256) before it
//! is parsed; nothing in them runs:
//!   * `external/people-motions`, or `EO_PEOPLE_MOTIONS_ROOT`:
//!     CodePawl's `rocketbox-motions-glb`, `objects/` tier, pinned in
//!     `assets/rocketbox-motions-manifest.json`: the 326 in-place clips of the
//!     Microsoft Rocketbox library (MIT), each on a Rocketbox avatar's own
//!     80-bone copy of the Bip01 skeleton.
//!   * `external/people-styles`, or `EO_PEOPLE_STYLES_ROOT`:
//!     CodePawl's `100style-glb`, `skeleton/` tier, pinned in
//!     `assets/100style-manifest.json`: the forward walks of the `STYLES`
//!     below on the 23-joint source skeleton (CC BY 4.0, The 100STYLE Dataset
//!     - Ian Mason).
//!
//! Both are needed: there is no other motion. Either folder missing (or
//! `--no-rocketbox-motions`) and no people are drawn; the log says why in
//! one line.
//!
//! WHY NO RETARGET FOR THE ROCKETBOX CLIPS: they were captured on the Bip01
//! skeleton the avatars are rigged to (same joint names, hierarchy and bone
//! axes), so a clip's local rotations drive an avatar's own nodes as an
//! AnimationMixer would bind them; each avatar keeps its bind and bone
//! lengths, the pelvis's travel is scaled by the root height. Women have no phone call clip of their own: the
//! men's call clips play on the women's skeleton (same joints; the hand
//! reaches the ear, checked in the tests).
//!
//! WHY 100STYLE FOR THE WALK (retargeted, at cook time): the Rocketbox walks
//! carry root motion and are not in the downloaded clip set; 100STYLE has one
//! performer walking in a hundred manners, about a fifth of them ordinary
//! street walking. One gait cycle is cut from each style's forward walk
//! (left heel strike to left heel strike, on a straight, steady stretch),
//! made in place (the hips less the cycle's mean travel), turned to face +Z
//! and closed into a seamless loop (cross-faded over the cycle with the
//! cycle before it), then retargeted onto each Bip01 proportion group (world
//! rotation changes from the source T-pose, limbs
//! lined up at rest, the torso keeps the avatar's posture, the hips' travel
//! scaled by the leg length; the fingers take the relaxed hand of the
//! group's idle clip, the capture has none). The stride a style covers on
//! each body is measured from the bake (the planted foot's travel over a
//! cycle), and the feed advances each walker's cycle by distance over that
//! stride, so the planted foot stays put at any pace and on any body.
//!
//! THE TABLE LAYOUT: the vertex shader reads a
//! walk slot and three standing slots, `clip_frames[slot]` frames from
//! `clip_base[slot]`, at `fract(phase) * frames` (the walk from the instance's
//! `anim`, the standing slot from its `clip_phase`) and blends that frame with
//! the next. Here each slot holds several loops back to back (the walk: one a
//! style; standing: the loops of `ROLES`), each closed by a copy of its first
//! frame, and the feed hands the shader a phase inside one loop's range
//! (`MotionMeta::walk_anim`, `MotionMeta::clip_phase`), so the frame pair it
//! blends never crosses into the next loop. Four frame fetches a vertex (see
//! `Meta::people_bone_bytes` for the tables' size).

