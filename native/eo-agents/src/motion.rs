/// The performer carries the head pitched down in every take (about 20
/// degrees in the Neutral walk, against the T-pose the rotations are
/// measured from): the Neutral cycle's mean neck and head rotations are
/// taken out of every style's, so a neutral walker looks ahead and a style
/// keeps only its own difference (Depressed and Monk still bow, LookUp still
/// looks up). Returns the levelling, degrees (none without a Neutral cycle).
pub fn level_heads(styles: &mut [StyleCycle]) -> Option<f32> {
    let reference = styles.iter().find(|c| c.name == "Neutral")?;
    let mut fix = vec![];
    for joint in ["Neck", "Head"] {
        let i = reference.nodes.iter().position(|n| n.name == joint)?;
        let first = reference.frames[0].0[i];
        let sum = reference.frames[..reference.frames.len() - 1].iter().fold(glam::Vec4::ZERO, |acc, (r, _)| {
            let q = if r[i].dot(first) < 0.0 { -r[i] } else { r[i] };
            acc + glam::Vec4::from(q)
        });
        fix.push((joint, Quat::from_vec4(sum).normalize()));
    }
    let angle = fix.iter().map(|(_, q)| q.angle_between(Quat::IDENTITY).to_degrees()).sum();
    for c in styles.iter_mut() {
        for (joint, q) in &fix {
            let Some(i) = c.nodes.iter().position(|n| n.name == *joint) else { continue };
            for (r, _) in c.frames.iter_mut() {
                r[i] = (q.inverse() * r[i]).normalize();
            }
        }
    }
    Some(angle)
}

/// A style's cycle from its verified file's bytes.
pub fn style_from_bytes(bytes: &[u8], style: &str, phone: bool) -> Result<StyleCycle> {
    let g = Glb::parse(bytes).with_context(|| style.to_string())?;
    let nodes = rest_nodes(&g);
    if nodes.len() > 64 {
        bail!("{style}: {} nodes", nodes.len());
    }
    let clip = glb_clip(&g, style)?;
    extract_cycle(style, phone, &nodes, &clip)
}

