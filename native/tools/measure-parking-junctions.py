#!/usr/bin/env python3
"""Restore shared OpenStreetMap nodes lost when parking aisle centrelines were simplified."""
import argparse
import gzip
import hashlib
import itertools
import json
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[2]
WAYS = "327668380v3,327668381v2,503951600v4,504295551v4,504298662v3,504298663v2,504298664v3,762905203v2,762905205v2,762905206v2,762905207v2,762905210v2,1155389262v2,1155389263v2,1202321080v1,1202321081v1,1202321085v1,1202321086v1,1202321088v1,1526074145v1"
NODES = "3344714431v1,3344714432v1,3344714433v1,3344714434v3,3344714435v1,3344714436v1,4941850558v1,4941850561v1,4941850564v1,7128815692v1,7128815694v1,7128815695v1,7128815697v1,7128815698v1,7128815699v1,10744838688v1,11146348679v1,11146348683v1,11146348701v1,11146348704v1,11146350806v1,11146350811v1"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=ROOT / "external/survey/parking-junctions")
    cache = parser.parse_args().cache
    cache.mkdir(parents=True, exist_ok=True)
    notice = ["OpenStreetMap contributors, ODbL 1.0.", "https://www.openstreetmap.org/copyright",
              "Elevated parking aisle junctions. Each pair contains the same node in both versioned way records."]
    def fetch(kind, refs):
        url = f"https://api.openstreetmap.org/api/0.6/{kind}.json?{kind}={refs}"
        file = cache / (hashlib.sha256(url.encode()).hexdigest() + ".json")
        if not file.exists():
            with urlopen(url, timeout=60) as response:
                file.write_bytes(response.read())
        data = file.read_bytes()
        elements = json.loads(data)["elements"]
        assert {f"{w['id']}v{w['version']}" for w in elements} == set(refs.split(","))
        notice.extend([url, "SHA-256 " + hashlib.sha256(data).hexdigest()])
        return elements
    ways = sorted(fetch("ways", WAYS), key=lambda w: w["id"])
    nodes = {v["id"]: v for v in fetch("nodes", NODES)}
    with gzip.open(ROOT / "public/data/sf/sf-city.json.gz") as f:
        meta = json.load(f)["meta"]
    c, p = meta["center"], meta["projection"]
    lines = ["//! Generated by native/tools/measure-parking-junctions.py.",
             "//! Each pair of ways shares this mapped node in source plan metres.",
             "pub const CONNECTIONS: &[(&str, &str, [f64; 2])] = &["]
    for a,b in itertools.combinations(ways,2):
        for n in sorted(set(a["nodes"]) & set(b["nodes"])):
            pt = nodes[n]
            x = (pt["lon"]-c["lon"])*p["metersPerDegreeLon"]
            z = (c["lat"]-pt["lat"])*p["metersPerDegreeLat"]
            lines.append(f'    ("{a["id"]}", "{b["id"]}", [{x:.3f}, {z:.3f}]), // OSM node {n}')
    lines.append("];")
    output = ROOT / "native/eo-data/src/parking_junctions.rs"
    output.write_text("\n".join(lines)+"\n")
    notice.append("Output SHA-256 " + hashlib.sha256(output.read_bytes()).hexdigest())
    (ROOT/"native/eo-data/data/parking-junctions.NOTICE.txt").write_text("\n".join(notice)+"\n")

if __name__ == "__main__":
    main()
