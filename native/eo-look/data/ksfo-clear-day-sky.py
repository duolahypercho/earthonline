#!/usr/bin/env python3
"""Regenerate ksfo-clear-day-sky.csv: per month, how San Francisco airport's
clear days split into cloudless, cirrus-only and fair (scattered low cloud).

Input: the routine hourly METARs of KSFO, 2014-2023, as the Iowa Environmental
Mesonet archives them (NOAA/NWS ASOS observations, public domain). The file is
not tracked; give its path in EO_KSFO_METAR_CSV. It is the answer to this query
(fetched 2026-11-18; the digest below pins it):

  https://mesonet.agron.iastate.edu/cgi-bin/request/asos.py?station=SFO
    &data=skyc1&data=skyc2&data=skyc3&data=skyc4
    &data=skyl1&data=skyl2&data=skyl3&data=skyl4
    &year1=2014&month1=1&day1=1&year2=2024&month2=1&day2=1
    &tz=America%2FLos_Angeles&format=onlycomma&latlon=no&elev=no
    &missing=M&trace=T&direct=no&report_type=3

Method (each threshold INFERRED, see the CSV's header): the reports of 10:00 to
16:59 local time; a day with fewer than five is left out. A day with broken,
overcast or obscured sky under 18,000 ft in over half its reports is not a
clear day (the weather's clear rung) and is counted apart. Of the rest, a day
with scattered or more cloud under 18,000 ft in two or more reports is fair,
else one with any layer at or over 18,000 ft (cirrus height) in two or more is
cirrus, else cloudless.

With --amount it writes ksfo-cirrus-amount.csv instead: per month, the
cirrus days above split by the day's high-cloud amount, the METAR sky-cover
code of the most covering layer at or over 18,000 ft, its median over the
reports that carry one (FEW 1-2 oktas, SCT 3-4, BKN 5-7, OVC 8: WMO Manual on
Codes, WMO-No. 306, Vol. I.1, FM 15 METAR regulation 15.9.1.1; the NWS
Federal Meteorological Handbook No. 1, chapter 9, uses the same eighths).

Usage: EO_KSFO_METAR_CSV=<path> python3 ksfo-clear-day-sky.py > ksfo-clear-day-sky.csv
       EO_KSFO_METAR_CSV=<path> python3 ksfo-clear-day-sky.py --amount > ksfo-cirrus-amount.csv
"""
import collections
import csv
import hashlib
import os
import sys

EXPECTED_SHA256 = "108ab81bc11ac6cf8ef58b97fee005e138fea602cef8709dd3c7ccab1bf50e54"
HIGH_FT = 18000.0
FIRST_HOUR, LAST_HOUR = 10, 16
MIN_REPORTS = 5
MIN_LAYER_REPORTS = 2
AMOUNTS = ("FEW", "SCT", "BKN", "OVC")


def main():
    path = os.environ.get("EO_KSFO_METAR_CSV")
    if not path:
        sys.exit("set EO_KSFO_METAR_CSV to the IEM KSFO METAR CSV (see this script's docstring)")
    raw = open(path, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        sys.exit(f"input sha256 {digest} is not the recorded {EXPECTED_SHA256}")
    lines = raw.decode("utf-8").splitlines()
    rows = list(csv.DictReader(lines))
    days = collections.defaultdict(list)
    for r in rows:
        d, t = r["valid"].split(" ")
        if not FIRST_HOUR <= int(t[:2]) <= LAST_HOUR:
            continue
        layers = []
        for i in range(1, 5):
            c, h = r[f"skyc{i}"].strip(), r[f"skyl{i}"]
            if c in ("M", "", "CLR", "SKC", "NSC"):
                continue
            try:
                h = float(h)
            except ValueError:
                if c != "VV":
                    continue
                h = 0.0
            layers.append((c, h))
        days[d].append(layers)
    amount_mode = "--amount" in sys.argv[1:]
    stats = collections.defaultdict(collections.Counter)
    amounts = collections.defaultdict(collections.Counter)
    for d, reps in days.items():
        if len(reps) < MIN_REPORTS:
            continue
        m = int(d[5:7])
        low_cloudy = sum(1 for ls in reps if any(c in ("BKN", "OVC", "VV") and h < HIGH_FT for c, h in ls))
        if low_cloudy * 2 > len(reps):
            stats[m]["low_cloudy"] += 1
            continue
        low = sum(1 for ls in reps if any(c in ("SCT", "BKN", "OVC") and h < HIGH_FT for c, h in ls))
        high = sum(1 for ls in reps if any(h >= HIGH_FT for _, h in ls))
        if low >= MIN_LAYER_REPORTS:
            stats[m]["fair"] += 1
        elif high >= MIN_LAYER_REPORTS:
            stats[m]["cirrus"] += 1
            covers = sorted(max(AMOUNTS.index(c) for c, h in ls if h >= HIGH_FT and c in AMOUNTS) for ls in reps if any(h >= HIGH_FT and c in AMOUNTS for c, h in ls))
            if covers:
                amounts[m][AMOUNTS[covers[len(covers) // 2]]] += 1
        else:
            stats[m]["cloudless"] += 1
    out = sys.stdout
    if amount_mode:
        out.write("# KSFO cirrus-day amount by month: generated by ksfo-clear-day-sky.py --amount; do not edit.\n")
        out.write("# Source: NOAA/NWS ASOS routine METARs of San Francisco airport (KSFO), 2014-2023, public domain,\n")
        out.write("#   via the Iowa Environmental Mesonet ASOS archive (query in the script's docstring).\n")
        out.write(f"# Input sha256 {digest}, {len(rows)} reports.\n")
        out.write("# The cirrus days of ksfo-clear-day-sky.csv by the day's high-cloud amount: the sky-cover code of\n")
        out.write(f"#   the most covering layer at or over {HIGH_FT:.0f} ft, median over the day's reports that carry one\n")
        out.write("#   (FEW 1-2 oktas, SCT 3-4, BKN 5-7, OVC 8; WMO-No. 306 FM 15 regulation 15.9.1.1).\n")
        out.write("month,few,sct,bkn,ovc\n")
        for m in range(1, 13):
            a = amounts[m]
            out.write(f"{m},{a['FEW']},{a['SCT']},{a['BKN']},{a['OVC']}\n")
        return
    out.write("# KSFO clear-day sky by month: generated by ksfo-clear-day-sky.py; do not edit.\n")
    out.write("# Source: NOAA/NWS ASOS routine METARs of San Francisco airport (KSFO), 2014-2023, public domain,\n")
    out.write("#   via the Iowa Environmental Mesonet ASOS archive (query in the script's docstring).\n")
    out.write(f"# Input sha256 {digest}, {len(rows)} reports.\n")
    out.write(f"# Day: reports {FIRST_HOUR}:00-{LAST_HOUR}:59 local, at least {MIN_REPORTS}; high cloud at or over {HIGH_FT:.0f} ft (INFERRED);\n")
    out.write(f"#   low_cloudy: BKN/OVC/VV under it in over half the reports; fair: SCT+ under it in {MIN_LAYER_REPORTS}+ reports;\n")
    out.write(f"#   cirrus: any layer at or over it in {MIN_LAYER_REPORTS}+ reports; else cloudless (thresholds INFERRED).\n")
    out.write("month,low_cloudy,cloudless,cirrus,fair\n")
    for m in range(1, 13):
        s = stats[m]
        out.write(f"{m},{s['low_cloudy']},{s['cloudless']},{s['cirrus']},{s['fair']}\n")


if __name__ == "__main__":
    main()
