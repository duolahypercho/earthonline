def place(objs, dx, dz, yaw=0.0):
    for o in objs:
        o.location.x += dx
        o.location.z += dz
    if yaw:
        piv = bpy.data.objects.new('pivot', None)
        bpy.context.scene.collection.objects.link(piv)
        piv.location = (dx, 0, 0)
        for o in objs:
            o.parent = piv
            o.matrix_parent_inverse = piv.matrix_world.inverted()
        piv.rotation_euler.z = yaw


