RUST_STEEL = (0.20, 0.085, 0.035)  # linear: rusted steel bolts and bands
RUST_CAST = (0.30, 0.27, 0.24)  # corroded cast aluminium
RUST_NYLON = (0.55, 0.47, 0.30)  # a yellowed nylon washer
STRIP = 0.0625  # the atlas's foot: metal swatches (aluminium back, stainless, cast aluminium, nylon)
SWATCH = {'aluminium-back': 0, 'stainless': 1, 'cast-aluminium': 2, 'nylon-washer': 3}
GAME_ALB, GAME_AUX = 512, 256  # eo-render props_lib ALBEDO_RES and AUX_RES: the layers the game samples
LOD2_SIMPLIFY_M = 0.006


def to_srgb(c):
    c = np.clip(c, 0, 1)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * np.power(c, 1 / 2.4) - 0.055)


def resize(arr, H, W):
    """Area-filtered resize of an (h, w, c) array (box prefilter, then bilinear)."""
    h, w = arr.shape[:2]
    out = arr.astype(np.float64)
    ry, rx = h / H, w / W
    for axis, r in ((0, ry), (1, rx)):
        if r > 1.5:
            k = int(r / 2)
            pad = [(0, 0)] * out.ndim
            pad[axis] = (k + 1, k)
            p = np.pad(out, pad, mode='edge')
            c = np.cumsum(p, axis=axis)
            n = out.shape[axis]
            out = (np.take(c, np.arange(2 * k + 1, 2 * k + 1 + n), axis=axis) - np.take(c, np.arange(0, n), axis=axis)) / (2 * k + 1)
    ys = (np.arange(H) + 0.5) * h / H - 0.5
    xs = (np.arange(W) + 0.5) * w / W - 0.5
    y0 = np.clip(np.floor(ys).astype(int), 0, h - 1)
    x0 = np.clip(np.floor(xs).astype(int), 0, w - 1)
    y1, x1 = np.minimum(y0 + 1, h - 1), np.minimum(x0 + 1, w - 1)
    fy = np.clip(ys - y0, 0, 1)[:, None, None]
    fx = np.clip(xs - x0, 0, 1)[None, :, None]
    a, b = out[y0][:, x0], out[y0][:, x1]
    c, d = out[y1][:, x0], out[y1][:, x1]
    return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy


def game_atlas(face_maps, back_col, back_rough, variant='aged'):
    """The face over a strip of four metal swatches: albedo (sRGB), ORM (R 1, G roughness, B metal), normal.
    The rusty variant's bolts, bands and saddles are rusted."""
    alb_f, rough_f, nrm_f, metal_f = face_maps
    strip_a = int(round(GAME_ALB * STRIP))
    strip_x = int(round(GAME_AUX * STRIP))
    alb = np.zeros((GAME_ALB, GAME_ALB, 3))
    alb[strip_a:] = resize(alb_f[..., :3], GAME_ALB - strip_a, GAME_ALB)
    sw = GAME_ALB // 4
    alb[:strip_a, 0:sw] = resize(back_col, strip_a, sw)
    hw_lin = ((1, (0.66, 0.66, 0.65)), (2, (0.55, 0.56, 0.56)), (3, (0.80, 0.79, 0.75)))
    if variant == 'rusty':
        hw_lin = ((1, RUST_STEEL), (2, RUST_CAST), (3, RUST_NYLON))
    for i, lin in hw_lin:
        alb[:strip_a, i * sw:(i + 1) * sw] = to_srgb(np.array(lin))
    orm = np.zeros((GAME_AUX, GAME_AUX, 3))
    orm[..., 0] = 1.0
    orm[strip_x:, :, 1] = resize(rough_f[..., None], GAME_AUX - strip_x, GAME_AUX)[..., 0]
    orm[strip_x:, :, 2] = resize(metal_f[..., None], GAME_AUX - strip_x, GAME_AUX)[..., 0]
    sx = GAME_AUX // 4
    orm[:strip_x, 0:sx, 1] = resize(back_rough[..., None], strip_x, sx)[..., 0]
    hw_orm = ((None, 1.0), (0.28, 1.0), (0.55, 1.0), (0.60, 0.0))
    if variant == 'rusty':
        hw_orm = ((None, 1.0), (0.82, 0.45), (0.72, 0.6), (0.7, 0.0))
    for i, (rg, mt) in enumerate(hw_orm):
        if rg is not None:
            orm[:strip_x, i * sx:(i + 1) * sx, 1] = rg
        orm[:strip_x, i * sx:(i + 1) * sx, 2] = mt
    nrm = np.zeros((GAME_AUX, GAME_AUX, 3))
    nrm[...] = (0.5, 0.5, 1.0)
    nrm[strip_x:] = resize(nrm_f, GAME_AUX - strip_x, GAME_AUX)
    return alb, orm, nrm


def atlas_material(name, alb, orm, nrm, tdir, textured=True):
    m, nt, bsdf = principled_mat(name)
    if not textured:
        return m
    imgs = []
    for arr, tag, cs in ((alb, 'albedo', 'sRGB'), (orm, 'orm', 'Non-Color'), (nrm, 'normal', 'Non-Color')):
        imgs.append(save_rgba(arr, os.path.join(tdir, f'{name}-{tag}.png'), cs))
    ta = tex_node(nt, imgs[0], 'sRGB', (-700, 300))
    to = tex_node(nt, imgs[1], 'Non-Color', (-700, 0))
    tn = tex_node(nt, imgs[2], 'Non-Color', (-700, -300))
    nt.links.new(ta.outputs['Color'], bsdf.inputs['Base Color'])
    sep = nt.nodes.new('ShaderNodeSeparateColor')
    nt.links.new(to.outputs['Color'], sep.inputs['Color'])
    nt.links.new(sep.outputs['Green'], bsdf.inputs['Roughness'])
    nt.links.new(sep.outputs['Blue'], bsdf.inputs['Metallic'])
    nm = nt.nodes.new('ShaderNodeNormalMap')
    nt.links.new(tn.outputs['Color'], nm.inputs['Color'])
    nt.links.new(nm.outputs['Normal'], bsdf.inputs['Normal'])
    return m


def game_mesh(objs, fit, dz, post_y, mat, name):
    """Join copies of objs into one mesh in the game frame (art fitted into the plate frame,
    the post axis at the origin), every face on the single atlas material."""
    bpy.ops.object.select_all(action='DESELECT')
    dup = []
    for o in objs:
        d = o.copy()
        d.data = o.data.copy()
        bpy.context.scene.collection.objects.link(d)
        dup.append(d)
        bpy.context.view_layer.objects.active = d
        d.select_set(True)
        for mod in list(d.modifiers):
            bpy.ops.object.modifier_apply(modifier=mod.name)
        d.select_set(False)
    # each part's kind from its first material, before the join renumbers them
    for d in dup:
        d.select_set(True)
    bpy.context.view_layer.objects.active = dup[0]
    bpy.ops.object.join()
    j = bpy.context.object
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    me = j.data
    kinds = [m.name if m else '' for m in me.materials]
    uv = me.uv_layers.active.data
    zs = [v.co.z for v in me.vertices]
    xs = [v.co.x for v in me.vertices]
    x0, x1, z0, z1 = min(xs), max(xs), min(zs), max(zs)
    for poly in me.polygons:
        k = kinds[poly.material_index]
        for li in poly.loop_indices:
            if k.endswith('-face'):
                u, v = uv[li].uv
                uv[li].uv = (u, STRIP + v * (1 - STRIP))
            else:
                sw = SWATCH.get(k.replace('-rusty', ''), 0)
                co = me.vertices[me.loops[li].vertex_index].co
                fu = (co.x - x0) / max(1e-6, x1 - x0) if sw == 0 else 0.5
                fv = (co.z - z0) / max(1e-6, z1 - z0) if sw == 0 else 0.5
                uv[li].uv = ((sw + 0.06 + 0.88 * fu) / 4.0, STRIP * (0.1 + 0.8 * fv))
    for v in me.vertices:
        v.co.x *= fit
        v.co.z = v.co.z * fit + dz
        v.co.y -= post_y
    me.materials.clear()
    me.materials.append(mat)
    for poly in me.polygons:
        poly.material_index = 0
    j.name = name
    return j


def canonical_indices(path):
    """Rewrite every primitive's index buffer in a canonical order (each triangle from its
    smallest index, winding kept; triangles sorted): the exporter's triangle order varies from
    run to run with the same geometry, and the digests in the provenance must not."""
    import struct
    with open(path, 'rb') as f:
        b = bytearray(f.read())
    jlen = struct.unpack_from('<I', b, 12)[0]
    gj = json.loads(bytes(b[20:20 + jlen]))
    boff = 20 + jlen + 8
    for mesh in gj['meshes']:
        for prim in mesh['primitives']:
            acc = gj['accessors'][prim['indices']]
            view = gj['bufferViews'][acc['bufferView']]
            fmt = {5121: 'B', 5123: 'H', 5125: 'I'}[acc['componentType']]
            size = struct.calcsize(fmt)
            start = boff + view.get('byteOffset', 0) + acc.get('byteOffset', 0)
            n = acc['count']
            idx = list(struct.unpack_from(f'<{n}{fmt}', b, start))
            tris = []
            for t in range(0, n, 3):
                a = idx[t:t + 3]
                k = a.index(min(a))
                tris.append(tuple(a[k:] + a[:k]))
            tris.sort()
            struct.pack_into(f'<{n}{fmt}', b, start, *[i for t in tris for i in t])
            assert size * n <= view['byteLength']
    with open(path, 'wb') as f:
        f.write(b)


def export_one(obj, path):
    bpy.ops.object.select_all(action='DESELECT')
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.export_scene.gltf(filepath=path, use_selection=True, export_format='GLB', export_yup=True, export_apply=True, export_image_format='JPEG', export_jpeg_quality=90)
    canonical_indices(path)
    tris = sum(len(p.vertices) - 2 for p in obj.data.polygons)
    return tris


def game_export(a, rows, built, built_v, shared):
    """Per inventory face: `<face>-v1.glb` (plates, bolts, brackets and bands), `-lod1` (the plates),
    `-lod2` (the plates' outlines at LOD2_SIMPLIFY_M); per wear variant past the first,
    `<face>-v1-<variant>.glb` and `-lod1` (the far level shared: wear does not read past 90 m);
    and the provenance with every digest."""
    out = a['game']
    os.makedirs(out, exist_ok=True)
    tdir = os.path.join(a['out'], 'game-textures')
    os.makedirs(tdir, exist_ok=True)
    man_sha = sha256(MANIFEST)
    faces = {}
    for row in rows:
        if row['table'] != 'faces' or 'frame_in' not in row or row['face'] not in built:
            continue
        face = row['face']
        plates = built[face]
        A = [v * IN for v in row['size_in']]
        F = [v * IN for v in row['frame_in']]
        fit = min(F[0] / A[0], F[1] / A[1])
        dz = (F[1] - A[1] * fit) / 2
        post_y = plates[0]['post_y']
        def export_variant(v, plates_v, far_lod):
            alb, orm, nrm = game_atlas(shared['maps'][(face, v)], shared['back_col'], shared['back_rough'], v)
            tagv = face if v == 'aged' else f'{face}-{v}'
            mat = atlas_material(f'{tagv}-sign', alb, orm, nrm, tdir)
            bare = atlas_material(f'{tagv}-sign', None, None, None, tdir, textured=False)
            suffix0 = '' if v == 'aged' else f'-{v}'
            objs = [(game_mesh([o for p in plates_v for o in p['objs']], fit, dz, post_y, mat, f'{face}-v1{suffix0}'), suffix0),
                    (game_mesh([p['objs'][0] for p in plates_v], fit, dz, post_y, bare, f'{face}-v1{suffix0}-lod1'), f'{suffix0}-lod1')]
            if far_lod:
                far = []
                for pi, p in enumerate(plates_v):
                    simple = simplify_closed(p['outline'], LOD2_SIMPLIFY_M)
                    far.append(plate_mesh(f'{face}-far{pi}', simple, SHEET_IN * IN, p['uv_of'], [p['face_mat'], shared['back']], chamfer=0.0))
                objs.append((game_mesh(far, fit, dz, post_y, bare, f'{face}-v1-lod2'), '-lod2'))
                for o in far:
                    me = o.data
                    bpy.data.objects.remove(o, do_unlink=True)
                    bpy.data.meshes.remove(me)
            out_l = []
            for obj, suffix in objs:
                path = os.path.join(out, f'{face}-v1{suffix}.glb')
                tris = export_one(obj, path)
