"""Build the v1 street-sign plates: San Francisco's sign plates modelled from the official art.

Usage (headless, Blender 4.5):
  blender -b --factory-startup --python scripts/assets/build-street-signs-v1.py -- \
      --faces DIR --out DIR [--renders DIR] [--only stop,oneWayRight] [--samples 128] [--seed 7]

`--faces DIR` is the print layer written by
  cargo run --release -p eo-props --example sign_faces_export -- --out DIR
(every face of the sign art manifest that names an FHWA layout or a Caltrans
sheet, rendered from the verified official art, with its size in inches).

Every plate is built here from that art and from published values; nothing
is imported, generated by a model service or traced from photographs:

  * the blank's outline is the official art's own outline (its alpha edge:
    the FHWA layouts carry each sign's corner radii), split into the stacked
    plates of a stack spec by the manifest's item sizes, convex hull, then
    simplified to 0.25 mm;
  * the blank is flat aluminium sheet (SHEET_IN), its face set back by a
    small chamfer; sides and back are mill-finish aluminium;
  * two button-head bolts with nylon washers on the vertical centre line
    hold it to a saddle bracket and stainless band on the post;
  * the print is the official face; the sheeting's weathering is computed
    per texel in numpy, deterministic from the seed and the face name: sun
    fading (reds toward pink, a lifted black), road grime from the edges and
    the foot, rain streaks from the top edge and the bolts, scratches,
    chipped edges, blank sticker remnants (no words, no marks), and the
    microprismatic sheeting's cell pattern in the roughness and normal maps:
    matte, aged plates that read at 2-30 m;
  * each plate is written as a GLB (glTF Y up, origin on the post axis at
    the plate's foot, the face toward +Z) with its albedo, roughness and
    normal maps, and a row in `<out>/street-signs-v1.json`;
  * `--renders DIR` (outside the repository): Cycles renders of a street
    corner under a physical sky, the assemblies on galvanised posts at the
    California mounting heights (`sign-mounting-height-urban`).
"""

