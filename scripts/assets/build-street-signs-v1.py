def fold_plate(ob, rng, outline):
    """A crease across one corner of a plate (a battered sign): the plate cut along a line
    through points 25-45 % along the two bounding edges at a corner, the corner side turned
    about it by 8-20 deg, forward or back."""
    xs = [p[0] for p in outline]
    zs = [p[1] for p in outline]
    x0, x1, z0, z1 = min(xs), max(xs), min(zs), max(zs)
    sx, sz = (1 if rng.random() < 0.5 else -1), (1 if rng.random() < 0.5 else -1)
    cx, cz = (x1 if sx > 0 else x0), (z1 if sz > 0 else z0)
    p1 = Vector((cx - sx * (0.25 + 0.2 * rng.random()) * (x1 - x0), 0.0, cz))
    p2 = Vector((cx, 0.0, cz - sz * (0.25 + 0.2 * rng.random()) * (z1 - z0)))
    axis = (p2 - p1).normalized()
    n = axis.cross(Vector((0.0, 1.0, 0.0))).normalized()
    corner = Vector((cx, 0.0, cz))
    side = 1.0 if (corner - p1).dot(n) > 0 else -1.0
    ang = math.radians(16 + 18 * rng.random()) * (1 if rng.random() < 0.5 else -1)
    rot = Matrix.Translation(p1) @ Matrix.Rotation(ang, 4, axis) @ Matrix.Translation(-p1)
    me = ob.data
    bm = bmesh.new()
    bm.from_mesh(me)
    bmesh.ops.bisect_plane(bm, geom=bm.verts[:] + bm.edges[:] + bm.faces[:], plane_co=p1, plane_no=n)
    for v in bm.verts:
        if (v.co - p1).dot(n) * side > 1e-6:
            v.co = rot @ v.co
    bmesh.ops.triangulate(bm, faces=[f for f in bm.faces if len(f.verts) > 3])
    bm.normal_update()
    bm.to_mesh(me)
    bm.free()


def build_face(row, a, man, out_dir, shared, variant='aged'):
    face = row['face']
    table = row['table']
    name = (f"{table}-{face}" if table != 'faces' else face).replace(' ', '-')
    tag = name if variant == 'aged' else f'{name}-{variant}'
    rgba = load_rgba(os.path.join(a['faces'], row['png']))
    h, w = rgba.shape[:2]
    spec = row.get('spec', {})
    if table == 'blade' or row.get('drawn'):
        # blades (the D3-1a's own corner radius is drawn on the face) and the faces the game draws
        # itself (square art on a blank with rounded corners): a rounded rectangle over the frame.
        m_per_px = row['size_in'][0] * IN / w
        W, H = w * m_per_px, h * m_per_px
        rr = 0.012 if table == 'blade' else DRAWN_CORNER_IN * IN
        plates = [{'outline': rounded_rect(W, H, rr), 'band': (0, h)}]
    else:
        plates, m_per_px = plate_outlines(rgba, row['size_in'], spec, man)
    # bolts per plate, on the vertical centre line
    bolts_px = []
    for p in plates:
        zs = [q[1] for q in p['outline']]
        z0, z1 = min(zs), max(zs)
        hh = z1 - z0
        e = min(BOLT_EDGE_IN * IN, hh * 0.22)
        p['bolts'] = [z1 - e, z0 + e] if table != 'blade' else []
        for bz in p['bolts']:
            bolts_px.append((bz / m_per_px, w / 2))
    alb, rough, nrm, metal = weather_face(rgba, name, a['seed'], m_per_px, bolts_px, variant)
    shared.setdefault('maps', {})[(name, variant)] = (alb, rough, nrm, metal)
    tdir = os.path.join(out_dir, 'textures')
    os.makedirs(tdir, exist_ok=True)
    img_a = save_rgba(alb, os.path.join(tdir, f'{tag}-albedo.png'), 'sRGB')
    img_r = save_rgba(np.stack([rough] * 3, -1), os.path.join(tdir, f'{tag}-roughness.png'), 'Non-Color')
    img_n = save_rgba(nrm, os.path.join(tdir, f'{tag}-normal.png'), 'Non-Color')
    face_m = face_material(f'{tag}-face', img_a, img_r, img_n)
    hw = shared['rusty_hw'] if variant == 'rusty' else (shared['cast'], shared['steel'], shared['nylon'])
    t = SHEET_IN * IN
    built = []
    for pi, p in enumerate(plates):
        def uv_of(x, z):
            return ((x / (w * m_per_px)) + 0.5, z / (h * m_per_px))
        ob = plate_mesh(f'{tag}-plate{pi}', p['outline'], t, uv_of, [face_m, shared['back']])
        objs = [ob]
        post_y = t + 0.018 + POST_R
        for bi, bz in enumerate(p['bolts']):
            objs += bolt(f'{tag}-p{pi}-bolt{bi}', 0.0, bz, 0.0, [hw[1], hw[2]])
            objs += bracket(f'{tag}-p{pi}-br{bi}', bz, t, post_y, [hw[0], hw[1]])
        zs = [q[1] for q in p['outline']]
        xs = [q[0] for q in p['outline']]
        if variant == 'battered':
            vr = rng_for(a['seed'], f'{name}:{pi}:battered:shape')
            if pi == 0:
                fold_plate(ob, vr, p['outline'])
            # knocked crooked on its pole: turned about the post and rolled on its bolts
            zc = (min(zs) + max(zs)) / 2
            yaw = math.radians((4 + 9 * vr.random()) * (1 if vr.random() < 0.5 else -1))
            roll = math.radians((1.5 + 4 * vr.random()) * (1 if vr.random() < 0.5 else -1))
            m = Matrix.Translation((0, post_y, 0)) @ Matrix.Rotation(yaw, 4, 'Z') @ Matrix.Translation((0, -post_y, 0))
            m = m @ Matrix.Translation((0, 0, zc)) @ Matrix.Rotation(roll, 4, 'Y') @ Matrix.Translation((0, 0, -zc))
            for o in objs:
                o.matrix_world = m @ o.matrix_world
        built.append({'name': f'{tag}-plate{pi}', 'objs': objs, 'z0': min(zs), 'z1': max(zs), 'w': max(xs) - min(xs), 'post_y': post_y, 'outline': p['outline'], 'face_mat': face_m, 'uv_of': uv_of})
    return name, built


GAME_ALBEDO_PX = 1024
GAME_AUX_PX = 512


def game_image(src, px, path, fmt='JPEG'):
    """A copy of a texture scaled to px on its long side, saved as fmt, for the game GLB."""
    img = src.copy()
    w, h = img.size
    k = px / max(w, h)
    img.scale(max(1, int(round(w * k))), max(1, int(round(h * k))))
    img.filepath_raw = path
    img.file_format = fmt
    if fmt == 'JPEG':
        bpy.context.scene.render.image_settings.quality = 88
    img.save()
    return img


def game_material(mat, tdir):
    """The face material with game-size maps (albedo 1024 px, roughness and normal 512 px, JPEG)."""
    gm = mat.copy()
    gm.name = mat.name + '-game'
    for n in gm.node_tree.nodes:
        if n.type == 'TEX_IMAGE' and n.image is not None:
            base = os.path.splitext(os.path.basename(n.image.filepath_raw or n.image.name))[0]
            px = GAME_ALBEDO_PX if base.endswith('albedo') else GAME_AUX_PX
            n.image = game_image(n.image, px, os.path.join(tdir, base + f'-{px}.jpg'))
    return gm


def export_glb(objs, path, tdir):
    """One joined mesh, transforms applied (the asset frame is the mesh's own), game-size maps."""
    bpy.ops.object.select_all(action='DESELECT')
    dup = []
    for o in objs:
        d = o.copy()
        d.data = o.data.copy()
        bpy.context.scene.collection.objects.link(d)
        dup.append(d)
    for d in dup:
        d.select_set(True)
    bpy.context.view_layer.objects.active = dup[0]
    for d in dup:
        for mod in list(d.modifiers):
            bpy.context.view_layer.objects.active = d
            bpy.ops.object.modifier_apply(modifier=mod.name)
    bpy.context.view_layer.objects.active = dup[0]
    bpy.ops.object.join()
    j = bpy.context.object
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    swapped = {}
    for i, m in enumerate(j.data.materials):
        if m is not None and m.name.endswith('-face'):
            swapped[i] = game_material(m, tdir)
            j.data.materials[i] = swapped[i]
    j.name = os.path.splitext(os.path.basename(path))[0]
    bpy.ops.export_scene.gltf(filepath=path, use_selection=True, export_format='GLB', export_yup=True, export_apply=True, export_image_format='AUTO', export_jpeg_quality=88)
    tris = sum(len(p.vertices) - 2 for p in j.data.polygons)
    me = j.data
    bpy.data.objects.remove(j, do_unlink=True)
    bpy.data.meshes.remove(me)
    for m in swapped.values():
        bpy.data.materials.remove(m)
    return tris


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        h.update(f.read())
    return h.hexdigest()


