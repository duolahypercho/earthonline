# ---------------------------------------------------------------- numpy helpers

def rng_for(seed, name):
    return np.random.default_rng(zlib.crc32(f'{seed}:{name}'.encode()))


def box_blur(a, r):
    """Separable box blur of radius r (pixels), edges clamped."""
    if r < 1:
        return a
    r = int(r)
    for axis in (0, 1):
        pad = [(0, 0)] * a.ndim
        pad[axis] = (r + 1, r)
        p = np.pad(a, pad, mode='edge')
        c = np.cumsum(p, axis=axis)
        n = a.shape[axis]
        hi = np.take(c, np.arange(2 * r + 1, 2 * r + 1 + n), axis=axis)
        lo = np.take(c, np.arange(0, n), axis=axis)
        a = (hi - lo) / (2 * r + 1)
    return a


def value_noise(h, w, cells, rng):
    """Smooth value noise: a random grid of `cells` across the long side, bicubic-ish (smoothstep) interpolated."""
    gy = max(2, int(round(cells * h / max(h, w))) + 2)
    gx = max(2, int(round(cells * w / max(h, w))) + 2)
    g = rng.random((gy, gx))
    y = np.linspace(0, gy - 1.0001, h)
    x = np.linspace(0, gx - 1.0001, w)
    y0 = np.floor(y).astype(int)
    x0 = np.floor(x).astype(int)
    fy = y - y0
    fx = x - x0
    fy = fy * fy * (3 - 2 * fy)
    fx = fx * fx * (3 - 2 * fx)
    a = g[y0][:, x0]
    b = g[y0][:, x0 + 1]
    c = g[y0 + 1][:, x0]
    d = g[y0 + 1][:, x0 + 1]
    top = a + (b - a) * fx[None, :]
    bot = c + (d - c) * fx[None, :]
    return top + (bot - top) * fy[:, None]


def fbm(h, w, cells, octaves, rng, gain=0.5):
    out = np.zeros((h, w))
    amp, tot = 1.0, 0.0
    for o in range(octaves):
        out += amp * value_noise(h, w, cells * (2 ** o), rng)
        tot += amp
        amp *= gain
    return out / tot


def draw_line(mask, p0, p1, width, value=1.0):
    """Rasterise a segment of `width` pixels into mask (max blend)."""
    h, w = mask.shape
    n = int(max(abs(p1[0] - p0[0]), abs(p1[1] - p0[1]))) + 1
    ys = np.linspace(p0[0], p1[0], n)
    xs = np.linspace(p0[1], p1[1], n)
    r = max(0, int(width // 2))
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            yy = np.clip(np.round(ys + dy).astype(int), 0, h - 1)
            xx = np.clip(np.round(xs + dx).astype(int), 0, w - 1)
            mask[yy, xx] = np.maximum(mask[yy, xx], value)


def height_to_normal(hgt, strength):
    gy, gx = np.gradient(hgt)
    nx = -gx * strength
    ny = -gy * strength
    nz = np.ones_like(hgt)
    l = np.sqrt(nx * nx + ny * ny + nz * nz)
    return np.stack([nx / l * 0.5 + 0.5, ny / l * 0.5 + 0.5, nz / l * 0.5 + 0.5], axis=-1)


# ---------------------------------------------------------------- the art

def load_rgba(path):
    img = bpy.data.images.load(path, check_existing=False)
    w, h = img.size
    buf = np.empty(w * h * 4, dtype=np.float32)
    img.pixels.foreach_get(buf)
    bpy.data.images.remove(img)
    return buf.reshape(h, w, 4)  # row 0 = bottom (Blender)


def save_rgba(arr, path, colorspace='sRGB'):
    h, w = arr.shape[:2]
    if arr.shape[2] == 3:
        arr = np.concatenate([arr, np.ones((h, w, 1))], axis=2)
    img = bpy.data.images.new(os.path.basename(path), w, h, alpha=True)
    img.colorspace_settings.name = colorspace
    img.pixels.foreach_set(np.clip(arr, 0, 1).astype(np.float32).ravel())
    img.filepath_raw = path
    img.file_format = 'PNG'
    img.save()
    return img


def stack_items(spec, man):
    """The plates of a face spec, top first: [(svg id or layout, [w_in, h_in])]."""
    files = {f['id']: f for f in man['files'] if 'id' in f}

    def size_of(it):
        if 'sizeIn' in it:
            return it['sizeIn']
        if 'svg' in it:
            return files[it['svg']]['sizeIn']
        return None

    if 'stack' in spec:
        return [(it.get('svg') or it.get('layout'), size_of(it)) for it in spec['stack']]
    return [(spec.get('svg') or spec.get('layout'), None)]


def hull(points):
    pts = sorted(set(map(tuple, points)))
    if len(pts) < 3:
        return pts

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower, upper = [], []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return lower[:-1] + upper[:-1]


def simplify_closed(poly, tol):
    """Drop hull vertices whose removal moves the outline by less than tol (arcs keep enough points)."""
    pts = list(poly)
    changed = True
    while changed and len(pts) > 8:
        changed = False
        i = 0
        while i < len(pts) and len(pts) > 8:
            a, b, c = pts[i - 1], pts[i], pts[(i + 1) % len(pts)]
            ab = (c[0] - a[0], c[1] - a[1])
            l = math.hypot(*ab) or 1.0
            d = abs((b[0] - a[0]) * ab[1] - (b[1] - a[1]) * ab[0]) / l
            if d < tol:
                pts.pop(i)
                changed = True
            else:
                i += 1
    return pts


