def plate_mesh(name, outline, t, uv_of, mats, chamfer=CHAMFER_M):
    """A flat blank: chamfered face (material 0, UVs from uv_of) at y=0 facing -Y, aluminium sides and back (material 1)."""
    bm = bmesh.new()
    uvl = bm.loops.layers.uv.new('UVMap')
    n = len(outline)
    cx = sum(p[0] for p in outline) / n
    cz = sum(p[1] for p in outline) / n

    def inset(p, d):
        vx, vz = p[0] - cx, p[1] - cz
        l = math.hypot(vx, vz) or 1.0
        return (p[0] - vx / l * d, p[1] - vz / l * d)

    face_ring = [bm.verts.new((*(lambda q: (q[0], 0.0, q[1]))(inset(p, chamfer)),)) for p in outline]
    outer_f = [bm.verts.new((p[0], chamfer, p[1])) for p in outline]
    outer_b = [bm.verts.new((p[0], t, p[1])) for p in outline]
    front = bm.faces.new(list(reversed(face_ring)))
    front.material_index = 0
    for i in range(n):
        j = (i + 1) % n
        f = bm.faces.new([face_ring[i], face_ring[j], outer_f[j], outer_f[i]])
        f.material_index = 1
        f2 = bm.faces.new([outer_f[i], outer_f[j], outer_b[j], outer_b[i]])
        f2.material_index = 1
    back = bm.faces.new(outer_b)
    back.material_index = 1
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    for f in bm.faces:
        for lp in f.loops:
            co = lp.vert.co
            if f.material_index == 0:
                lp[uvl].uv = uv_of(co.x, co.z)
            else:
                lp[uvl].uv = ((co.x - cx) * 1.5 + 0.5, (co.z - cz) * 1.5 + 0.5)
    bm.normal_update()
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    for m in mats:
        me.materials.append(m)
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    for p in me.polygons:
        p.use_smooth = False
    return ob


def bolt(name, x, z, y_face, mats):
    """A button-head bolt and nylon washer on the face (material 0 steel, 1 nylon)."""
    objs = []
    bpy.ops.mesh.primitive_cylinder_add(vertices=20, radius=0.0125, depth=0.0016, location=(x, y_face - 0.0008, z), rotation=(math.pi / 2, 0, 0))
    w = bpy.context.object
    w.name = name + '-washer'
    w.data.materials.append(mats[1])
    objs.append(w)
    bpy.ops.mesh.primitive_uv_sphere_add(segments=18, ring_count=8, radius=0.0085, location=(x, y_face - 0.0016, z))
    hd = bpy.context.object
    hd.scale = (1, 0.45, 1)
    hd.name = name + '-head'
    bm = bmesh.new()
    bm.from_mesh(hd.data)
    bmesh.ops.delete(bm, geom=[v for v in bm.verts if v.co.y > 0.0001], context='VERTS')
    bm.to_mesh(hd.data)
    bm.free()
    hd.data.materials.append(mats[0])
    objs.append(hd)
    for o in objs:
        for p in o.data.polygons:
            p.use_smooth = True
    return objs


def bracket(name, z, y_back, post_y, mats):
    """A cast saddle on the plate's back and a stainless band round the post at height z."""
    objs = []
    depth = post_y - POST_R - y_back
    bpy.ops.mesh.primitive_cube_add(size=1, location=(0, y_back + depth / 2 + 0.002, z))
    s = bpy.context.object
    s.scale = (0.075, depth + 0.004, 0.028)
    s.name = name + '-saddle'
    bpy.ops.object.transform_apply(scale=True)
    bev = s.modifiers.new('bevel', 'BEVEL')
    bev.width = 0.003
    bev.segments = 2
    s.data.materials.append(mats[0])
    objs.append(s)
    bpy.ops.mesh.primitive_cylinder_add(vertices=32, radius=POST_R + 0.0012, depth=0.019, location=(0, post_y, z))
    band = bpy.context.object
    band.name = name + '-band'
    band.data.materials.append(mats[1])
    for p in band.data.polygons:
        p.use_smooth = True
    objs.append(band)
    return objs


def post(name, height, mat):
    bpy.ops.mesh.primitive_cylinder_add(vertices=40, radius=POST_R, depth=height, location=(0, 0, height / 2))
    p = bpy.context.object
    p.name = name
    for f in p.data.polygons:
        f.use_smooth = True
    bpy.ops.mesh.primitive_cylinder_add(vertices=40, radius=POST_R + 0.003, depth=0.02, location=(0, 0, height + 0.01))
    cap = bpy.context.object
    cap.name = name + '-cap'
    bev = cap.modifiers.new('bevel', 'BEVEL')
    bev.width = 0.004
    bev.segments = 3
    for o in (p, cap):
        o.data.materials.append(mat)
    return [p, cap]


