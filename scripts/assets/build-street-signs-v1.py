def rounded_rect(W, H, r, steps=5):
    """A W x H rectangle (x centred, z from 0) with corners of radius r, counter-clockwise."""
    poly = []
    for (cx, cz, a0) in [(W / 2 - r, H - r, 0), (-W / 2 + r, H - r, 90), (-W / 2 + r, r, 180), (W / 2 - r, r, 270)]:
        for k in range(steps):
            ang = math.radians(a0 + k * 90.0 / (steps - 1))
            poly.append((cx + r * math.cos(ang), cz + r * math.sin(ang)))
    return poly


def plate_outlines(rgba, size_in, spec, man):
    """Each plate of the face: (outline in metres about the face's own frame, pixel band)."""
    h, w = rgba.shape[:2]
    m_per_px = size_in[0] * IN / w
    alpha = rgba[:, :, 3] > 0.5
    items = stack_items(spec, man)
    bands = []
    if len(items) == 1:
        bands.append((0, h))
    else:
        # stack: heights from the manifest sizes, top first; Blender rows are bottom first.
        hs = [it[1][1] for it in items]
        tot = sum(hs)
        top = h
        for hh in hs:
            n = int(round(h * hh / tot))
            bands.append((max(0, top - n), top))
            top -= n
    out = []
    for (r0, r1) in bands:
        sub = alpha[r0:r1]
        rows = np.where(sub.any(axis=1))[0]
        cols = np.where(sub.any(axis=0))[0]
        if len(rows) == 0:
            continue
        pts = []
        for r in rows:
            c = np.where(sub[r])[0]
            pts += [(c[0], r + r0), (c[-1] + 1, r + r0), (c[0], r + r0 + 1), (c[-1] + 1, r + r0 + 1)]
        for c in cols:
            r = np.where(sub[:, c])[0]
            pts += [(c, r[0] + r0), (c, r[-1] + r0 + 1), (c + 1, r[0] + r0), (c + 1, r[-1] + r0 + 1)]
        hp = hull(pts)
        poly = [((x - w / 2) * m_per_px, y * m_per_px) for (x, y) in hp]
        poly = simplify_closed(poly, SIMPLIFY_M)
        out.append({'outline': poly, 'band': (r0, r1)})
    return out, m_per_px


# ---------------------------------------------------------------- weathering

def soft_blur(a, r):
    """Three box passes: close to a Gaussian, no square contours."""
    for _ in range(3):
        a = box_blur(a, r / 1.7)
    return a


# The wear variants every face is built in: the plate the walk has always drawn ('aged'), one
# whose steel hardware bleeds rust down the face and whose edges corrode ('rusty'), and one hit,
# bent and defaced ('battered'). eo-app picks one per plate from its position.
VARIANTS = ('aged', 'rusty', 'battered')


def weather_face(rgba, name, seed, m_per_px, bolts_px, variant='aged'):
    """Albedo (sRGB), roughness, normal and metal mask of a sheeting face in one of the VARIANTS.
    bolts_px: [(row, col)]. The aged face draws exactly as before the variants."""
    rng = rng_for(seed, name if variant == 'aged' else f'{name}:{variant}')
    h, w = rgba.shape[:2]
    a = rgba[:, :, 3]
    inside = a > 0.5
    col = rgba[:, :, :3].astype(np.float64).copy()
    px_per_mm = 0.001 / m_per_px
    yy = np.linspace(0, 1, h)[:, None] * np.ones((1, w))  # 0 bottom, 1 top
    age = 0.6 + 0.4 * rng.random()  # this plate's years in the sun

    # Distance into the plate, smooth: 0 at the edge, 1 a few cm in.
    edge = np.clip(soft_blur(inside.astype(float), 10 * px_per_mm) * 2 - 1, 0, 1)

    # 1. Sun fading: reds go pink, every colour loses chroma, the black legend greys; the top most.
    n_fade = fbm(h, w, 4, 4, rng)
    fade = np.clip(age * (0.45 + 0.35 * yy + 0.45 * (n_fade - 0.5)), 0, 1)
    r, g, b = col[..., 0], col[..., 1], col[..., 2]
    red = np.clip((r - np.maximum(g, b) - 0.25) * 4, 0, 1)
    pink = np.array([0.80, 0.34, 0.38])
    k = (fade * 0.42 * red)[..., None]
    col = col * (1 - k) + pink * k
    lum = (0.2126 * col[..., 0] + 0.7152 * col[..., 1] + 0.0722 * col[..., 2])[..., None]
    col = col * (1 - 0.14 * fade[..., None]) + lum * 0.14 * fade[..., None]
    col = np.maximum(col, 0.08 + 0.07 * fade[..., None])

    # 2. Road film: a blotchy grey-brown haze over the whole face (whites show it most), heavier at the foot.
    n_dirt = fbm(h, w, 7, 6, rng)
    n_fine = fbm(h, w, 60, 3, rng)
    film = np.clip(0.18 + 0.30 * (n_dirt - 0.5) + 0.22 * (1 - yy) ** 2 + 0.10 * (n_fine - 0.5), 0, 1) * age
    film += (1 - edge) * 0.35
    # 3. Spray specks from passing wheels: small dark dots, dense toward the foot.
    specks = (rng.random((h, w)) < (0.0016 + 0.006 * (1 - yy) ** 3)).astype(float)
    specks = np.clip(soft_blur(specks, 0.5 * px_per_mm) * 6, 0, 1)

    # 4. Rain streaks: from the top edge and the bolts, running down.
    drip = np.zeros((h, w))
    top_row = np.array([np.max(np.where(inside[:, c])[0]) if inside[:, c].any() else 0 for c in range(w)])
    rr = np.arange(h)
    for c in np.where(rng.random(w) > 0.9935)[0]:
        length = (0.04 + 0.22 * rng.random() ** 2) * h
        prof = np.where(rr <= top_row[c], np.exp(-(top_row[c] - rr) / length), 0) * (0.25 + 0.55 * rng.random())
        cw = max(1, int((2 + 6 * rng.random()) * px_per_mm))
        drip[:, c:c + cw] = np.maximum(drip[:, c:c + cw], prof[:, None])
    for (br, bc) in bolts_px:
        for _ in range(int(4 + 5 * rng.random())):
            c = int(bc + (rng.random() - 0.5) * 26 * px_per_mm)
            length = (0.05 + 0.35 * rng.random()) * h
            prof = np.where(rr <= br - 8 * px_per_mm, np.exp(-(br - rr) / length), 0) * (0.5 + 0.5 * rng.random())
            cw = max(1, int((0.8 + 2 * rng.random()) * px_per_mm))
            if 0 <= c < w - cw:
                drip[:, c:c + cw] = np.maximum(drip[:, c:c + cw], prof[:, None])
    streak = soft_blur(drip, 1.6 * px_per_mm) * (0.4 + 1.0 * fbm(h, w, 18, 3, rng))

    # 5. Scratches (the film cut to the white base or the metal) and chipped edges.
    scratch = np.zeros((h, w))
    for _ in range(int(40 + 80 * rng.random())):
        y0, x0 = rng.random() * h, rng.random() * w
        ang = rng.random() * math.pi
        ln = (0.008 + 0.07 * rng.random() ** 2) * max(h, w)
        draw_line(scratch, (y0, x0), (y0 + math.sin(ang) * ln, x0 + math.cos(ang) * ln), max(1, int(0.3 * px_per_mm * (1 + rng.random()))), 0.5 + 0.5 * rng.random())
    chips = (edge < 0.25) & (fbm(h, w, 70, 2, rng) > 0.66) & inside

    # 6. Sticker remnants: blank, torn, pale (no words and no marks).
    sticker = np.zeros((h, w))
    sticker_col = np.zeros((h, w, 3))
    for _ in range(int(rng.integers(0, 3))):
        sh, sw = (0.04 + 0.07 * rng.random()) * h, (0.05 + 0.10 * rng.random()) * w
        cy, cx = (0.2 + 0.6 * rng.random()) * h, (0.2 + 0.6 * rng.random()) * w
        ang = (rng.random() - 0.5) * 0.5
        Y, X = np.mgrid[0:h, 0:w]
        u = (X - cx) * math.cos(ang) + (Y - cy) * math.sin(ang)
        v = -(X - cx) * math.sin(ang) + (Y - cy) * math.cos(ang)
        rect = (np.abs(u) < sw / 2) & (np.abs(v) < sh / 2) & inside
        torn = fbm(h, w, 35, 3, rng) > (0.40 + 0.2 * rng.random())
        tone = [np.array([0.90, 0.89, 0.85]), np.array([0.78, 0.78, 0.76]), np.array([0.88, 0.86, 0.80]), np.array([0.20, 0.20, 0.21])][int(rng.choice(4, p=[0.4, 0.3, 0.22, 0.08]))]
        keep, residue = rect & torn, rect & ~torn
        sticker[keep] = 1.0
        sticker[residue] = np.maximum(sticker[residue], 0.3)
        sticker_col[keep] = tone * (0.9 + 0.1 * rng.random())
        sticker_col[residue] = col[residue] * 0.75 + np.array([0.80, 0.79, 0.75]) * 0.25

    dust = fbm(h, w, 380, 2, rng)
    col *= (0.94 + 0.10 * dust)[..., None]
    dirt = np.array([0.36, 0.33, 0.28])
    col = col * (1 - 0.55 * film[..., None]) + dirt * 0.55 * film[..., None]
    col = col * (1 - 0.6 * streak[..., None]) + np.array([0.26, 0.24, 0.21]) * 0.6 * streak[..., None]
    col = col * (1 - 0.7 * specks[..., None]) + np.array([0.16, 0.15, 0.13]) * 0.7 * specks[..., None]
    col = col * (1 - 0.55 * scratch[..., None]) + np.array([0.84, 0.84, 0.82]) * 0.55 * scratch[..., None]
    sk = np.minimum(1, sticker)[..., None]
    col = np.where(sk > 0, sticker_col * sk + col * (1 - sk), col)
    col[chips] = np.array([0.60, 0.61, 0.62])

    metal = chips.astype(float)
    rust, peel, scrib, dents = (np.zeros((h, w)) for _ in range(4))
    if variant != 'aged':
        vr = rng_for(seed, f'{name}:{variant}:wear')
        Y, X = np.mgrid[0:h, 0:w]
        rr = np.arange(h)
    if variant == 'rusty':
        # Rust from the steel: a stain round each bolt and streaks running down from it and
        # from the top edge (the bands and saddles above), broken up by the film.
        for (br, bc) in bolts_px:
            d = np.hypot(Y - br, X - bc) / ((10 + 10 * vr.random()) * px_per_mm)
            rust = np.maximum(rust, np.exp(-d * d) * (0.7 + 0.3 * vr.random()))
            for _ in range(int(6 + 6 * vr.random())):
                c = int(bc + (vr.random() - 0.5) * 34 * px_per_mm)
                cw = max(2, int((3 + 12 * vr.random()) * px_per_mm))
                length = (0.3 + 0.9 * vr.random()) * h
                prof = np.where(rr <= br, np.exp(-(br - rr) / length), 0) * (0.6 + 0.4 * vr.random())
                if 0 <= c < w - cw:
                    rust[:, c:c + cw] = np.maximum(rust[:, c:c + cw], prof[:, None])
        for c in np.where(vr.random(w) > 0.985)[0]:
            length = (0.1 + 0.5 * vr.random()) * h
            prof = np.where(rr <= top_row[c], np.exp(-(top_row[c] - rr) / length), 0) * (0.35 + 0.55 * vr.random())
            cw = max(2, int((3 + 6 * vr.random()) * px_per_mm))
            rust[:, c:c + cw] = np.maximum(rust[:, c:c + cw], prof[:, None])
        # run-off: brown staining that collects toward the foot and along the edges
        runoff = np.clip((fbm(h, w, 5, 5, vr) - 0.42) * 2.2, 0, 1) * (0.35 + 0.65 * (1 - yy) ** 1.5)
        rim_rust = np.clip(1 - edge * 3.0, 0, 1) * (0.5 + 0.5 * fbm(h, w, 40, 3, vr))
        rust = np.maximum(rust, np.maximum(runoff * 0.75, rim_rust * 0.85))
        rust = np.clip(soft_blur(rust, 1.5 * px_per_mm) * (0.55 + 1.0 * fbm(h, w, 22, 3, vr)), 0, 1) * inside
        strong = np.array([0.33, 0.15, 0.06])
        weak = np.array([0.58, 0.36, 0.20])
        rc = strong * rust[..., None] + weak * (1 - rust[..., None])
        k = np.clip(rust * 1.15, 0, 0.95)[..., None]
        col = col * (1 - k) + rc * k
        # the sheeting lifts at the edges: white aluminium oxide under it
        ox = (edge < 0.45) & (fbm(h, w, 45, 3, vr) > 0.56) & inside
        col[ox] = col[ox] * 0.3 + np.array([0.79, 0.79, 0.76]) * 0.7
        metal[ox] = 0.35
        rust = np.where(ox, np.maximum(rust, 0.4), rust)
    if variant == 'battered':
        # Sheeting peeled back from the edges to bare aluminium, a darker lifted rim round each patch.
        cand = np.argwhere((edge < 0.12) & inside)
        for _ in range(int(2 + 4 * vr.random())):
            if len(cand) == 0:
                break
            cy, cx = cand[int(vr.integers(0, len(cand)))]
            rad = (0.06 + 0.14 * vr.random()) * max(h, w)
            ragged = 0.65 + 0.7 * fbm(h, w, 30, 3, vr)
            peel = np.maximum(peel, ((np.hypot(Y - cy, X - cx) < rad * ragged) & inside).astype(float))
        rim = np.clip(soft_blur(peel, 1.5 * px_per_mm) - peel, 0, 1) * 4
        alu = np.array([0.66, 0.67, 0.68]) * (0.9 + 0.15 * fbm(h, w, 60, 2, vr))[..., None]
        col = np.where(peel[..., None] > 0.5, alu, col)
        col = col * (1 - 0.5 * np.clip(rim, 0, 1)[..., None])
        metal = np.maximum(metal, peel)
        # marker scribbles: abstract strokes, no letters
        for _ in range(int(2 + 4 * vr.random())):
            ink = [np.array([0.04, 0.04, 0.05]), np.array([0.74, 0.75, 0.77]), np.array([0.14, 0.17, 0.44]), np.array([0.52, 0.07, 0.10])][int(vr.choice(4, p=[0.45, 0.25, 0.15, 0.15]))]
            stroke = np.zeros((h, w))
            y0, x0 = (0.15 + 0.7 * vr.random()) * h, (0.15 + 0.7 * vr.random()) * w
            ang = vr.random() * math.tau
            step = 3.5 * px_per_mm
            width = max(2, int((2 + 3 * vr.random()) * px_per_mm))
            for _ in range(int(25 + 70 * vr.random())):
                ang += (vr.random() - 0.5) * 0.9
                y1, x1 = y0 + math.sin(ang) * step, x0 + math.cos(ang) * step
                draw_line(stroke, (y0, x0), (y1, x1), width, 1.0)
                y0, x0 = y1, x1
            stroke = stroke * inside * (peel < 0.5)
            scrib = np.maximum(scrib, stroke)
            col = col * (1 - 0.9 * stroke[..., None]) + ink * 0.9 * stroke[..., None]
        # dents from impacts
        for _ in range(int(2 + 4 * vr.random())):
            cy, cx = vr.random() * h, vr.random() * w
            r = (15 + 30 * vr.random()) * px_per_mm
            dents = np.maximum(dents, np.exp(-((Y - cy) ** 2 + (X - cx) ** 2) / (r * r)))
        # and the sun has had it longer
        lum2 = (0.2126 * col[..., 0] + 0.7152 * col[..., 1] + 0.0722 * col[..., 2])[..., None]
        col = col * 0.86 + lum2 * 0.08 + 0.06

    # Roughness: an aged satin film (matte), duller under the film and the streaks.
    yx = np.mgrid[0:h, 0:w]
    period = max(3, int(round(3.6 * px_per_mm)))
    cells = (((yx[0] + yx[1]) % period) == 0) | (((yx[0] - yx[1]) % period) == 0)
    rough = 0.46 + 0.10 * (n_fine - 0.5) + 0.12 * (dust - 0.5) + 0.28 * film + 0.15 * streak + 0.2 * specks - 0.08 * scratch + 0.06 * cells
    rough = np.where(sticker > 0.5, 0.6, rough)
    rough[chips] = 0.42
    if variant == 'rusty':
        rough = np.maximum(rough, 0.55 + 0.35 * rust)
    if variant == 'battered':
        rough = np.where(peel > 0.5, 0.45, rough)
        rough = np.where(scrib > 0.5, 0.34, rough)
    rough = np.clip(rough, 0.25, 0.95)

    # Height: oil-canned sheet, the sheeting's seal-line cells, scratches cut in, stickers proud.
    hgt = (fbm(h, w, 3, 2, rng) - 0.5) * 60.0 + cells * 0.15 + (dust - 0.5) * 0.6 - scratch * 0.6 + sticker * 0.3
    if variant == 'battered':
        hgt = hgt - dents * 9.0 - peel * 0.4 + scrib * 0.15
    nrm = height_to_normal(hgt, 1.0)

    out = np.concatenate([np.clip(col, 0, 1), np.ones((h, w, 1))], axis=2)
    out[~inside] = [0.60, 0.61, 0.62, 1]  # outside the plate: the blank's edge colour (UV bleed)
    return out, rough, nrm, metal


def weather_back(w, h, name, seed):
    rng = rng_for(seed, 'back:' + name)
    yy = np.linspace(0, 1, h)[:, None] * np.ones((1, w))
    ox = fbm(h, w, 6, 5, rng)
    base = 0.58 + 0.10 * (ox - 0.5) - 0.06 * (1 - yy) ** 2
    streaks = box_blur((rng.random((1, w)) > 0.96).astype(float), 2)[0][None, :] * np.exp(-(1 - yy) * 3) * 0.12
    g = np.clip(base - streaks, 0, 1)
    col = np.stack([g * 0.98, g, g * 1.02], -1)
    rough = np.clip(0.42 + 0.25 * (ox - 0.5) + streaks, 0.2, 0.9)
    return col, rough


