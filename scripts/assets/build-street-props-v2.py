def _hash(ix, iy, iz, seed):
    h = (ix.astype(np.uint64) * np.uint64(0x9E3779B1)) ^ (iy.astype(np.uint64) * np.uint64(0x85EBCA77)) \
        ^ (iz.astype(np.uint64) * np.uint64(0xC2B2AE3D)) ^ np.uint64(seed)
    h ^= h >> np.uint64(15)
    h *= np.uint64(0x2C1B3C6D)
    h ^= h >> np.uint64(12)
    h *= np.uint64(0x297A2D39)
    h ^= h >> np.uint64(15)
    return (h & np.uint64(0xFFFFFF)).astype(np.float64) / float(0xFFFFFF)


def vnoise(P, seed):
    Pi = np.floor(P)
    f = P - Pi
    f = f * f * (3.0 - 2.0 * f)
    Pi = Pi.astype(np.int64)
    out = np.zeros(len(P))
    for dx in (0, 1):
        for dy in (0, 1):
            for dz in (0, 1):
                w = (f[:, 0] if dx else 1 - f[:, 0]) * (f[:, 1] if dy else 1 - f[:, 1]) * (f[:, 2] if dz else 1 - f[:, 2])
                out += _hash(Pi[:, 0] + dx, Pi[:, 1] + dy, Pi[:, 2] + dz, seed) * w
    return out


def fbm(P, seed, octaves=4):
    tot, amp, norm = np.zeros(len(P)), 1.0, 0.0
    for o in range(octaves):
        tot += vnoise(P * (2.0 ** o), seed + o * 1013) * amp
        norm += amp
        amp *= 0.5
    return tot / norm


def ss(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def weather(kind, paints, pid, P, N, ao, edge, overhead):
    """Albedo (linear), roughness, metalness per texel from the bakes."""
    n = len(pid)
    seed = zlib.crc32(kind.encode())
    y = P[:, 1]
    up = np.clip(N[:, 1], 0.0, 1.0)
    n1 = fbm(P * 3.0, seed + 1)
    n2 = fbm(P * 9.0, seed + 2)
    n3 = fbm(P * np.array([26.0, 1.3, 26.0]), seed + 3, 3)
    n4 = fbm(P * 15.0, seed + 4)
    n5 = fbm(P * 1.6, seed + 5, 3)
    nck = fbm(P * np.array([55.0, 0.6, 55.0]), seed + 6, 2)
    em = np.clip(edge * 7.0, 0.0, 1.0)
    convex = em * ss(0.55, 0.9, ao)
    dust = lin('#6b6357')
    rust_col = lin('#6b3c22')
    col = np.zeros((n, 3))
    rough = np.ones(n)
    metal = np.zeros(n)
    for i, name in enumerate(paints):
        s = pid == i
        if not s.any():
            continue
        p = PAINTS[name]
        c = np.tile(lin(p['c']), (s.sum(), 1))
        r = np.full(s.sum(), p['r'])
        mt = np.full(s.sum(), p['m'])
        c *= (1.0 + p.get('mottle', 0.1) * (n1[s] - 0.5) * 2.0)[:, None]
        c *= (1.0 + p.get('mottle', 0.1) * 0.6 * (n2[s] - 0.5) * 2.0)[:, None]
        if p.get('fade'):
            lum = (c * np.array([0.2126, 0.7152, 0.0722])).sum(1, keepdims=True)
            faded = lum * 1.12 + 0.025
            k = (p['fade'] * (0.35 + 0.65 * up[s]) * (0.55 + 0.9 * n5[s]))[:, None]
            c = c + (faded - c) * np.clip(k, 0.0, 0.9)
            r = r + 0.08 * k[:, 0]
        if p.get('checks'):
            mk = ss(0.62, 0.72, nck[s]) * p['checks']
            c *= (1.0 - 0.55 * mk)[:, None]
        if p.get('streak'):
            mk = ss(0.50, 0.72, n3[s]) * p['streak'] * (0.6 + 0.4 * (1.0 - up[s]))
            c *= (1.0 - 0.38 * mk)[:, None]
            r = r + 0.06 * mk
        if p.get('wear'):
            w = p['wear'] * ss(0.15, 0.6, convex[s]) * ss(0.35, 0.65, n4[s])
            w = np.maximum(w, p['wear'] * 0.6 * ss(0.78, 0.92, n4[s] * 0.6 + n2[s] * 0.4) * (1.0 - ss(0.3, 1.2, y[s])))
            c = c + (lin(p.get('wear_col', '#808080')) - c) * w[:, None]
            r = r + (0.5 - r) * w
            mt = mt + (p.get('wear_metal', 0.3) - mt) * w
        if p.get('rust'):
            q = n2[s] * 0.65 + em[s] * 0.25 + (1.0 - ss(0.0, 0.45, y[s])) * 0.15 * (0 if overhead else 1) + n4[s] * 0.1
            rr = p['rust'] * ss(0.58, 0.78, q) * 2.2
            rr = np.clip(rr, 0.0, 0.85)
            c = c + (rust_col * (0.75 + 0.5 * n1[s])[:, None] - c) * rr[:, None]
            r = r + (0.88 - r) * rr
            mt = mt * (1.0 - rr)
        if p.get('dust'):
            d = p['dust'] * (0.45 + 0.55 * n1[s]) * (0.5 + 0.5 * up[s])
            c = c + (dust * 1.4 - c) * (d * 0.55)[:, None]
            r = r + (0.6 - r) * d * 0.6
        if p.get('grime') and not overhead:
            g = p['grime'] * (0.85 * (1.0 - ss(0.0, 0.32, y[s])) + 0.30 * (1.0 - ss(0.0, 1.0, y[s]))) * (0.65 + 0.7 * n4[s])
            g = g + p['grime'] * 0.35 * (1.0 - ao[s]) * (0.5 + n2[s])
            g = np.clip(g, 0.0, 0.92)
            c = c + (dust * (0.8 + 0.4 * n1[s])[:, None] - c) * g[:, None]
            r = r + (0.93 - r) * g
            mt = mt * (1.0 - g)
        c *= (0.42 + 0.58 * ao[s])[:, None]
        col[s] = c
        rough[s] = r
        metal[s] = mt
    return np.clip(col, 0.0, 1.0), np.clip(rough, 0.05, 1.0), np.clip(metal, 0.0, 1.0)


def paint_palm(res):
    """The palm atlas, painted from noise: trunk with diamond leaf-base scars, the boss,
    leaflet bands (young, mature, old, dead; base to tip along u, shade along v), rachis."""
    ys, xs = np.mgrid[0:res, 0:res]
    u = (xs + 0.5) / res
    v = (ys + 0.5) / res
    P = np.stack([u.ravel() * 37.0, v.ravel() * 41.0, np.zeros(res * res)], axis=1)
    n1 = fbm(P * 1.0, 11).reshape(res, res)
    n2 = fbm(P * 5.0, 12).reshape(res, res)
    col = np.zeros((res, res, 3))
    rough = np.full((res, res), 0.85)
    # trunk (u 0-0.5 around, v 0-1 = 0-7.3 m)
    tu, tv = u / 0.5, v * 7.3
    wob = (n1 - 0.5) * 0.35
    a = tu * 20.0 + tv * 6.5 + wob
    b = tu * 20.0 - tv * 6.5 + wob
    da = a - np.floor(a)
    db = b - np.floor(b)
    groove = 1.0 - ss(0.03, 0.14, np.minimum(np.minimum(da, 1 - da), np.minimum(db, 1 - db)))
    # each scar's upper edge catches the light, its lower lip is in shade
    relief = ss(0.55, 0.95, da) * ss(0.55, 0.95, db) - ss(0.55, 0.95, 1 - da) * ss(0.55, 0.95, 1 - db)
    base = lin('#76695a')[None, None, :] * (0.82 + 0.36 * n1[..., None])
    base = base * (1.0 + 0.3 * (n2[..., None] - 0.5))
    grey = lin('#7e7b72')
    low = (1.0 - ss(0.4, 2.6, tv))[..., None]
    trunk = base * (1.0 - 0.38 * groove[..., None] + 0.12 * relief[..., None]) * (1.0 - 0.2 * low) + grey * 0.22 * low
    dirt = (1.0 - ss(0.0, 0.6, tv))[..., None] * 0.5
    trunk = trunk + (lin('#5a5248') - trunk) * dirt
    m_trunk = u < 0.5
    col[m_trunk] = trunk[m_trunk]
    # boss
    m_boss = (u >= 0.5) & (u < 0.75) & (v >= 0.5)
    bu, bv = (u - 0.5) / 0.25, (v - 0.5) / 0.5
    a = bu * 18.0 + bv * 6.0
    b = bu * 18.0 - bv * 6.0
    stub = 1.0 - ss(0.06, 0.2, np.minimum(np.abs(a - np.round(a)), np.abs(b - np.round(b))))
    boss = lin('#8f6f45')[None, None, :] * (0.8 + 0.4 * n1[..., None]) * (1.0 - 0.6 * stub[..., None])
    col[m_boss] = boss[m_boss]
    # leaflets
    classes = {'young': ('#73903f', '#8a9a4a'), 'mature': ('#4d6b2d', '#5f7434'), 'old': ('#8d8a3e', '#a8914a'), 'dead': ('#8b7452', '#7a6447')}
    for k, cls in enumerate(PALM_CLASSES):
        mb = (u >= 0.5) & (v >= k * 0.125) & (v < (k + 1) * 0.125)
        t = (u - 0.5) / 0.5
        shade = ((v - k * 0.125) / 0.125 - 0.12) / 0.76
        c0, c1 = lin(classes[cls][0]), lin(classes[cls][1])
        mix = np.clip(1.0 - t * 1.4, 0.0, 1.0)[..., None]
        c = c0 * (1.0 - mix) + c1 * mix
        tipb = ss(0.82, 1.0, t)[..., None] * (0.55 if cls != 'dead' else 0.2)
        c = c + (lin('#8a7550') - c) * tipb
        c = c * (0.85 + 0.3 * n2[..., None]) * (0.45 + 0.6 * np.clip(shade, 0.0, 1.0))[..., None]
        col[mb] = c[mb]
        rough[mb] = 0.62 if cls in ('young', 'mature') else 0.8
    for k, cls in enumerate(PALM_CLASSES):
        mb = (u >= 0.75) & (v >= 0.5 + k * 0.125) & (v < 0.5 + (k + 1) * 0.125)
        t = (u - 0.75) / 0.25
        c0 = lin({'young': '#a3a65e', 'mature': '#999a58', 'old': '#a8975e', 'dead': '#7f6a4e'}[cls])
        c = c0 * (0.85 + 0.3 * n1[..., None]) * (1.0 - 0.25 * t[..., None])
        col[mb] = c[mb]
        rough[mb] = 0.7
    rough[m_trunk] = 0.92
    rough[m_boss] = 0.9
    return np.clip(col.reshape(-1, 3), 0.0, 1.0), rough.ravel(), np.zeros(res * res), np.ones(res * res)


