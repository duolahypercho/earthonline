"""Build the v2 street-prop GLBs: San Francisco's street furniture modelled from parameters.

Usage (headless, Blender 4.5):
  blender -b --factory-startup --python scripts/assets/build-street-props-v2.py -- [kind ...] [--renders DIR] [--no-build]

Every model here is built by this script from published dimensions and the
City's own standards (the `SOURCES` table, each with its URL); nothing is
imported, generated by a model service or traced from imagery. The v1 slot each
kind replaces (public/assets/street-props/street-props-v1.provenance.json) gives
the target bounds and the triangle budget (about the v1 count, never over 2x).

The pipeline per kind:

  * a mesh in the street-furniture frame: glTF Y up, origin at the centre of
    the foot (or the kind's own anchor, see each builder), the long side along
    +X (along the street), -Z toward the carriageway and +Z toward the footway;
    every face tagged with a paint (`PAINTS`);
  * smart UV unwrap into one atlas of ATLAS_PX square;
  * Cycles bakes of the paint id, object position, normal, ambient occlusion
    (with the footway as a ground plane) and a bevel edge mask;
  * the weathering is computed per texel in numpy from those bakes: mottled and
    sun-faded paint, rain streaks, scuffed edges, rust, road dust rising from
    the foot, grime in the crevices - matte, aged surfaces that read at 5-30 m;
  * one albedo JPEG and one metallic-roughness JPEG (glTF: G roughness, B
    metalness; R carries the baked occlusion) shared by every material of the
    kind, so a loader that reads only the first material still draws every
    part with the right colours;
  * materials: `body` first, then the named parts a renderer lights or treats
    apart (`lamp_glass`, `lens_red`, `lens_amber`, `lens_green`, `glass`,
    `ad_panel`, `lantern_silk`), all on the same atlas;
  * the GLB, re-read and checked (bounds against the v1 slot, triangles against
    the budget, baseline JPEGs), and a row in street-props-v2.provenance.json.

The palm and its far form are painted, not baked: their fronds share UVs.

The renders (`--renders DIR`, a folder outside the repository) are a lineup
of every kind beside a 1.8 m figure and one sheet per priority group.
"""

