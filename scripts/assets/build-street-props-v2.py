def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    render_dir = None
    if '--renders' in argv:
        i = argv.index('--renders')
        render_dir = argv[i + 1]
        del argv[i:i + 2]
    no_build = '--no-build' in argv
    argv = [a for a in argv if not a.startswith('--')]
    only = argv or list(KINDS)
    v1 = json.load(open(V1_PROVENANCE))['assets']
    rows = {}
    if os.path.exists(V2_PROVENANCE):
        rows = json.load(open(V2_PROVENANCE)).get('assets', {})
    if not no_build:
        for kind in only:
            spec = KINDS[kind]
            if os.path.exists(os.path.join(OUT_DIR, f'{kind}-v1.glb')):
                print(f'[street-props-v2] {kind}: its v1 GLB is present, skipped')
                continue
            rows[kind] = build_kind(kind, spec, v1[kind])
        json.dump({
            'version': 'street-props-v2',
            'note': 'San Francisco street furniture modelled from parameters by scripts/assets/build-street-props-v2.py in Blender: '
                    'no imported, generated or traced geometry and no downloaded imagery. Dimensions from the sources listed in '
                    'dimensionSources; where none was readable the v1 slot is kept (see each row\'s fitToSlot and deviation). '
                    'Frame: glTF Y up, origin at the foot unless the row says otherwise, +X along the street, -Z toward the '
                    'carriageway. Materials share one albedo and one metallic-roughness JPEG per kind; `body` is always first.',
            'assets': {k: rows[k] for k in sorted(rows)},
            'dimensionSources': SOURCES,
            'referencePhotosPending': REFERENCE_PHOTOS,
            'materialNames': {
                'body': 'every ordinary part',
                'lamp_glass': 'lamp glass / refractor; emissiveFactor is the 3000 K night colour, to be scaled by the lamp state',
                'lens_red/lens_amber/lens_green': 'signal lenses (unlit tint); the renderer lights them',
                'glass': 'shelter glazing, alpha 0.35 (BLEND)',
                'ad_panel': 'shelter poster faces (plain tones, no artwork)',
                'lantern_silk': 'the lantern body, for a lit-lantern treatment',
            },
        }, open(V2_PROVENANCE, 'w'), indent=2, sort_keys=False)
        print(f'[street-props-v2] wrote {V2_PROVENANCE}')
