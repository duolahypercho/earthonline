PALM_CLASSES = ('young', 'mature', 'old', 'dead')


def _palm_uv_leaf(cls, t, shade):
    band = PALM_CLASSES.index(cls)
    return (0.5 + 0.5 * min(max(t, 0.01), 0.99), band * 0.125 + 0.125 * (0.12 + 0.76 * shade))


def _palm_uv_rachis(cls, t):
    band = PALM_CLASSES.index(cls)
    return (0.75 + 0.25 * min(max(t, 0.01), 0.99), 0.5 + band * 0.125 + 0.06)


def palm_trunk(m, sides, rings_trunk, boss_rings):
    tr = [(0.62, 0.0), (0.52, 0.12), (0.47, 0.35), (0.44, 2.0), (0.42, 4.0), (0.43, 6.0), (0.47, 6.9), (0.55, 7.3)]
    if rings_trunk < len(tr):
        tr = [tr[0], tr[2], tr[4], tr[-1]]
    boss = [(0.55, 7.3), (0.66, 7.6), (0.64, 7.9), (0.50, 8.1), (0.30, 8.25), (0.0, 8.3)]
    if boss_rings < len(boss):
        boss = [boss[0], boss[1], boss[3], boss[-1]]
    for prof, region in ((tr, 'trunk'), (boss, 'boss')):
        ring_ids = []
        for (r, y) in prof:
            if r <= 1e-7:
                ring_ids.append([m.vert((0.0, y, 0.0))] * sides)
                continue
            fl = flutes(9, 0.10) if region == 'boss' else (lambda a: 1.0)
            ring_ids.append([m.vert((r * fl(TAU * s / sides) * math.cos(TAU * s / sides), y, r * fl(TAU * s / sides) * math.sin(TAU * s / sides)))
                             for s in range(sides)])
        for k in range(len(prof) - 1):
            for s in range(sides):
                s1 = s + 1
                a, b = ring_ids[k], ring_ids[k + 1]
                idx = [a[s], a[s1 % sides], b[s1 % sides], b[s]]
                # outward: (k,i),(k+1,i),(k+1,i+1),(k,i+1) per the kit; here reversed order list
                idx = [a[s], b[s], b[s1 % sides], a[s1 % sides]]
                corners = [(s, k), (s, k + 1), (s1, k + 1), (s1, k)]
                uv = []
                for (ss, kk) in corners:
                    y = prof[kk][1]
                    if region == 'trunk':
                        uv.append((0.5 * ss / sides, min(y / 7.3, 1.0)))
                    else:
                        uv.append((0.5 + 0.25 * ss / sides, 0.5 + 0.5 * min(max((y - 7.3) / 1.0, 0.0), 1.0)))
                dedup = []
                duv = []
                for i_, u_ in zip(idx, uv):
                    if i_ not in dedup:
                        dedup.append(i_)
                        duv.append(u_)
                if len(dedup) >= 3:
                    m.face(dedup, 'palm', uv=tuple(duv))
                    c = m.centroid(dedup)
                    if m.newell(dedup).dot(Vector((c.x, 0.0, c.z))) < 0:
                        m.reverse(len(m.f) - 1)
    # bottom cap
    ring = list(range(0, sides))
    return


def palm_fronds(m, n, leaf_pairs, far=False, length_k=1.0):
    golden = math.pi * (3.0 - math.sqrt(5.0))
    up = Vector((0, 1, 0))
    for i in range(n):
        f = i / n
        phi = i * golden
        jit = ((i * 7) % 5) / 4.0
        if f < 0.18:
            cls, elev, L, droop = 'young', 1.15 - f * 1.5, 3.3, 0.16
        elif f < 0.72:
            cls, elev, L, droop = 'mature', 0.85 - (f - 0.18) * 1.85, 4.4, 0.42
        elif f < 0.91:
            cls, elev, L, droop = 'old', -0.20 - (f - 0.72) * 2.0, 4.1, 0.30
        else:
            cls, elev, L, droop = 'dead', -1.25, 2.8, 0.08
        L *= (0.93 + 0.14 * jit) * length_k
        d0 = Vector((math.cos(elev) * math.cos(phi), math.sin(elev), math.cos(elev) * math.sin(phi)))
        root = Vector((math.cos(phi) * 0.30, 8.15 - f * 0.75, math.sin(phi) * 0.30))
        pos = lambda t: root + d0 * (L * t) - up * (droop * L * t * t)

        def frame(t):
            tg = (d0 * L - up * (2.0 * droop * L * t)).normalized()
            side = tg.cross(up)
            side = side.normalized() if side.length > 1e-6 else Vector((1, 0, 0))
            u = side.cross(tg).normalized()
            return tg, side, u
        segs = 8 if far else 10
        if far:
            # a folded ribbon whose edges carry the leaflet colour
            prev = None
            for k in range(segs + 1):
                t = k / segs
                p = pos(t)
                tg, side, u = frame(t)
                w = 0.55 * math.sin(math.pi * min(t * 1.05, 1.0)) ** 0.6 * (1.0 - 0.25 * t) * (t / 0.12 if t < 0.12 else 1.0)
                if k % 2 == 1:
                    w *= 0.55   # leaflet teeth along the edge
                fold = 0.45
                a = m.vert(p)
                l = m.vert(p + side * (w * math.cos(fold)) + u * (w * math.sin(fold)))
                r = m.vert(p - side * (w * math.cos(fold)) + u * (w * math.sin(fold)))
                cur = (a, l, r, t)
                if prev:
                    pa, pl, pr, pt = prev
                    uvc = lambda tt: _palm_uv_leaf(cls, tt, 0.35)
                    uve = lambda tt: _palm_uv_leaf(cls, tt, 0.8)
                    m.face([pa, a, l, pl], 'palm', uv=(uvc(pt), uvc(t), uve(t), uve(pt)))
                    m.face([pa, pr, r, a], 'palm', uv=(uvc(pt), uve(pt), uve(t), uvc(t)))
                prev = cur
            continue
        # rachis: a narrow V strip
        prev = None
        for k in range(segs + 1):
            t = k / segs
            p = pos(t)
            tg, side, u = frame(t)
            rw = 0.045 * (1.0 - 0.8 * t) + 0.006
            a = m.vert(p + u * 0.014)
            l = m.vert(p + side * rw - u * 0.006)
            r = m.vert(p - side * rw - u * 0.006)
            if prev:
                pa, pl, pr, pt = prev
                uvc = lambda tt: _palm_uv_rachis(cls, tt)
                m.face([pa, a, l, pl], 'palm', uv=(uvc(pt), uvc(t), uvc(t), uvc(pt)))
                m.face([pa, pr, r, a], 'palm', uv=(uvc(pt), uvc(pt), uvc(t), uvc(t)))
            prev = (a, l, r, t)
        # leaflets: single tapering blades in a V, alternate pairs lifted and dropped
        for j in range(leaf_pairs):
            t = 0.20 + 0.78 * (j + 0.5) / leaf_pairs
            p = pos(t)
            tg, side, u = frame(t)
            ell = 0.58 * math.sin(math.pi * (t - 0.14) / 0.90) ** 0.55 + 0.08
            if cls == 'young':
                ell *= 0.85
            for sgn in (-1.0, 1.0):
                th = math.radians(32 + (18 if j % 2 == 0 else -14) + 7 * math.sin(i * 1.7 + j))
                if cls == 'dead':
                    th = math.radians(-55)
                dvec = (side * (sgn * math.cos(th)) + u * math.sin(th) + tg * 0.55).normalized()
                tip = p + dvec * ell - up * (0.10 * ell + (0.25 * ell if cls in ('old', 'dead') else 0.0))
                b1 = p - tg * 0.055
                b2 = p + tg * 0.055
                ia, ib, ic = m.vert(b1), m.vert(b2), m.vert(tip)
                # shade: leaflets low on the crown and pointing down sit in the crown's shadow
                shade = min(max(0.55 + 0.45 * dvec.y + 0.25 * (1.0 - f) - 0.25 * (1 - t), 0.0), 1.0)
                m.face([ia, ib, ic], 'palm', uv=(_palm_uv_leaf(cls, t, shade), _palm_uv_leaf(cls, t + 0.02, shade), _palm_uv_leaf(cls, min(t + 0.12, 0.99), shade)))


def fit_dims(m, target):
    """Scale about the trunk axis and the ground so the bounds are `target` (the v1 slot)."""
    xs = [v[0] for v in m.v]
    ys = [v[1] for v in m.v]
    zs = [v[2] for v in m.v]
    cx, cz = (min(xs) + max(xs)) / 2, (min(zs) + max(zs)) / 2
    kx = target[0] / (max(xs) - min(xs))
    ky = target[1] / max(ys)
    kz = target[2] / (max(zs) - min(zs))
    print(f'[street-props-v2] palm fit: x {kx:.3f} y {ky:.3f} z {kz:.3f}')
    m.v = [((x - cx) * kx, y * ky, (z - cz) * kz) for (x, y, z) in m.v]


