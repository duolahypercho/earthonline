# ============================================================================ the modelling kit
# The kit works in the street-furniture frame (glTF: x along the street, y up,
# z toward the footway). Blender gets (x, -z, y), a proper rotation, so a face
# wound counter-clockwise seen from outside stays outward after export.

def V3(x, y=None, z=None):
    if y is None:
        return Vector(x)
    return Vector((x, y, z))


class Mesh:
    def __init__(self):
        self.v = []      # vertex positions (tuples)
        self.f = []      # faces (tuples of vertex indices)
        self.p = []      # paint per face
        self.uv = []     # per face: tuple of (u, v) per corner, or None (palm only)

    def vert(self, p):
        self.v.append((float(p[0]), float(p[1]), float(p[2])))
        return len(self.v) - 1

    def face(self, idx, paint, uv=None):
        assert paint in PAINTS or paint.startswith('palm'), paint
        self.f.append(tuple(idx))
        self.p.append(paint)
        self.uv.append(uv)

    def mark(self):
        return (len(self.v), len(self.f))

    def apply(self, mark, mat):
        """Transform every vertex added since `mark` by a 4x4 matrix (positive determinant)."""
        for i in range(mark[0], len(self.v)):
            self.v[i] = tuple(mat @ Vector(self.v[i]))

    def place(self, mark, at=(0, 0, 0), axis=None, q=None, scale=None):
        m = Matrix.Identity(4)
        if scale is not None:
            m = Matrix.Diagonal((scale[0], scale[1], scale[2], 1.0))
        if axis is not None:
            m = Vector((0, 1, 0)).rotation_difference(Vector(axis).normalized()).to_matrix().to_4x4() @ m
        if q is not None:
            m = q.to_matrix().to_4x4() @ m
        m = Matrix.Translation(Vector(at)) @ m
        self.apply(mark, m)

    def newell(self, idx):
        n = Vector((0.0, 0.0, 0.0))
        for a, b in zip(idx, idx[1:] + idx[:1]):
            pa, pb = self.v[a], self.v[b]
            n.x += (pa[1] - pb[1]) * (pa[2] + pb[2])
            n.y += (pa[2] - pb[2]) * (pa[0] + pb[0])
            n.z += (pa[0] - pb[0]) * (pa[1] + pb[1])
        return n

    def centroid(self, idx):
        c = Vector((0.0, 0.0, 0.0))
        for i in idx:
            c += Vector(self.v[i])
        return c / len(idx)

    def reverse(self, fi):
        self.f[fi] = tuple(reversed(self.f[fi]))
        if self.uv[fi] is not None:
            self.uv[fi] = tuple(reversed(self.uv[fi]))

    def orient_from(self, f0, inside):
        """Every face from index f0 on faces away from `inside` (convex parts)."""
        for fi in range(f0, len(self.f)):
            if self.newell(list(self.f[fi])).dot(self.centroid(self.f[fi]) - Vector(inside)) < 0:
                self.reverse(fi)

    def orient_cap(self, fi, outward):
        if self.newell(list(self.f[fi])).dot(Vector(outward)) < 0:
            self.reverse(fi)


def _bridge(m, rings, centres, paint, closed=True):
    """Quads between consecutive rings (lists of vertex indices; a pole ring repeats
    one index). Wound outward from the ring centres, decided over all its faces."""
    f0 = len(m.f)
    for k in range(len(rings) - 1):
        a, b = rings[k], rings[k + 1]
        n = len(a)
        for i in range(n if closed else n - 1):
            j = (i + 1) % n
            q = []
            for x in (a[i], b[i], b[j], a[j]):
                if x not in q:
                    q.append(x)
            if len(q) >= 3:
                m.face(q, paint)
    score = 0.0
    for fi in range(f0, len(m.f)):
        idx = m.f[fi]
        nrm = m.newell(list(idx))
        c = m.centroid(idx)
        # the ring this face starts on
        k = min(range(len(centres)), key=lambda kk: (Vector(centres[kk]) - c).length)
        r = c - Vector(centres[k])
        if nrm.length > 1e-12 and r.length > 1e-9:
            score += nrm.normalized().dot(r.normalized()) * nrm.length
    if score < 0:
        for fi in range(f0, len(m.f)):
            m.reverse(fi)
    return f0


def lathe(m, prof, sides, paint, at=(0, 0, 0), axis=None, shape=None, phase=0.0, caps=(True, True), q=None):
    """A surface of revolution about +Y: `prof` is (radius, y) bottom up. `shape(a)`
    scales the radius by angle (flutes, a rounded square). Placed at `at`, its +Y
    turned onto `axis`."""
    mk = m.mark()
    rings, centres = [], []
    for (r, y) in prof:
        if r <= 1e-7:
            i = m.vert((0.0, y, 0.0))
            rings.append([i] * sides)
        else:
            ring = []
            for s in range(sides):
                a = phase + TAU * s / sides
                f = shape(a) if shape else 1.0
                ring.append(m.vert((r * f * math.cos(a), y, r * f * math.sin(a))))
            rings.append(ring)
        centres.append((0.0, y, 0.0))
    _bridge(m, rings, centres, paint)
    if caps[0] and prof[0][0] > 1e-7:
        m.face(list(rings[0]), paint)
        m.orient_cap(len(m.f) - 1, (0, -1, 0))
    if caps[1] and prof[-1][0] > 1e-7:
        m.face(list(rings[-1]), paint)
        m.orient_cap(len(m.f) - 1, (0, 1, 0))
    m.place(mk, at=at, axis=axis, q=q)
    return mk


def sweep(m, pts, radii, sides, paint, caps=True, closed_loop=False, squash=None):
    """A round tube along `pts` (radius radii[i], the last beyond), parallel-transported
    frames. `squash` (k) scales the section along the frame normal (an elliptical arm)."""
    pts = [Vector(p) for p in pts]
    n = len(pts)
    rad = lambda i: radii[min(i, len(radii) - 1)]

    def tan(i):
        if closed_loop:
            return (pts[(i + 1) % n] - pts[(i - 1) % n]).normalized()
        return (pts[min(i + 1, n - 1)] - pts[max(i - 1, 0)]).normalized()

    t0 = tan(0)
    ref = Vector((0, 1, 0)) if abs(t0.y) < 0.9 else Vector((1, 0, 0))
    nrm = t0.cross(ref).normalized()
    prev = t0
    rings, centres, frames = [], [], []
    for i in range(n):
        t = tan(i)
        nrm = (prev.rotation_difference(t) @ nrm).normalized()
        prev = t
        b = t.cross(nrm)
        frames.append((nrm.copy(), b.copy()))
        ring = []
        for j in range(sides):
            a = TAU * j / sides
            d = nrm * (math.cos(a) * (squash or 1.0)) + b * math.sin(a)
            ring.append(m.vert(pts[i] + d * rad(i)))
        rings.append(ring)
        centres.append(tuple(pts[i]))
    if closed_loop:
        rings.append(rings[0])
        centres.append(centres[0])
    _bridge(m, rings, centres, paint)
    if caps and not closed_loop:
        m.face(list(rings[0]), paint)
        m.orient_cap(len(m.f) - 1, -tan(0))
        m.face(list(rings[n - 1]), paint)
        m.orient_cap(len(m.f) - 1, tan(n - 1))


def box(m, mn, mx, paint, q=None, pivot=None):
    """An axis-aligned box from mn to mx, optionally turned by `q` about `pivot` (default its centre)."""
    mn, mx = Vector(mn), Vector(mx)
    c = (mn + mx) / 2
    mk = m.mark()
    ids = []
    for k in range(8):
        ids.append(m.vert((mx.x if k & 1 else mn.x, mx.y if k & 2 else mn.y, mx.z if k & 4 else mn.z)))
    f0 = len(m.f)
    for quad in ((1, 3, 7, 5), (4, 6, 2, 0), (2, 6, 7, 3), (0, 1, 5, 4), (4, 5, 7, 6), (0, 2, 3, 1)):
        m.face([ids[i] for i in quad], paint)
    m.orient_from(f0, c)
    if q is not None:
        pv = Vector(pivot) if pivot is not None else c
        m.apply(mk, Matrix.Translation(pv) @ q.to_matrix().to_4x4() @ Matrix.Translation(-pv))


def cube(m, c, size, paint, q=None):
    c, size = Vector(c), Vector(size)
    box(m, c - size / 2, c + size / 2, paint, q=q, pivot=c)


def bar(m, p0, p1, w, t, paint, up=(0, 1, 0)):
    """A rectangular bar from p0 to p1, `w` wide (across, near `up` x dir) and `t` thick."""
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    L = d.length
    mk = m.mark()
    box(m, (-w / 2, 0, -t / 2), (w / 2, L, t / 2), paint)
    q = Vector((0, 1, 0)).rotation_difference(d.normalized())
    m.place(mk, at=p0, q=q)


def extrude(m, poly, z0, z1, paint, caps=(True, True)):
    """A prism of a convex 2-D outline (x, y) between z0 and z1."""
    f0 = len(m.f)
    a = [m.vert((x, y, z0)) for (x, y) in poly]
    b = [m.vert((x, y, z1)) for (x, y) in poly]
    n = len(poly)
    for i in range(n):
        j = (i + 1) % n
        m.face([a[i], a[j], b[j], b[i]], paint)
    cx = sum(p[0] for p in poly) / n
    cy = sum(p[1] for p in poly) / n
    m.orient_from(f0, (cx, cy, (z0 + z1) / 2))
    if caps[0]:
        m.face(list(a), paint)
        m.orient_cap(len(m.f) - 1, (0, 0, -1 if z0 < z1 else 1))
    if caps[1]:
        m.face(list(b), paint)
        m.orient_cap(len(m.f) - 1, (0, 0, 1 if z0 < z1 else -1))


def loft(m, stations, ring, exp, paint, flat=True):
    """A shell along local -z: per station (z, half width, y bottom, y top), a
    superellipse section of exponent `exp` (much squarer below when `flat`)."""
    rings, centres = [], []
    for (z, hw, yb, yt) in stations:
        mid, half = (yb + yt) / 2, (yt - yb) / 2
        r = []
        for j in range(ring):
            a = TAU * j / ring
            s, c = math.sin(a), math.cos(a)
            e = 0.22 if (flat and s < 0) else 2.0 / exp
            x = math.copysign(abs(c) ** e, c) * hw
            y = mid + math.copysign(abs(s) ** e, s) * half
            r.append(m.vert((x, y, z)))
        rings.append(r)
        centres.append((0.0, mid, z))
    _bridge(m, rings, centres, paint)
    m.face(list(rings[0]), paint)
    m.orient_cap(len(m.f) - 1, (0, 0, 1))
    m.face(list(rings[-1]), paint)
    m.orient_cap(len(m.f) - 1, (0, 0, -1))


def disc(m, c, r, n, paint, normal=(0, 0, 1), sag=0.0):
    """A flat (or slightly sagging) disc facing `normal`."""
    mk = m.mark()
    ring = [m.vert((r * math.cos(TAU * i / n), 0.0, r * math.sin(TAU * i / n))) for i in range(n)]
    ctr = m.vert((0.0, -sag, 0.0))
    for i in range(n):
        m.face([ctr, ring[(i + 1) % n], ring[i]], paint)
        m.orient_cap(len(m.f) - 1, (0, 1, 0))
    q = Vector((0, 1, 0)).rotation_difference(Vector(normal).normalized())
    m.place(mk, at=c, q=q)


def quad(m, pts, paint, facing=None):
    ids = [m.vert(p) for p in pts]
    m.face(ids, paint)
    if facing is not None:
        m.orient_cap(len(m.f) - 1, facing)


def grid(m, fn, nu, nv, paint_of, facing=None):
    """A sheet from fn(u, v) -> point, nu x nv cells; paint_of(i, j) names each cell's paint."""
    ids = [[m.vert(fn(i / nu, j / nv)) for j in range(nv + 1)] for i in range(nu + 1)]
    for i in range(nu):
        for j in range(nv):
            m.face([ids[i][j], ids[i + 1][j], ids[i + 1][j + 1], ids[i][j + 1]], paint_of(i, j))
            if facing is not None:
                m.orient_cap(len(m.f) - 1, facing)


def bez(p, k):
    p = [Vector(x) for x in p]
    out = []
    for i in range(k + 1):
        t = i / k
        u = 1 - t
        out.append(p[0] * (u * u * u) + p[1] * (3 * u * u * t) + p[2] * (3 * u * t * t) + p[3] * (t * t * t))
    return out


def flutes(n, depth):
    return lambda a: 1.0 - depth * (0.5 - 0.5 * math.cos(n * a))


def superellipse(p):
    return lambda a: (abs(math.cos(a)) ** p + abs(math.sin(a)) ** p) ** (-1.0 / p)


def hexnut(m, c, r, h, paint, axis=(0, 1, 0)):
    lathe(m, [(r, 0.0), (r, h)], 6, paint, at=c, axis=axis)


