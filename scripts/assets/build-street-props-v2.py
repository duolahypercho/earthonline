def make_image(name, rgb8, res, colorspace):
    img = bpy.data.images.new(name, res, res, alpha=False)
    img.colorspace_settings.name = colorspace
    px = np.ones((res * res, 4), dtype=np.float32)
    px[:, :3] = rgb8.astype(np.float32) / 255.0
    img.pixels.foreach_set(px.ravel())
    path = os.path.join(bpy.app.tempdir, f'{name}.png')
    img.filepath_raw = path
    img.file_format = 'PNG'
    img.save()
    return img


def final_materials(obj, kind, paints, m_paints, albedo, mr):
    slots = []
    for p in m_paints:
        s = SLOT_OF.get(p, 'body')
        if s not in slots:
            slots.append(s)
    slots.sort(key=SLOT_ORDER.index)
    if 'body' not in slots:
        slots.insert(0, 'body')
    me = obj.data
    me.materials.clear()
    for s in slots:
        mat = bpy.data.materials.new(s)
        mat.use_nodes = True
        nt = mat.node_tree
        bsdf = next(n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED')
        t0 = nt.nodes.new('ShaderNodeTexImage')
        t0.image = albedo
        nt.links.new(t0.outputs['Color'], bsdf.inputs['Base Color'])
        t1 = nt.nodes.new('ShaderNodeTexImage')
        t1.image = mr
        sep = nt.nodes.new('ShaderNodeSeparateColor')
        nt.links.new(t1.outputs['Color'], sep.inputs['Color'])
        nt.links.new(sep.outputs['Green'], bsdf.inputs['Roughness'])
        nt.links.new(sep.outputs['Blue'], bsdf.inputs['Metallic'])
        if s == 'lamp_glass':
            bsdf.inputs['Emission Color'].default_value = (*LAMP_EMISSIVE, 1.0)
            bsdf.inputs['Emission Strength'].default_value = 1.0
        if s == 'glass':
            bsdf.inputs['Alpha'].default_value = 0.35
            try:
                mat.surface_render_method = 'BLENDED'
            except Exception:
                pass
        me.materials.append(mat)
    idx = [slots.index(SLOT_OF.get(p, 'body')) for p in m_paints]
    me.polygons.foreach_set('material_index', idx)
    if 'paint' in me.attributes:
        me.attributes.remove(me.attributes['paint'])
    return slots


def export(obj, path):
    select_only(obj)
    props = bpy.ops.export_scene.gltf.get_rna_type().properties
    vc = props['export_vertex_color'].enum_items.keys()
    kw = dict(filepath=path, export_format='GLB', use_selection=True, export_image_format='JPEG', export_jpeg_quality=JPEG_QUALITY,
              export_yup=True, export_apply=True, export_texcoords=True, export_normals=True, export_tangents=False,
              export_materials='EXPORT', export_animations=False, export_skins=False, export_morph=False, export_extras=False,
              export_cameras=False, export_lights=False, export_all_vertex_colors=False)
    if 'NONE' in vc:
        kw['export_vertex_color'] = 'NONE'
    if 'export_attributes' in props:
        kw['export_attributes'] = False
    bpy.ops.export_scene.gltf(**kw)


def read_glb(path):
    """Parse a GLB: JSON, binary chunk; bounds, triangles, material names, image formats."""
    data = open(path, 'rb').read()
    magic, ver, length = struct.unpack_from('<4sII', data, 0)
    assert magic == b'glTF' and ver == 2 and length == len(data)
    off = 12
    js, blob = None, b''
    while off < length:
        clen, ctype = struct.unpack_from('<I4s', data, off)
        chunk = data[off + 8: off + 8 + clen]
        if ctype == b'JSON':
            js = json.loads(chunk)
        elif ctype == b'BIN\x00':
            blob = chunk
        off += 8 + clen
    mn, mx = [1e9] * 3, [-1e9] * 3
    tris = 0
    for mesh in js['meshes']:
        for prim in mesh['primitives']:
            acc = js['accessors'][prim['attributes']['POSITION']]
            for i in range(3):
                mn[i] = min(mn[i], acc['min'][i])
                mx[i] = max(mx[i], acc['max'][i])
            tris += (js['accessors'][prim['indices']]['count'] if 'indices' in prim else acc['count']) // 3
    images = []
    for img in js.get('images', []):
        bv = js['bufferViews'][img['bufferView']]
        b = blob[bv.get('byteOffset', 0): bv.get('byteOffset', 0) + bv['byteLength']]
        baseline = b[:2] == b'\xff\xd8' and b'\xff\xc0' in b and b'\xff\xc2' not in b
        w = h = None
        i = b.find(b'\xff\xc0')
        if i >= 0:
            h, w = struct.unpack_from('>HH', b, i + 5)
        images.append({'mime': img.get('mimeType'), 'baseline': baseline, 'size': [w, h], 'bytes': len(b)})
    mats = [mt.get('name') for mt in js.get('materials', [])]
    return {'min': mn, 'max': mx, 'dims': [mx[i] - mn[i] for i in range(3)], 'triangles': tris, 'materials': mats,
            'images': images, 'nodes': [n.get('name') for n in js.get('nodes', [])]}


