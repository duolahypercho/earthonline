def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def to_object(m, name, uv_from_mesh=False):
    me = bpy.data.meshes.new(name)
    verts = [(x, -z, y) for (x, y, z) in m.v]
    me.from_pydata(verts, [], [list(f) for f in m.f])
    me.update()
    assert len(me.polygons) == len(m.f), f'{name}: {len(me.polygons)} faces against {len(m.f)} built'
    paints = sorted(set(m.p), key=m.p.index)
    attr = me.attributes.new('paint', 'FLOAT', 'FACE')
    attr.data.foreach_set('value', [float(paints.index(p)) for p in m.p])
    if uv_from_mesh:
        uvl = me.uv_layers.new(name='UVMap')
        data = []
        for poly, uv in zip(me.polygons, m.uv):
            assert uv is not None and len(uv) == poly.loop_total
            for c in uv:
                data.extend(c)
        uvl.data.foreach_set('uv', data)
    me.shade_smooth()
    me.set_sharp_from_angle(angle=SHARP_ANGLE)
    obj = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(obj)
    return obj, paints


def select_only(obj):
    for o in bpy.context.scene.objects:
        o.select_set(False)
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj


def unwrap(obj):
    select_only(obj)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.smart_project(angle_limit=math.radians(60), margin_method='FRACTION', island_margin=0.006,
                             area_weight=0.0, correct_aspect=True, scale_to_bounds=False)
    try:
        bpy.ops.uv.pack_islands(rotate=True, margin_method='FRACTION', margin=0.006, shape_method='CONCAVE')
    except TypeError:
        bpy.ops.uv.pack_islands(rotate=True, margin=0.006)
    bpy.ops.object.mode_set(mode='OBJECT')


def ground_plane():
    me = bpy.data.meshes.new('ground')
    me.from_pydata([(-30, -30, 0), (30, -30, 0), (30, 30, 0), (-30, 30, 0)], [], [[0, 1, 2, 3]])
    obj = bpy.data.objects.new('ground', me)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def bake(obj, res, overhead, ao_dist):
    """The id, position, normal, occlusion and edge bakes of `obj` (numpy arrays, rows bottom up)."""
    sc = bpy.context.scene
    sc.render.engine = 'CYCLES'
    sc.cycles.device = 'CPU'
    sc.cycles.use_denoising = False
    sc.cycles.seed = 0
    sc.cycles.use_animated_seed = False
    sc.render.bake.margin = BAKE_MARGIN
    sc.render.bake.margin_type = 'EXTEND'
    if not overhead:
        ground_plane()
    xs = [v.co for v in obj.data.vertices]
    mn = Vector((min(c.x for c in xs), min(c.y for c in xs), min(c.z for c in xs))) - Vector((0.01, 0.01, 0.01))
    mx = Vector((max(c.x for c in xs), max(c.y for c in xs), max(c.z for c in xs))) + Vector((0.01, 0.01, 0.01))
    size = mx - mn
    mat = bpy.data.materials.new('bake')
    mat.use_nodes = True
    obj.data.materials.clear()
    obj.data.materials.append(mat)
    nt = mat.node_tree
    N, L = nt.nodes, nt.links
    N.clear()
    out = N.new('ShaderNodeOutputMaterial')
    emit = N.new('ShaderNodeEmission')
    emit.inputs['Strength'].default_value = 1.0
    L.new(emit.outputs['Emission'], out.inputs['Surface'])
    tex = N.new('ShaderNodeTexImage')
    attr = N.new('ShaderNodeAttribute')
    attr.attribute_type = 'GEOMETRY'
    attr.attribute_name = 'paint'
    idm = N.new('ShaderNodeMath')
    idm.operation = 'MULTIPLY'
    idm.inputs[1].default_value = 1.0 / 64.0
    L.new(attr.outputs['Fac'], idm.inputs[0])
    tc = N.new('ShaderNodeTexCoord')
    sub = N.new('ShaderNodeVectorMath')
    sub.operation = 'SUBTRACT'
    sub.inputs[1].default_value = mn
    L.new(tc.outputs['Object'], sub.inputs[0])
    div = N.new('ShaderNodeVectorMath')
    div.operation = 'DIVIDE'
    div.inputs[1].default_value = size
    L.new(sub.outputs['Vector'], div.inputs[0])
    geo = N.new('ShaderNodeNewGeometry')
    nrm = N.new('ShaderNodeVectorMath')
    nrm.operation = 'MULTIPLY_ADD'
    nrm.inputs[1].default_value = (0.5, 0.5, 0.5)
    nrm.inputs[2].default_value = (0.5, 0.5, 0.5)
    L.new(geo.outputs['Normal'], nrm.inputs[0])
    ao = N.new('ShaderNodeAmbientOcclusion')
    ao.samples = 16
    ao.inputs['Distance'].default_value = ao_dist
    bev = N.new('ShaderNodeBevel')
    bev.samples = 8
    bev.inputs['Radius'].default_value = 0.006
    dot = N.new('ShaderNodeVectorMath')
    dot.operation = 'DOT_PRODUCT'
    L.new(bev.outputs['Normal'], dot.inputs[0])
    L.new(geo.outputs['Normal'], dot.inputs[1])
    edge = N.new('ShaderNodeMath')
    edge.operation = 'SUBTRACT'
    edge.inputs[0].default_value = 1.0
    L.new(dot.outputs['Value'], edge.inputs[1])
    passes = {
        'id': (idm.outputs[0], 1),
        'pos': (div.outputs['Vector'], 1),
        'nrm': (nrm.outputs['Vector'], 1),
        'ao': (ao.outputs['AO'], 24),
        'edge': (edge.outputs[0], 16),
    }
    select_only(obj)
    got = {}
    for name, (sock, samples) in passes.items():
        img = bpy.data.images.new(f'bake-{name}', res, res, alpha=False, float_buffer=True)
        img.colorspace_settings.name = 'Non-Color'
        tex.image = img
        nt.nodes.active = tex
        for l in list(emit.inputs['Color'].links):
            L.remove(l)
        L.new(sock, emit.inputs['Color'])
        sc.cycles.samples = samples
        bpy.ops.object.bake(type='EMIT', margin=BAKE_MARGIN, margin_type='EXTEND', use_clear=True)
        px = np.empty(res * res * 4, dtype=np.float32)
        img.pixels.foreach_get(px)
        got[name] = px.reshape(res * res, 4)[:, :3].astype(np.float64)
        bpy.data.images.remove(img)
    for o in list(bpy.context.scene.objects):
        if o.name.startswith('ground'):
            bpy.data.objects.remove(o, do_unlink=True)
    obj.data.materials.clear()
    bpy.data.materials.remove(mat)
    # decode to the street-furniture frame
    pb = np.array(mn) + got['pos'] * np.array(size)
    P = np.stack([pb[:, 0], pb[:, 2], -pb[:, 1]], axis=1)
    nb = got['nrm'] * 2.0 - 1.0
    Nn = np.stack([nb[:, 0], nb[:, 2], -nb[:, 1]], axis=1)
    Nn /= np.maximum(np.linalg.norm(Nn, axis=1, keepdims=True), 1e-6)
    pid = np.rint(got['id'][:, 0] * 64.0).astype(np.int64)
    return pid, P, Nn, np.clip(got['ao'][:, 0], 0.0, 1.0), np.clip(got['edge'][:, 0], 0.0, 1.0)


