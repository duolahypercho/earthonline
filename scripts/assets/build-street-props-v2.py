    lathe(m, [(0.045, 0.150), (0.045, 0.180), (0.040, 0.195), (0.022, 0.204), (0.0, 0.207)], 10, 'photocell', at=(0, 0, -0.22))
    q = Vector((0, 0, -1)).rotation_difference(Vector(direction).normalized())
