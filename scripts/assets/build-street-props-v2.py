def figure(m):
    """A plain 1.8 m figure for scale."""
    for sx in (-1, 1):
        lathe(m, [(0.06, 0.0), (0.065, 0.08), (0.07, 0.45), (0.075, 0.55), (0.085, 0.88), (0.0, 0.92)], 10, 'galv', at=(sx * 0.09, 0, 0), caps=(True, False))
    lathe(m, [(0.0, 0.86), (0.17, 0.90), (0.16, 1.05), (0.15, 1.20), (0.19, 1.42), (0.12, 1.48), (0.05, 1.52), (0.0, 1.53)], 14, 'galv')
    for sx in (-1, 1):
        sweep(m, [(sx * 0.21, 1.43, 0), (sx * 0.24, 1.15, 0.02), (sx * 0.25, 0.86, 0.04)], [0.045, 0.04, 0.035], 8, 'galv')
    lathe(m, [(0.045, 1.50), (0.045, 1.58)], 8, 'galv')
    lathe(m, [(0.0, 1.57), (0.075, 1.60), (0.10, 1.66), (0.098, 1.72), (0.07, 1.78), (0.0, 1.80)], 12, 'galv')


def render_sheets(render_dir, kinds):
    os.makedirs(render_dir, exist_ok=True)
    reset()
    sc = bpy.context.scene
    engines = [e.identifier for e in bpy.types.RenderSettings.bl_rna.properties['engine'].enum_items]
    sc.render.engine = 'BLENDER_EEVEE_NEXT' if 'BLENDER_EEVEE_NEXT' in engines else ('BLENDER_EEVEE' if 'BLENDER_EEVEE' in engines else 'BLENDER_WORKBENCH')
    try:
        sc.eevee.taa_render_samples = 32
    except Exception:
        pass
    labels = []
    for vt in ('AgX', 'Filmic', 'Standard'):
        try:
            sc.view_settings.view_transform = vt
            break
        except TypeError:
            continue
    world = bpy.data.worlds.new('w')
    sc.world = world
    world.use_nodes = True
    bg = world.node_tree.nodes['Background']
    bg.inputs['Color'].default_value = (0.62, 0.66, 0.72, 1)
    bg.inputs['Strength'].default_value = 0.9
    sun = bpy.data.objects.new('sun', bpy.data.lights.new('sun', 'SUN'))
    sun.data.energy = 3.2
    sun.data.angle = math.radians(3)
    sun.rotation_euler = (math.radians(50), math.radians(10), math.radians(-35))
    sc.collection.objects.link(sun)
    gm = bpy.data.materials.new('ground')
    gm.use_nodes = True
    gb = next(n for n in gm.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    gb.inputs['Base Color'].default_value = (0.36, 0.35, 0.33, 1)
    gb.inputs['Roughness'].default_value = 0.95
    fmat = bpy.data.materials.new('figure')
    fmat.use_nodes = True
    fb = next(n for n in fmat.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    fb.inputs['Base Color'].default_value = (0.55, 0.42, 0.33, 1)
    fb.inputs['Roughness'].default_value = 0.8
    tmat = bpy.data.materials.new('label')
    tmat.use_nodes = True
    tb = next(n for n in tmat.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    tb.inputs['Base Color'].default_value = (0.02, 0.02, 0.02, 1)

    def import_kind(kind):
        before = set(bpy.data.objects)
        bpy.ops.import_scene.gltf(filepath=os.path.join(OUT_DIR, f'{kind}-v2.glb'))
        objs = [o for o in bpy.data.objects if o not in before and o.type == 'MESH']
        if kind == 'payStation':
            for o in objs:
                o.scale = (PAY_STATION_STRETCH[0], PAY_STATION_STRETCH[2], PAY_STATION_STRETCH[1])
        mn, _ = bounds(objs)
        if mn.z < 0.0 or KINDS[kind].get('overhead'):
            for o in objs:
                o.location.z -= mn.z
        for o in objs:
            for mt in o.data.materials:
                if mt and mt.node_tree:
                    for nd in mt.node_tree.nodes:
                        if nd.type == 'BSDF_PRINCIPLED':
                            nd.inputs['Emission Strength'].default_value = 0.0
        return objs

    def make_figure(at):
        fm = Mesh()
        figure(fm)
        o, _ = to_object(fm, 'figure')
        o.data.attributes.remove(o.data.attributes['paint'])
        o.data.materials.append(fmat)
        o.location = at
        return o

    def label(text, at, size):
        cu = bpy.data.curves.new('label', 'FONT')
        cu.body = text
        cu.size = size
        cu.align_x = 'CENTER'
        o = bpy.data.objects.new('label', cu)
        o.data.materials.append(tmat)
        sc.collection.objects.link(o)
        o.location = at
        return o

    def bounds(objs):
        bpy.context.view_layer.update()
        pts = [o.matrix_world @ Vector(c) for o in objs for c in o.bound_box]
        return Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts))), Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))

    def shoot(path, objs_all, res_x, res_y, az, el=20.0, pad=1.08):
        """Orthographic 3/4 view; `az` 0 looks from the street side (Blender +Y)."""
        mn, mx = bounds(objs_all)
        c = (mn + mx) / 2
        cam_data = bpy.data.cameras.new('cam')
        cam_data.type = 'ORTHO'
        cam = bpy.data.objects.new('cam', cam_data)
        sc.collection.objects.link(cam)
        d = Vector((math.sin(math.radians(az)) * math.cos(math.radians(el)), math.cos(math.radians(az)) * math.cos(math.radians(el)), math.sin(math.radians(el))))
        cam.location = c + d * 200.0
        cam.rotation_euler = (-d).to_track_quat('-Z', 'Y').to_euler()
        # fit: project the bound corners on the camera's right and up axes
        rot = cam.rotation_euler.to_matrix()
        right, upv = rot @ Vector((1, 0, 0)), rot @ Vector((0, 1, 0))
        corners = [Vector((x, y, z)) for x in (mn.x, mx.x) for y in (mn.y, mx.y) for z in (mn.z, mx.z)]
        w = max(abs((p - c).dot(right)) for p in corners) * 2
        h = max(abs((p - c).dot(upv)) for p in corners) * 2
        aspect = res_x / res_y
        cam_data.ortho_scale = max(w, h * aspect) * pad
        cam_data.clip_end = 1000
        for lb in labels:
            lb.rotation_euler = cam.rotation_euler
        sc.camera = cam
        sc.render.resolution_x, sc.render.resolution_y = res_x, res_y
        sc.render.filepath = path
        bpy.ops.render.render(write_still=True)
        bpy.data.objects.remove(cam, do_unlink=True)

    def ground(mn, mx):
        me = bpy.data.meshes.new('g')
        me.from_pydata([(mn.x - 3, mn.y - 6, 0), (mx.x + 3, mn.y - 6, 0), (mx.x + 3, mx.y + 6, 0), (mn.x - 3, mx.y + 6, 0)], [], [[0, 1, 2, 3]])
        o = bpy.data.objects.new('g', me)
        o.data.materials.append(gm)
        sc.collection.objects.link(o)
        return o

    def clear():
        labels.clear()
        for o in list(sc.objects):
            if o.name.startswith('sun'):
                continue
            bpy.data.objects.remove(o, do_unlink=True)

    def lay_out(kind_list, gap=0.7, with_labels=True, label_size=0.22):
        placed = []
        x = 0.0
        fig = make_figure((0, 0, 0))
        fmn, fmx = bounds([fig])
        x = fmx.x - fmn.x + gap
        placed.append(fig)
        for kind in kind_list:
            objs = import_kind(kind)
            mn, mx = bounds(objs)
            dx = x - mn.x
            for o in objs:
                o.location.x += dx
            mn, mx = bounds(objs)
            if with_labels:
                text = 'payStation (load stretch)' if kind == 'payStation' else kind
                labels.append(label(text, ((mn.x + mx.x) / 2, 0.0, mx.z + 0.12), label_size))
            placed.extend(objs)
            x = mx.x + gap
        return placed

    # the lineup: every kind beside the figure
    order = [k for k in KINDS if k in kinds]
    placed = lay_out(order, gap=0.8, label_size=0.35)
    mn, mx = bounds(placed)
    ground(mn, mx)
    shoot(os.path.join(render_dir, 'lineup-all-street.png'), placed, 4800, 1500, az=25)
    shoot(os.path.join(render_dir, 'lineup-all-footway.png'), placed, 4800, 1500, az=180 - 25)
    clear()
    # one sheet per priority group, both sides
    for g in (1, 2, 3, 4):
        ks = [k for k in order if KINDS[k]['group'] == g]
        if not ks:
            continue
        placed = lay_out(ks, gap=0.6, label_size=0.16 if g in (2,) else 0.28)
        mn, mx = bounds(placed)
        ground(mn, mx)
        shoot(os.path.join(render_dir, f'group{g}-street.png'), placed, 3200, 1400, az=25)
        shoot(os.path.join(render_dir, f'group{g}-footway.png'), placed, 3200, 1400, az=180 - 25)
        clear()
    # close-ups of each kind (street and footway side), for the detail
    for kind in order:
        objs = import_kind(kind)
        mn, mx = bounds(objs)
        ground(mn, mx)
        shoot(os.path.join(render_dir, f'kind-{kind}-street.png'), objs, 1000, 1000, az=30, el=18)
        shoot(os.path.join(render_dir, f'kind-{kind}-footway.png'), objs, 1000, 1000, az=180 - 30, el=18)
        clear()
    print(f'[street-props-v2] renders in {render_dir}')


