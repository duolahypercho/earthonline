    """An LED cobra head: neck (the slip fitter on a 2-3/8 in tenon) at `neck`, the
    head reaching along `direction`; flat bottom, the lamp glass underneath, the
    photocell on top. Returns the lens centre."""
    k = width / 0.44
    st = [(0.00, 0.060 * k, -0.025, 0.075), (-0.06, 0.150 * k, -0.040, 0.125), (-0.20, 0.205 * k, -0.045, 0.165),
          (-0.40, 0.220 * k, -0.045, 0.180), (-0.60, 0.205 * k, -0.042, 0.160), (-0.74, 0.150 * k, -0.035, 0.115),
          (-0.80, 0.070 * k, -0.020, 0.060)]
    mk = m.mark()
    loft(m, st, 14, 3.0, 'luminaire_grey')
    # slip-fitter collar round the tenon
    lathe(m, [(0.045, -0.06), (0.045, 0.03)], 10, 'luminaire_grey', axis=(0, 0, 1))
    # the refractor: a shallow rounded rectangle under the shell
    ring = []
    for i in range(12):
        a = TAU * i / 12
        c, s = math.cos(a), math.sin(a)
        x = math.copysign(abs(c) ** 0.5, c) * 0.150 * k
        z = -0.42 + math.copysign(abs(s) ** 0.5, s) * 0.25
        ring.append(m.vert((x, -0.046, z)))
    ctr = m.vert((0.0, -0.058, -0.42))
    for i in range(12):
        m.face([ctr, ring[i], ring[(i + 1) % 12]], 'lamp_glass')
        m.orient_cap(len(m.f) - 1, (0, -1, 0))
