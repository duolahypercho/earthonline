def build_kind(kind, spec, v1):
    reset()
    m = Mesh()
    extra = spec['build'](m) or {}
    res = spec.get('atlas', ATLAS_PX)
    obj, paints = to_object(m, kind, uv_from_mesh=spec.get('painted', False))
    if spec.get('bevel'):
        # chamfered edges: a highlight line on every hard edge, which is what reads at 5-30 m
        w, seg = spec['bevel']
        select_only(obj)
        mod = obj.modifiers.new('bevel', 'BEVEL')
        mod.width = w
        mod.segments = seg
        mod.limit_method = 'ANGLE'
        mod.angle_limit = math.radians(50)
        mod.use_clamp_overlap = True
        bpy.ops.object.modifier_apply(modifier='bevel')
        obj.data.set_sharp_from_angle(angle=SHARP_ANGLE)
    if spec.get('painted'):
        col, rough, metal, ao = paint_palm(res)
    else:
        unwrap(obj)
        pid, P, Nn, ao, edge = bake(obj, res, spec.get('overhead', False), spec.get('ao', 0.4))
        col, rough, metal = weather(kind, paints, pid, P, Nn, ao, edge, spec.get('overhead', False))
    albedo = make_image(f'{kind}-albedo', to_srgb8(col), res, 'sRGB')
    mr8 = np.stack([np.clip(np.round(ao * 255), 0, 255), np.clip(np.round(rough * 255), 0, 255), np.clip(np.round(metal * 255), 0, 255)], axis=1).astype(np.uint8)
    mr = make_image(f'{kind}-mr', mr8, res, 'Non-Color')
    vals = np.empty(len(obj.data.polygons), dtype=np.float32)
    obj.data.attributes['paint'].data.foreach_get('value', vals)
    face_paints = [paints[int(round(v))] for v in vals]
    slots = final_materials(obj, kind, paints, face_paints, albedo, mr)
    out = os.path.join(OUT_DIR, f'{kind}-v2.glb')
    export(obj, out)
    info = read_glb(out)
    data = open(out, 'rb').read()
    slot = v1['dimensionsM']
    target = list(slot)
    if spec.get('target_height'):
        target[1] = spec['target_height']
    budget = 2 * v1['triangles']
    off = [abs(info['dims'][i] - target[i]) / target[i] for i in range(3)]
    row = {
        'path': f'public/assets/street-props/{kind}-v2.glb',
        'url': f'/assets/street-props/{kind}-v2.glb',
        'sha256': hashlib.sha256(data).hexdigest(),
        'bytes': len(data),
        'triangles': info['triangles'],
        'dimensionsM': [round(d, 4) for d in info['dims']],
        'boundsM': {'min': [round(x, 4) for x in info['min']], 'max': [round(x, 4) for x in info['max']]},
        'scale': 1.0,
        'materials': info['materials'],
        'atlasPx': res,
        'v1Slot': {'dimensionsM': slot, 'triangles': v1['triangles'], 'triangleBudget': budget},
        'fitToSlot': {'targetDimensionsM': target, 'offFraction': [round(o, 4) for o in off],
                      'within5pc': [o <= 0.05 for o in off]},
        'source': {
            'generator': 'procedural Blender model and Cycles-baked weathering atlas (this script); no imported, generated or traced geometry'
                         if not spec.get('painted') else 'procedural Blender model with a painted atlas (this script); no imported, generated or traced geometry',
            'script': 'scripts/assets/build-street-props-v2.py',
            'scriptSha256': hashlib.sha256(open(SCRIPT, 'rb').read()).hexdigest(),
            'blender': bpy.app.version_string,
            'license': 'authored for this repository',
        },
        'group': spec['group'],
    }
    if spec.get('consumer'):
        row['consumer'] = spec['consumer']
    if kind in DEVIATIONS:
        row['deviation'] = DEVIATIONS[kind]
    row.update(extra)
    assert info['materials'][0] == 'body', f'{kind}: first material {info["materials"][0]}'
    assert all(im['baseline'] and im['mime'] == 'image/jpeg' for im in info['images']), f'{kind}: images {info["images"]}'
    print(f'[street-props-v2] {kind}: {info["triangles"]} tri (v1 {v1["triangles"]}, budget {budget}), {len(data)} B, '
          f'dims {row["dimensionsM"]} vs {target} off {row["fitToSlot"]["offFraction"]}, materials {info["materials"]}')
    if info['triangles'] > budget:
        print(f'[street-props-v2] {kind}: OVER BUDGET')
    return row


