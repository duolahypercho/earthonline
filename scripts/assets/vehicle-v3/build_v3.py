"""Deterministic v3 fleet recipe. Run with Blender --background --python.

  blender -b -P scripts/assets/vehicle-v3/build_v3.py -- --output DIR [--bodies compactHatch,...]

For every body: builds LOD0-2 from bodies/<id>.json, carries the fleet-v2 cabin
(seats, dash, steering, door cards: the occupant contract) across from the same
LOD of the shipped v2 GLB, and exports <id>-lod<N>.glb plus build-report.json.
Promotion into public/assets is the caller's choice of --output; the manifest is
then regenerated by artifacts/vehicles/write-manifest.py.
"""
