# v2 part names that miss the runtime contract (vehicle-occupant.js reads
# Seat_FL_Base; hero-sedan-glb.js steers SteeringWheel_Rim/SteeringWheel)
CABIN_RENAME = {'SeatDriverBase': 'Seat_FL_Base', 'SeatDriverBack': 'Seat_FL_Back',
                'SeatDriverHeadrest': 'Seat_FL_Headrest0', 'SteeringBusWheel': 'SteeringWheel_Rim'}


def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def carry_cabin(body_id, lod):
    """Import the v2 GLB of the same LOD and keep only its cabin."""
    src = V2 / f'{body_id}-lod{lod}.glb'
    if not src.exists():
        return []
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=str(src))
    new = [o for o in bpy.data.objects if o not in before]
    keep = [o for o in new if o.type == 'MESH' and o.name.startswith(CABIN_V2)
            and not o.name.startswith(('Headliner', 'RearShelf', 'InteriorHeadliner'))]
    # the seat/steering group empties (Seat_FL, Seat_FR, Seat_Rear, SteeringWheel)
    # are the occupant/entry anchors the runtime resolves: carry them too, and
    # remember which one each kept mesh hung from so it can be re-hung later
    is_anchor = lambda a: a.type == 'EMPTY' and a.name.startswith(CABIN_V2)
    anchors = []
    for o in keep:
        a = o.parent
        while a is not None:
            if is_anchor(a) and a not in anchors:
                anchors.append(a)
            a = a.parent
    for o in keep + anchors:
        a = o.parent
        while a is not None and not is_anchor(a):
            a = a.parent
        if a is not None:
            o['_anchor'] = a.name.split('.')[0]
    keep += anchors
    bpy.context.view_layer.update()
    for o in keep:
        w = o.matrix_world.copy()
        o.parent = None
        o.matrix_world = w
    for o in new:
        if o not in keep:
            bpy.data.objects.remove(o, do_unlink=True)
    for o in keep:
        o.name = CABIN_RENAME.get(o.name.split('.')[0], o.name.split('.')[0])
    # A v2 GLB exported in the runtime frame is mirrored back before this
    # builder's shell clamps and door reparenting (all authoring-frame) see it.
    F.carried_to_authoring_frame(keep)
    return keep


def dress_cabin(cfg, cabin, lod):
    """Real proportions for the carried seats (the v2 kit's seat backs stop at the
    belt, so a side view looked straight through the cabin) and the inner B/C-pillar
    trims a viewer sees through the far window. Seat anchors (object origins) do not move."""
    import v3_body as V
    spec = V.BodySpec(cfg)
    c = spec.c
    bpy.context.view_layer.update()
    for o in cabin:
        n = o.name
        if o.type == 'MESH' and n.startswith('Seat') and ('Back' in n or 'Headrest' in n) and 'Post' not in n:
            me = o.data
            zs = [v.co.z for v in me.vertices]
            if not zs:
                continue
            z0 = min(zs)
            k = 1.28 if 'Back' in n else 1.35
            for v in me.vertices:
                v.co.z = z0 + (v.co.z - z0) * k
                if 'Headrest' in n:
                    v.co.x *= 1.25
    if lod > 1:
        return
    trim = bpy.data.materials.get('VehicleInterior')
    g = cfg['glass']
    y_lo, y_hi = g['front'], min(cfg['roofRear'] + 0.6, cfg['L'] / 2 - 0.3)
    for y, w in (((g['bFront'] + g['bRear']) / 2, 0.11), ((g['rear'] + g['qFront']) / 2, 0.08), (g['qRear'] + 0.05, 0.16)):
        if not y_lo < y < y_hi:
            continue  # a sentinel station (no such pillar on this body)
        z0, z1 = c['belt'](y) - 0.05, c['top'](y) - c['rail'](y) - 0.02
        if not z0 + 0.1 < z1 < z0 + 1.4:
            continue
        for sx in (-1, 1):
            pillar_trim(f'InteriorPillarTrim{"L" if sx < 0 else "R"}{int(y * 100)}', sx, y, w, z0, z1, trim)


def normalise_cabin(cfg):
    """Contract nodes a carried v2 cabin may lack: a `SteeringWheel` group over
    the wheel parts, and (a city bus) a front-row passenger seat opposite the
    driver, copied from the driver's seat parts and mirrored across the car."""
    bpy.context.view_layer.update()
    if bpy.data.objects.get('SteeringWheel') is None:
        parts = [o for o in bpy.data.objects if o.name.startswith('SteeringWheel_') and o.parent is None]
        if parts:
            c_ = sum((o.matrix_world.translation for o in parts), Vector()) / len(parts)
            grp = P.empty('SteeringWheel', tuple(c_))
            for o in parts:
                P.parent_keep(o, grp)
    ms = cfg.get('mirrorDriverSeat')
    if ms and bpy.data.objects.get('Seat_FR_Base') is None:
        for o in [o for o in bpy.data.objects if o.name.startswith('Seat_FL_') and o.type == 'MESH']:
            dup = o.copy()
            dup.data = o.data.copy()
            bpy.context.scene.collection.objects.link(dup)
            dup.parent = None
            w = o.matrix_world.copy()
            dup.matrix_world = w
            dup.name = 'Seat_FR_' + o.name[len('Seat_FL_'):]
            me = dup.data
            for v in me.vertices:
                v.co.x = -v.co.x
            me.flip_normals()
            dup.location.x = -w.translation.x
            dup.location.y = w.translation.y + ms.get('dy', 0.0)


def finish_utility_cabin(cfg, lod):
    if not cfg.get('utilityInterior'):
        return
    fabric = P.mat('VehicleSeatFabric', (0.17, 0.18, 0.18), rough=0.86)
    seat_names = ('Seat_FL_Base', 'Seat_FR_Base', 'SeatFBL', 'SeatFBR',
                  'Seat_Rear_Base', 'Seat_Rear_Back')
    for name in seat_names:
        seat = bpy.data.objects.get(name)
        if seat is None or seat.type != 'MESH':
            continue
        seat.data = seat.data.copy()
        seat.data.materials.clear()
        seat.data.materials.append(fabric)
    if lod > 0:
        return
    inset = P.mat('VehicleSeatInset', (0.115, 0.125, 0.125), rough=0.93)
    for side, x in (('FL', -0.38), ('FR', 0.38)):
        for part, size, center in (
            ('Back', (0.38, 0.018, 0.32), (x, 0.316, 1.06)),
            ('Base', (0.39, 0.36, 0.018), (x, 0.14, 0.768)),
        ):
            pad = P.box(f'Seat_{side}_{part}_Inset', size, center, inset,
                        bevel=0.014, segs=2)
            anchor = bpy.data.objects.get(f'Seat_{side}')
            if anchor is not None:
                P.parent_keep(pad, anchor)
    rear = P.box('Seat_Rear_Back_Inset', (1.10, 0.018, 0.40),
                 (0, 1.158, 1.09), inset, bevel=0.014, segs=2)
    anchor = bpy.data.objects.get('Seat_Rear')
    if anchor is not None:
        P.parent_keep(rear, anchor)


def reanchor_cabin(cabin):
    """Hang each carried mesh back under its seat/steering anchor empty (the
    shell clamps above run on free meshes); door-card trims stay on their door."""
    for o in cabin:
        try:
            if '_anchor' not in o:
                continue
        except ReferenceError:
            continue  # dropped by fit_cabin
        a = bpy.data.objects.get(o['_anchor'])
        if a is not None and o.parent is None:
            P.parent_keep(o, a)
        del o['_anchor']


def trim_floor(cfg, cabin):
    """A floor plate's corners can sit inside the shell while its faces still
    cross the wheel-arch tunnels; the floor belongs between the arches."""
    y0 = cfg['frontAxle'] + cfg['R'] + 0.12
    y1 = cfg['rearAxle'] - cfg['R'] - 0.12
    bpy.context.view_layer.update()
    crown = 2 * cfg['R'] + 0.15  # door trims only need clearing below the arch crown
    span = cfg['R'] + 0.12
    tw = cfg.get('tyreWidth', 0.225)
    for o in cabin:
        # arch clearance for everything carried: inboard of the tyre's inner face
        if o.type == 'MESH':
            mw = o.matrix_world
            inv = mw.inverted()
            for v in o.data.vertices:
                w = mw @ v.co
                for axle, track in ((cfg['frontAxle'], cfg['track']), (cfg['rearAxle'], cfg.get('trackRear', cfg['track']))):
                    xin = track / 2 - tw / 2 - 0.07
                    if abs(w.y - axle) < span and w.z < crown and abs(w.x) > xin:
                        w.x = math.copysign(xin, w.x)
                        v.co = inv @ w
            o.data.update()
        floor = o.name.startswith(('FloorPan', 'Tunnel', 'Carpet'))
        door = o.name.startswith(('DoorCard_', 'DoorInsert_', 'DoorPull_', 'DoorArmrest_'))
        if o.type != 'MESH' or not (floor or door):
            continue
        mw = o.matrix_world
        inv = mw.inverted()
        for v in o.data.vertices:
            w = mw @ v.co
            if floor:
                w.y = min(max(w.y, y0), y1)
            elif w.z < crown:
                # a door trim swings outboard into the tyre's tread band as the
                # door opens, so it needs more room than the skin at rest
                w.y = min(max(w.y, y0 + 0.05), y1 - 0.05)
            v.co = inv @ w
        o.data.update()


def fit_cabin(cabin, inset=0.035):
    """The v2 cabin kit was laid out for the v2 body. Pull every carried vertex
    back inside the v3 shell (sides, ends, roof and backlight) so no seat, door
    card or floor pan stands proud of the skin or the glass."""
    from mathutils import Vector
    bvh = B.SHELL_BVH
    bpy.context.view_layer.update()
    moved = 0
    # the shell's own mid-length (a box truck's cab shell does not reach y = 0)
    yc = 0.0
    for zt in (0.7, 1.0, 1.4, 1.8):
        ends = [bvh.ray_cast(Vector((0, sg * 20.0, zt)), Vector((0, -sg, 0)), 40.0)[0] for sg in (-1, 1)]
        if all(ends):
            yc = (ends[0].y + ends[1].y) / 2
            break
    floor = bvh.ray_cast(Vector((0, yc, -2.0)), Vector((0, 0, 1)), 10.0)[0]
    zsafe = (floor.z if floor is not None else 0.3) + 0.12
    dropped = []
    for o in cabin:
        if o.type != 'MESH':
            continue
        mw = o.matrix_world
        inv = mw.inverted()
        worst = 0.0
        rest = [v.co.copy() for v in o.data.vertices]
        for v in o.data.vertices:
            w = mw @ v.co
            if inside(bvh, w):
                continue
            p = w.copy()
            zr = max(w.z, zsafe)
            for axis in (1, 0):  # ends first, so the side ray starts inside the body
                sgn = 1 if p[axis] >= (0 if axis == 0 else yc) else -1
                d = Vector((0, 0, 0)); d[axis] = sgn
                hit = None
                origins = ([(0, p.y, w.z), (0, p.y, zr)] if axis == 0
                           else [(p.x, yc, w.z), (p.x, yc, zr), (0, yc, zr)])
                for origin in origins:
                    hit = bvh.ray_cast(Vector(origin), d, 12.0)[0]
                    if hit is not None:
                        break
                c0 = 0 if axis == 0 else yc
                if hit is not None and sgn * (p[axis] - c0) > sgn * (hit[axis] - c0) - inset:
                    p[axis] = hit[axis] - sgn * inset
            hit = bvh.ray_cast(Vector((p.x, p.y, -2.0)), Vector((0, 0, 1)), 12.0)[0]
            if hit is not None and p.z < hit.z + 0.01:
                p.z = hit.z + 0.01
            hit = bvh.ray_cast(Vector((p.x, p.y, 6.0)), Vector((0, 0, -1)), 12.0)[0]
            if hit is not None and p.z > hit.z - inset:
                p.z = hit.z - inset
            if (p - w).length > 1e-5:
                worst = max(worst, (p - w).length)
                v.co = inv @ p
                moved += 1
        o.data.update()
        # a part laid out for a longer v2 body (a third row in a shorter van)
        # cannot be squashed into shape; drop it unless it is occupant contract
        if worst > 0.25 and not o.name.startswith(CONTRACT):
            # a seat over a wheel box: lift it whole (a podium) before giving up
            for v, co in zip(o.data.vertices, rest):
                v.co = co
            o.data.update()
            ws = [mw @ co for co in rest]
            lift = next((dz for dz in (0.05 * k for k in range(1, 13))
                         if all(inside(bvh, w + Vector((0, 0, dz))) for w in ws)), None)
            if lift is not None:
                o.location.z += lift
                print('FIT_CABIN lift', o.name, round(lift, 2), flush=True)
            else:
                print('FIT_CABIN drop', o.name, round(worst, 2), flush=True)
                dropped.append(o.name)
                bpy.data.objects.remove(o, do_unlink=True)
    # a seat row stays whole: once any part of it is dropped, drop the row
    import re
    rows = {m.group(1) for n in dropped for m in [re.match(r'(SeatRow\d+)', n)] if m}
    for o in list(cabin):
        try:
            name = o.name
        except ReferenceError:
            continue  # removed above
        if name in bpy.data.objects and o.type == 'MESH' and any(name.startswith(r) for r in rows):
            print('FIT_CABIN drop row', o.name, flush=True)
            bpy.data.objects.remove(o, do_unlink=True)
    print('FIT_CABIN moved', moved, flush=True)



def inside(bvh, point):
    """Parity of shell crossings straight up (the pristine shell is closed)."""
    from mathutils import Vector
    up = Vector((0, 0, 1))
    origin = point.copy()
    n = 0
    for _ in range(12):
        hit = bvh.ray_cast(origin, up, 20.0)[0]
        if hit is None:
            break
        n += 1
        origin = hit + up * 1e-4
    return n % 2 == 1


CONTRACT = ('Seat_FL', 'Seat_FR', 'Seat_Rear', 'Seat_R', 'DoorCard_', 'Dash', 'Steering', 'FloorPan', 'Tunnel')


def pillar_trim(name, sx, y, w, z0, z1, material, inset=0.038, thick=0.02, rows=7):
    """A trim strip that follows the inside of the shell (tumblehome and all), so
    it can never stand proud of the glass or the roof."""
    import bmesh
    from mathutils import Vector
    bvh = B.SHELL_BVH
    grid = []
    for k in range(rows):
        z = z0 + (z1 - z0) * k / (rows - 1)
        row = []
        for yy in (y - w / 2, y + w / 2):
            hit = bvh.ray_cast(Vector((0, yy, z)), Vector((sx, 0, 0)), 3.0)[0]
            if hit is None:
                return None
            row.append((abs(hit.x) - inset, yy, z))
        grid.append(row)
    # the top row must also sit under the roof
    for row in grid[-1:]:
        for i, (x, yy, z) in enumerate(row):
            up = bvh.ray_cast(Vector((sx * x, yy, z - 0.2)), Vector((0, 0, 1)), 2.0)[0]
            if up is not None and up.z - inset < z:
                row[i] = (x, yy, up.z - inset)
    bm = bmesh.new()
    outer = [[bm.verts.new((sx * x, yy, z)) for x, yy, z in row] for row in grid]
    inner = [[bm.verts.new((sx * (x - thick), yy, z)) for x, yy, z in row] for row in grid]
    for k in range(rows - 1):
        for layer in (outer, inner):
            bm.faces.new((layer[k][0], layer[k][1], layer[k + 1][1], layer[k + 1][0]))
        for i in (0, 1):
            bm.faces.new((outer[k][i], outer[k + 1][i], inner[k + 1][i], inner[k][i]))
    bm.faces.new((outer[-1][0], outer[-1][1], inner[-1][1], inner[-1][0]))
    bm.faces.new((outer[0][0], inner[0][0], inner[0][1], outer[0][1]))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)  # closed box strip: safe
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    me.materials.append(material)
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    return ob


def tri_count():
    dg = bpy.context.evaluated_depsgraph_get()
    total = 0
    for ob in bpy.context.scene.objects:
        if ob.type == 'MESH':
            me = ob.evaluated_get(dg).data
            total += sum(len(p.vertices) - 2 for p in me.polygons)
    return total


def export(path):
    """Export the whole scene in the runtime frame (scripts/assets/vehicle_frame.py):
    this builder's "X right, -Y nose" frame is mirrored, so it is converted here."""
    bpy.ops.object.select_all(action='SELECT')
    F.export_runtime_frame(list(bpy.context.scene.objects), lambda: bpy.ops.export_scene.gltf(
        filepath=str(path), use_selection=True, export_apply=True, export_yup=True,
        export_materials='EXPORT', export_format='GLB', export_animations=False,
        export_skins=False, export_texcoords=False, export_normals=True, export_extras=True))


def load_body(body_id):
    """A body JSON may `extends` another: a trim shares its parent's measured body."""
    cfg = json.loads((HERE / 'bodies' / f'{body_id}.json').read_text())
    if 'extends' in cfg:
        base = load_body(cfg['extends'])
        for k, v in cfg.items():
            if k == 'curvesOverride':
                base['curves'].update(v)
            elif isinstance(v, dict) and isinstance(base.get(k), dict) and k not in ('lamps',):
                base[k] = {**base[k], **v}
            else:
                base[k] = v
        base.pop('extends', None)
        cfg = base
    return cfg


def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    ap = argparse.ArgumentParser()
    ap.add_argument('--output', required=True)
    ap.add_argument('--bodies', default='compactHatch')
    ap.add_argument('--blend', default=None,
                    help='save the first requested body at LOD0 as a reusable study source')
    args = ap.parse_args(argv)
    out = Path(args.output).expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)
    rpath = out / 'build-report.json'
    report = json.loads(rpath.read_text()) if rpath.exists() else {'schemaVersion': 1, 'generator': 'vehicle-v3', 'bodies': {}}
    for body_id in args.bodies.split(','):
        cfg = load_body(body_id)
        record = {'vehicleId': cfg.get('vehicleId', body_id), 'body': body_id, 'label': cfg['label'],
                  'lengthM': cfg['L'], 'wheelRadiusM': cfg['R'],
                  'typeIds': cfg.get('typeIds', [body_id]), 'lods': [],
                  'source': f'scripts/assets/vehicle-v3/bodies/{body_id}.json'}
        if cfg.get('openableLampPods'):
            record['lids'] = [
                'Hood', 'Trunk',
                'HeadlampPodL', 'HeadlampPodR',
                'TaillampPodL', 'TaillampPodR',
            ]
        for lod in range(3):
            reset()
            cabin = carry_cabin(cfg.get('cabinSource', body_id), lod)
            off = cfg.get('cabinOffset')
            if off:
                for o in cabin:
                    o.location.x += off[0]
                    o.location.y += off[1]
                    o.location.z += off[2]
            B.build(cfg, lod)
            for o in cabin:
                if o.name.startswith(('DoorCard_', 'DoorArmrest_', 'DoorInsert_', 'DoorPull_')):
                    pivot = bpy.data.objects.get('Door_' + o.name.split('_')[1])
                    if pivot:
                        P.parent_keep(o, pivot)
            dress_cabin(cfg, cabin, lod)
            trim_floor(cfg, cabin)
            fit_cabin(cabin)
            reanchor_cabin(cabin)
            normalise_cabin(cfg)
            finish_utility_cabin(cfg, lod)
            if args.blend and lod == 0:
                blend_path = Path(args.blend).expanduser().resolve()
                blend_path.parent.mkdir(parents=True, exist_ok=True)
                bpy.ops.wm.save_as_mainfile(filepath=str(blend_path))
                print('V3_STUDY', body_id, blend_path, flush=True)
            tris = tri_count()
            f = out / f'{body_id}-lod{lod}.glb'
            export(f)
            record['lods'].append({'file': f.name, 'sha256': hashlib.sha256(f.read_bytes()).hexdigest(),
                                   'bytes': f.stat().st_size, 'triangles': tris})
            print('V3_EXPORT', body_id, lod, tris, f.stat().st_size, flush=True)
        report['bodies'][body_id] = record
        rpath.write_text(json.dumps(report, indent=2) + '\n')


main()
